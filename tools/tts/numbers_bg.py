"""Числата — с думи, за да се четат по човешки (11.10.2026).

Гласът чете „(343–356 г.)" като цифри, а трябва „от триста четиридесет и
трета до триста петдесет и шеста година". Годините и вековете са РЕДНИ
числителни, количествата — бройни.

Пуска се ПРЕДИ съкращенията („г." → „година"): тук „г." още е признакът,
че числото е година.

Нарочно НЕ се пипат:
  • препратките към Писанието („Мат. 14:15–21") — с двоеточие, иска се
    отделно правило;
  • диапазон без „г." извън скоби — може да са страници, стихове, номера.
"""

import re

_UNITS_M = ['', 'един', 'два', 'три', 'четири', 'пет', 'шест', 'седем', 'осем', 'девет']
_UNITS_F = ['', 'една', 'две'] + _UNITS_M[3:]
_UNITS_N = ['', 'едно', 'две'] + _UNITS_M[3:]
_TEENS = ['десет', 'единадесет', 'дванадесет', 'тринадесет', 'четиринадесет',
          'петнадесет', 'шестнадесет', 'седемнадесет', 'осемнадесет', 'деветнадесет']
_TENS = ['', '', 'двадесет', 'тридесет', 'четиридесет', 'петдесет',
         'шестдесет', 'седемдесет', 'осемдесет', 'деветдесет']
_HUNDREDS = ['', 'сто', 'двеста', 'триста', 'четиристотин', 'петстотин',
             'шестстотин', 'седемстотин', 'осемстотин', 'деветстотин']

# Редните — основата; окончанието идва по рода (м. -и, ж. -а, ср. -о).
_ORD_UNITS = ['', 'първ', 'втор', 'трет', 'четвърт', 'пет', 'шест', 'седм', 'осм', 'девет']
_ORD_HUNDREDS = ['', 'стотн', 'двестотн', 'тристотн', 'четиристотн', 'петстотн',
                 'шестстотн', 'седемстотн', 'осемстотн', 'деветстотн']


def _parts(n, gender='m'):
    """Съставките на числото поред: хиляди, стотици, десетици, единици.
    Числата от 10 до 19 са ЕДНА съставка."""
    assert 0 < n < 10000
    out = []
    th, rest = divmod(n, 1000)
    if th == 1:
        out.append(('th', 1, 'хиляда'))
    elif th > 1:
        out.append(('th', th, _UNITS_F[th] + ' хиляди'))
    h, rest = divmod(rest, 100)
    if h:
        out.append(('h', h, _HUNDREDS[h]))
    if 10 <= rest <= 19:
        out.append(('teen', rest, _TEENS[rest - 10]))
    else:
        t, u = divmod(rest, 10)
        if t:
            out.append(('t', t, _TENS[t]))
        if u:
            units = {'m': _UNITS_M, 'f': _UNITS_F, 'n': _UNITS_N}[gender]
            out.append(('u', u, units[u]))
    return out


def _join(words):
    # „и" стои пред ПОСЛЕДНАТА съставка: триста четиридесет и три,
    # триста и пет, хиляда двеста и четири, хиляда и осемстотин.
    if len(words) == 1:
        return words[0]
    return ' '.join(words[:-1]) + ' и ' + words[-1]


def cardinal(n, gender='m'):
    """Бройно: 343 → „триста четиридесет и три"."""
    if n == 0:
        return 'нула'
    return _join([w for _, _, w in _parts(n, gender)])


def _ord_word(kind, v, gender):
    end = {'m': 'и', 'f': 'а', 'n': 'о'}[gender]
    if kind == 'u':
        stem = _ORD_UNITS[v]
    elif kind == 'teen':
        stem = _TEENS[v - 10]
    elif kind == 't':
        stem = _TENS[v]
    elif kind == 'h':
        stem = _ORD_HUNDREDS[v]
    else:  # хиляди
        stem = 'хилядн' if v == 1 else _UNITS_F[v] + 'хилядн'
    if gender == 'm' and stem.endswith(('тн', 'дн')):
        # стотен, хиляден — мъжкият род вмъква „е"
        return stem[:-1] + 'ен'
    return stem + end


def ordinal(n, gender='f'):
    """Редно: 343 → „триста четиридесет и трета" (ж. р. — „година")."""
    parts = _parts(n, gender)
    words = [w for _, _, w in parts[:-1]]
    k, v, _ = parts[-1]
    words.append(_ord_word(k, v, gender))
    return _join(words)


_ROMAN = {'I': 1, 'V': 5, 'X': 10, 'L': 50, 'C': 100}


def roman(s):
    total = 0
    for a, b in zip(s, s[1:] + ' '):
        v = _ROMAN[a]
        total += -v if b != ' ' and _ROMAN.get(b, 0) > v else v
    return total


_DASH = r'\s*[-–—]\s*'
_YEAR_SUFFIX = r'(?:\s*(?:г\.|гг\.|година|години))'
# „след/пр. Р. Хр." — пред и след „г.".
_ERA = [(r'\s*(?:пр\.|преди)\s*Р\.\s*Хр\.', ' преди Христа'),
        (r'\s*(?:сл\.|след)\s*Р\.\s*Хр\.', ' след Христа'),
        (r'\s*(?:пр\.|преди)\s*Хр\.', ' преди Христа'),
        (r'\s*(?:сл\.|след)\s*Хр\.', ' след Христа')]
# „г." е и край на изречението: „през 304 г. Мощите ѝ…" — точката остава.
_G = r'\s*г\.(?=(\s+[А-ЯA-Z„"(]|\s*$))?'


def _g(m, gi):
    return ' година' + ('.' if m.group(gi) is not None else '')


def _second(a, b):
    """„1833–34" → 1834: вторият край, даден съкратено."""
    if b < a and len(str(b)) < len(str(a)):
        p = 10 ** len(str(b))
        b = a // p * p + b
    return b


def _range(pre, a, b):
    b = _second(a, b)
    if b <= a:
        return None
    p = pre.strip()
    if p == 'между':
        return f'между {ordinal(a)} и {ordinal(b)} година'
    if p in ('през', 'в'):
        # „през 1833–34 г." — „от … до" след „през" звучи криво.
        return f'{p} {ordinal(a)} – {ordinal(b)} година'
    return (pre if p not in ('', 'от') else '') + f'от {ordinal(a)} до {ordinal(b)} година'


def years_text(txt):
    # Диапазон с „г.": „(343–356 г.)", „от 813–820 г.", „между 471–474 г.".
    def rng(m):
        r = _range(m.group(1) or '', int(m.group(2)), int(m.group(3)))
        return r if r else m.group(0)

    txt = re.sub(r'(\b(?:от|между|през|в)\s+)?\b([1-9]\d{0,3})' + _DASH + r'([1-9]\d{0,3})' + _YEAR_SUFFIX,
                 rng, txt)
    # „от 81 до 96 г.", „от 527 г. до 565 г."
    def od(m):
        a, b = int(m.group(2)), int(m.group(3))
        return f'{m.group(1)} {ordinal(a)} до {ordinal(b)}' + _g(m, 4)
    txt = re.sub(r'\b([Оо]т)\s+([1-9]\d{0,3})(?:\s*г\.)?\s+до\s+([1-9]\d{0,3})' + _G, od, txt)
    # „през 267 и 269 г."
    def i_(m):
        return f'{ordinal(int(m.group(1)))} и {ordinal(int(m.group(2)))}' + _g(m, 3)
    txt = re.sub(r'\b([1-9]\d{0,3})\s+и\s+([1-9]\d{0,3})' + _G, i_, txt)
    # В скоби, без „г.": (98–117), (1389–1425) — владетел, понтификат.
    def paren(m):
        r = _range('', int(m.group(1)), int(m.group(2)))
        return '(' + r + ')' if r else m.group(0)

    # „(ок. 130–ок. 202)" — години на живот, и двата края приблизителни.
    txt = re.sub(r'\(\s*ок\.\s*([1-9]\d{1,3})' + _DASH + r'ок\.\s*([1-9]\d{1,3})\s*\)',
                 lambda m: f'(около {ordinal(int(m.group(1)))} – около {ordinal(int(m.group(2)))} година)',
                 txt)
    txt = re.sub(r'\(\s*([1-9]\d{1,3})' + _DASH + r'([1-9]\d{1,3})\s*\)', paren, txt)
    # Единична година: „през 1866 г." → „хиляда осемстотин шестдесет и шеста година".
    txt = re.sub(r'\b([1-9]\d{0,3})' + _G, lambda m: ordinal(int(m.group(1))) + _g(m, 2), txt)
    # Векове: „XV в.", „XV–XVI в."
    txt = re.sub(r'\b([IVXLC]+)' + _DASH + r'([IVXLC]+)\s*в(?:в)?\.',
                 lambda m: f'{ordinal(roman(m.group(1)), "m")} – '
                           f'{ordinal(roman(m.group(2)), "m")} век', txt)
    txt = re.sub(r'\b([IVXLC]+)\s*в(?:в)?\.',
                 lambda m: ordinal(roman(m.group(1)), 'm') + ' век', txt)
    for pat, rep in _ERA:
        txt = re.sub(pat, rep, txt)
    return misc_text(suffixed_text(txt))


# Редно с окончание след тире: „1-ва", „13-та", „8-мия", „12-ата", „1-вото".
# Родът и членът се четат от последните букви на окончанието.
_SUFFIX = [('ият', 'm', 'ят'), ('ия', 'm', 'я'), ('ата', 'f', 'та'), ('ото', 'n', 'то'),
           ('ите', 'm', 'те'), ('и', 'm', ''), ('а', 'f', ''), ('о', 'n', '')]


def _suffixed(m):
    n, suf = int(m.group(1)), m.group(2)
    for end, gender, art in _SUFFIX:
        if suf.endswith(end):
            return ordinal(n, gender) + art
    return m.group(0)


def suffixed_text(txt):
    # „52-годишния" → „петдесет и двегодишния"
    def god(m):
        words = cardinal(int(m.group(1)), 'n').rsplit(' ', 1)
        return ' '.join(words[:-1] + [words[-1] + m.group(2)])
    txt = re.sub(r'\b([1-9]\d{0,3})\s*[-–]\s*(годишн[а-я]*)', god, txt)
    return re.sub(r'\b([1-9]\d{0,3})\s*[-–]\s*([а-я]{1,4})\b', _suffixed, txt)


MONTHS = ('януари', 'февруари', 'март', 'април', 'май', 'юни', 'юли', 'август',
          'септември', 'октомври', 'ноември', 'декември')


def misc_text(txt):
    """Останалите числа, които гласът би прочел криво (11.10.2026)."""
    # Празни скоби — от махнатия номер на бележка („888()", „виж тук []").
    txt = re.sub(r'\s*\(\s*виж тук\s*\[\s*\]\s*\)', '', txt)
    txt = re.sub(r'\s*(?:\(\s*\)|\[\s*\])', '', txt)
    txt = re.sub(r'\s*\(\s*0\s*K\s*\)', '', txt)            # „абсолютната нула (0 K)"
    # „(+637)" — годината на кончината.
    txt = re.sub(r'\(\s*[+†]\s*([1-9]\d{2,3})\s*\)',
                 lambda m: f'(почил през {ordinal(int(m.group(1)))} година)', txt)
    # „(ок. 306–373)"
    txt = re.sub(r'\(\s*ок\.\s*([1-9]\d{1,3})' + _DASH + r'([1-9]\d{1,3})\s*\)',
                 lambda m: f'(около {ordinal(int(m.group(1)))} – {ordinal(int(m.group(2)))} година)', txt)
    # „28 декември 1895" — денят е редно в мъжки род; годината след месеца — също.
    mon = '|'.join(MONTHS)
    txt = re.sub(r'\b([1-9]|[12]\d|3[01])\s+(' + mon + r')\b(?:\s+([1-9]\d{3})\b(?!\s*(?:г\.|година)))?',
                 lambda m: f'{ordinal(int(m.group(1)), "m")} {m.group(2)}'
                           + (f' {ordinal(int(m.group(3)))} година' if m.group(3) else ''), txt)
    # „през 1605 година" — само три- и четирицифрени (иначе „1 година" е срок).
    txt = re.sub(r'\b([1-9]\d{2,3})(\s+година)\b', lambda m: ordinal(int(m.group(1))) + m.group(2), txt)
    # „17 век", „2 – 3 век"
    txt = re.sub(r'\b([1-9]\d?)' + _DASH + r'([1-9]\d?)\s+(век|века)\b',
                 lambda m: f'{ordinal(int(m.group(1)), "m")} – {ordinal(int(m.group(2)), "m")} {m.group(3)}', txt)
    txt = re.sub(r'\b([1-9]\d?)\s+(век|века)\b',
                 lambda m: f'{ordinal(int(m.group(1)), "m")} {m.group(2)}', txt)
    # „-273,14 ᵒC"
    txt = re.sub(r'[-–−]\s*([1-9]\d*),(\d\d)\s*[ᵒ°]\s*C',
                 lambda m: f'минус {cardinal(int(m.group(1)))} цяло и {cardinal(int(m.group(2)), "f")} стотни градуса', txt)
    # „3.5 години"
    txt = re.sub(r'\b([1-9]\d*)[.,]5\b', lambda m: cardinal(int(m.group(1)), 'f') + ' и половина', txt)
    # „5%"
    txt = re.sub(r'\b(\d+)\s*%', lambda m: 'един процент' if m.group(1) == '1'
                 else cardinal(int(m.group(1))) + ' процента', txt)
    # „(6=7–1)"
    txt = re.sub(r'\((\d)\s*=\s*(\d)\s*[–-]\s*(\d)\)',
                 lambda m: f'({cardinal(int(m.group(1)), 'n')} е равно на {cardinal(int(m.group(2)), 'n')} минус {cardinal(int(m.group(3)), 'n')})', txt)
    # Изброяване „(1) … (2) …" и „… или 2) …" → „първо, …"
    txt = re.sub(r'(^|\s)\(?([1-9])\)\s+', lambda m: m.group(1) + ordinal(int(m.group(2)), 'n') + ', ', txt)
    return txt



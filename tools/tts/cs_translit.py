"""Църковнославянското — с български букви, за да го прочете гласът (11.10.2026).

„А҆́зъ рѣ́хъ: бо́зи є҆стѐ“ → „А́з ре́х: бо́зи есте́“. Буквите се четат както в
българското църковно четене (ѣ → е, ы → и, ѧ/ꙗ → я, ѹ/ꙋ → у, ѡ → о, ѿ → от),
крайният ер отпада. Ударенията идват от САМИЯ ТЕКСТ (остро, тежко и облечено
стават U+0301), а не от речник или модел.

Съкращенията под титла не се разгъват по правило — те са изброени в ABBR и
скриптът спира при непознато: разгадано наслуки, „гдⷭ҇ь“ би станало каквото
и да е.

Всяка преобразувана дума се огражда с ⟦…⟧, за да не я пипат речникът и
моделът. Признакът е буквата или знакът, който българският няма — така в
цитата се хващат всички многосрични думи (те винаги носят ударение).
"""

import re
import unicodedata

ACUTE = '́'

# Съкращение (без надредните знаци за дишане) → разгънато, с ударението.
# ⚠ Ударенията тук са предложение — чакат потвърждение от потребителя.
ABBR = {
    'гдⷭ҇ь': 'Госпо́д',
    'гдⷭ҇и': 'Го́споди',
    'гдⷭ҇нѧ': 'Госпо́дня',          # потвърдено от потребителя
    'а́гг҃лы': 'а́нгели',
    'іи҃лѧ': 'Изра́иля',
    'првⷣными': 'пра́ведними',
    'ст҃и': 'свя́ти',
    'іерⷭ҇ли́мѣ': 'Иерусали́ме',
    'премⷣростїю': 'прему́дростию',
}

LETTERS = {
    'ѣ': 'е', 'ы': 'и', 'ѧ': 'я', 'ꙗ': 'я', 'ѹ': 'у', 'ꙋ': 'у', 'ѡ': 'о',
    'ѻ': 'о', 'ѿ': 'от', 'і': 'и', 'ї': 'и', 'є': 'е', 'ѯ': 'кс', 'ѱ': 'пс',
    'ѳ': 'ф', 'ѵ': 'и', 'ѕ': 'з', 'ꙁ': 'з', 'ꙃ': 'з', 'ѽ': 'о', 'ѫ': 'у',
}
LETTERS.update({k.upper(): v.capitalize() for k, v in LETTERS.items()})
LETTERS.update({'Ꙗ': 'Я', 'Ѹ': 'У', 'Ꙋ': 'У'})

_STRESS = {'́': ACUTE, '̀': ACUTE, '̑': ACUTE}   # остро, тежко, облечено
_DROP = '҆҅'                                          # дишане
_TITLO = re.compile('[҃҇ⷠ-ⷿ]')
_CS = re.compile('[ѣыѧꙗѹꙋѡѻѿіїєѯѱѳѵѕꙁꙃѽѫЀ-ЏѠ-ҁꙀ-ꚟ҃-҉ⷠ-ⷿ̀̑]')
VOWELS = set('аеиоуъюяАЕИОУЪЮЯ')
# Дума: букви (вкл. църковнославянските) и надредни знаци.
TOKEN = re.compile('[A-Za-zА-Яа-яЀ-ӿꙀ-ꚟ̀-ͯ҃-҉ⷠ-ⷿ]+')


def _key(w):
    return ''.join(c for c in unicodedata.normalize('NFC', w) if c not in _DROP).lower()


def word(w):
    """Една църковнославянска дума → българска, с ударението си."""
    k = _key(w)
    if _TITLO.search(k):
        if k not in ABBR:
            raise ValueError(f'непознато съкращение под титла: {w}')
        out = ABBR[k]
        return out[0].upper() + out[1:] if w[:1].isupper() else out
    s = unicodedata.normalize('NFD', w)
    s = ''.join(_STRESS.get(c, c) for c in s if c not in _DROP)
    s = unicodedata.normalize('NFC', s.replace('оу', 'у').replace('Оу', 'У'))
    s = ''.join(LETTERS.get(c, c) for c in s)
    s = unicodedata.normalize('NFC', s)
    s = re.sub('ъ$', '', s)                       # краен ер
    if sum(c in VOWELS for c in s) < 2:           # едносрична — без знак
        s = s.replace(ACUTE, '')
    return s


# ѐ и ѝ са предварително съставени — също ударение (самотното българско „ѝ“
# не се пипа, защото до него няма църковнославянска дума).
_MARK = re.compile('[\u0301\u0300\u0311ѐѝЀЍ]')


def convert(text):
    """Транслитерира всяка църковнославянска дума в текста и я огражда с ⟦…⟧.

    Църковнославянска е думата с буква или знак, каквито българският няма, И
    думата с ударение, която стои ДО такава („Сѐ жени́хъ грѧде́тъ“ —
    „жени́хъ“ няма особена буква). Самотна българска дума с ударение
    („Па́сха“) остава непипната."""
    toks = list(TOKEN.finditer(text))
    # Краен ер („въ“, „жени́хъ“) е сигурен признак: в днешния български
    # дума на „ъ“ не свършва.
    cs = [bool(_CS.search(m.group(0)) or m.group(0).endswith(('ъ', 'Ъ'))) for m in toks]
    changed = True
    while changed:
        changed = False
        for i, m in enumerate(toks):
            if cs[i] or not _MARK.search(m.group(0)):
                continue
            if (i > 0 and cs[i - 1]) or (i + 1 < len(toks) and cs[i + 1]):
                cs[i] = changed = True
    out, last = [], 0
    for m, c in zip(toks, cs):
        if c:
            out.append(text[last:m.start()] + '⟦' + word(m.group(0)) + '⟧')
            last = m.end()
    out.append(text[last:])
    return ''.join(out)



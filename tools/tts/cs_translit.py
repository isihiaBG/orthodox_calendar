    checks = {
        '„А҆́зъ рѣ́хъ: бо́зи є҆стѐ, и҆ сы́нове вы́шнѧгѡ всѝ“':
            '„⟦Аз⟧ ⟦рех⟧: ⟦бо́зи⟧ ⟦есте́⟧, ⟦и⟧ ⟦си́нове⟧ ⟦ви́шняго⟧ ⟦вси⟧“',
        'Покаѧ́нїѧ ѿве́рзи мѝ двє́ри жизнода́вче':
            '⟦Покая́ния⟧ ⟦отве́рзи⟧ ⟦ми⟧ ⟦две́ри⟧ ⟦жизнода́вче⟧',
        'И҆ речѐ гдⷭ҇ь ко мнѣ̀':
            '⟦И⟧ ⟦рече́⟧ ⟦Госпо́д⟧ ко ⟦мне⟧',
        'сотвори́лъ є҆сѝ': '⟦сотвори́л⟧ ⟦еси́⟧',
        'на прага: „Сѐ жени́хъ грѧде́тъ въ полꙋ́нощи“': 'на прага: „⟦Се⟧ ⟦жени́х⟧ ⟦гряде́т⟧ ⟦в⟧ ⟦полу́нощи⟧“',
        'Па́сха е': 'Па́сха е',
    }
    bad = 0
    for s, want in checks.items():
        got = convert(s)
        if got != want:
            bad += 1
            print('✗', s, '\n   →', got, '\n   ≠', want)
    print('грешки:', bad, 'от', len(checks))

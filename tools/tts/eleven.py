def spoken(block):
    """Текстът за гласа и карта: позиция в block['text'] → позиция в него.

    'marked' е 'text' с ВМЪКНАТИ ударения; ⟦…⟧ (църковнославянското) не се
    изпращат."""
    text, marked = block['text'], block['marked']
    out, pos, j = [], [], 0
    for c in text:
        while marked[j] != c:              # вмъкнато ударение
            out.append(marked[j])
            j += 1
        pos.append(len(out))
        if c not in '⟦⟧':
            out.append(c)
        j += 1
    out.extend(marked[j:])
    pos.append(len(out))
    sp, remap = yat(voice_fix(''.join(out)))
    sp, remap2 = insert_fix(sp)
    res = [remap2[remap[p]] for p in pos]
    # Заглавие и подзаглавие — с точка накрая, за спокойно окончание
    # (автора, 11.10.2026). Краят сочи след нея.
    if block.get('kind') in ('head', 'centernote') and not block.get('cont') \
            and sp.rstrip()[-1:] not in '.!?…':
        sp = sp.rstrip() + '.'
        res[-1] = len(sp)
    return sp, res



# ⚠ Знаците на Типикона са Unicode (🕀🕁🕂🕃), каквито почти никой шрифт
# няма. Заменят се със СЪЩИТЕ SVG-та, с които календарът бележи ранга —
# таг `<znak n="…"></znak>`, затворен изрично (самозатварящият се поглъща
# остатъка от абзаца — платено в справочника).
ЗНАЦИ = {'🕀': '1', '🕁': '2', '🕂': '3'}
# ⚠⚠ 🕃 Е ОБЩ ЗА ДВА ЗНАКА — „славословие" (червен) и „шестерик" (черен).
# В Unicode е един, а цветът в книгата е изгубен. Различава се по ранга на
# деня в СЕМЕТО: има ли светия с ранг 4, знакът е 4, инак 5.
ДВОЕН_ЗНАК = '🕃'


def редове() -> list[str]:
    """Текстът на книгата, абзац по абзац, в реда на spine-а."""
    z = zipfile.ZipFile(EPUB)
    opf_име = next(n for n in z.namelist() if n.endswith('.opf'))
    opf = z.read(opf_име).decode()
    база = opf_име.rsplit('/', 1)[0] + '/' if '/' in opf_име else ''
    items = {}
    for m in re.finditer(r'<item\b[^>]*>', opf):
        t = m.group(0)
        i = re.search(r'id="([^"]+)"', t)
        h = re.search(r'href="([^"]+)"', t)
        if i and h:
            items[i.group(1)] = h.group(1)
    out = []
    for idref in re.findall(r'<itemref[^>]*idref="([^"]+)"', opf):
        s = z.read(база + items[idref]).decode('utf-8', 'replace')
        for m in re.finditer(r'<(p|h\d)\b[^>]*>(.*?)</\1>', s, re.S):
            t = ' '.join(html.unescape(re.sub(r'<[^>]+>', '', m.group(2))).split())
            if t:
                out.append(t)
    return out


def ранг4(месец: int, ден: int) -> bool:
    """Има ли в семето светия с ранг 4 (славословие) на тази църковна дата.

    ⚠ Датата в семето е ГРАЖДАНСКА по стар стил за 2026 — църковната + 13
    дни (виж `extract_rules.py`).
    """
    год = 2028 if (месец, ден) == (2, 29) else 2026
    гр = datetime.date(год, месец, ден) + datetime.timedelta(days=13)
    with sqlite3.connect(f'file:{СЕМЕ}?mode=ro', uri=True) as c:
        return c.execute('SELECT 1 FROM saints WHERE date = ? AND rank = 4',
                         (гр.isoformat(),)).fetchone() is not None


def абзац(t: str, знак4: bool) -> str:
    """Един абзац като HTML — екраниран, със знаците и бележките."""
    t = html.escape(t, quote=False)
    for к, n in ЗНАЦИ.items():
        t = t.replace(к, f'<znak n="{n}"></znak> ')
    t = t.replace(ДВОЕН_ЗНАК, f'<znak n="{"4" if знак4 else "5"}"></znak> ')
    t = re.sub(r'\s+', ' ', t).strip()
    # ⚠ „[Зри]"/„[МРК]" са уставни бележки — в червено, с класа, който
    # четецът вече има (`.rubric`), за да се виждат сред реда на службата.
    t = re.sub(r'^\[(Зри|МРК)\]', r'<span class="rubric">[\1]</span>', t)
    return t


def заглавие(t: str) -> str:
    """Кратко име за лентата на четеца — първата част на заглавието."""
    t = re.sub(r'^\d+\.\s*', '', t)
    t = re.sub('[🕀🕁🕂🕃]', '', t).strip()
    t = re.split(r'[:.]\s', t + ' ', maxsplit=1)[0].strip(' :.')
    return t if len(t) <= 90 else t[:88].rsplit(' ', 1)[0] + '…'


# ─── Месецослов ─────────────────────────────────────────────────────────

RE_ДЕН = re.compile(r'^(\d{1,2})\.\s?\S')


def месецослов(L: list[str], от: int, до: int) -> list[dict]:
    """Дните от глава 48, по църковна дата.

    ⚠ Нов ден се признава САМО ако номерът му е ТОЧНО следващият. Вътре в
    дните има и номерирани изброявания („1. …", „2. …"); без проверката
    на реда те биха нарязали деня.
    """
    дни, месец, очакван, текущ = [], None, 1, None
    for i in range(от, до):
        t = L[i]
        m = re.match(r'^Месяц (\S+)$', t)
        if m:
            if m.group(1) not in МЕСЕЦИ:
                sys.exit(f'непознат месец: {t}')
            месец, очакван, текущ = МЕСЕЦИ[m.group(1)], 1, None
            continue
        if месец is None:
            continue
        md = RE_ДЕН.match(t)
        if md and int(md.group(1)) == очакван:
            текущ = {'month': месец, 'day': очакван, 'lines': [t]}
            дни.append(текущ)
            очакван += 1
            continue
        if текущ is not None:
            текущ['lines'].append(t)
        # редовете преди „1." (броят на дните и часовете) не са ден
    # ⚠ Пазач: всеки месец с точния брой дни, иначе делението е сгрешено.
    брой = {}
    for д in дни:
        брой[д['month']] = брой.get(д['month'], 0) + 1
    for м, n in ДНИ_В_МЕСЕЦА.items():
        if брой.get(м) != n:
            sys.exit(f'месец {м}: {брой.get(м)} дни вместо {n}')
    return дни



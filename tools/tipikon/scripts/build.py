"""Указанията на Типикона за всеки ден → `assets/db/lives_plus.db`.

Изворът е „Типикон" (Иерусалимски устав, издание на azbyka.ru), .epub в
`tools/Troparion/input/` — там го сложи потребителят и там си стои.

Какво се взима, БЕЗ превод (изрично искане на потребителя):

    Глава 48  Месецослов        366 дни, по ЦЪРКОВНА дата „ММ-ДД"
    Глава 49  Триодион          от Митаря до Велика събота
    Глава 50  Пентикостар       от Пасха до Вси светии

Бележките „[Зри]" и „[МРК]" за деня СА вътре в дяла му — те стоят в самия
текст, между редовете на службата, и влизат заедно с него.

⚠ Общите глави (1–47, 51–60, „О храмех") не са по дни и тук не влизат.

Таблиците `tipikon` и `tipikon_days` живеят в `lives_plus.db` до словата и
главите на Дебольски, в СВОИ таблици — `lives_plus/03_build_db.py` трие само
`slova`/`slovo_days`, тъй че конвейерите не се тъпчат.

⚠⚠ ПРОВЕРКИТЕ СА ПРЕДИ `DROP` — скрипт, който пресъздава таблица, трябва да се
проваля, докато старата още е цяла (платено веднъж с `articles`).
"""


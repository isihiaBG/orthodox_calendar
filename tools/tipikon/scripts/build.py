def редно(n: int) -> str:
    """1-ва, 2-ра, 3-та … 7-ма, 8-ма — българското окончание на редното."""
    return f'{n}-' + {1: 'ва', 2: 'ра', 7: 'ма', 8: 'ма'}.get(n, 'та')


def име_бг(отм: int) -> str:
    if отм in ИМЕНА_БГ:
        return ИМЕНА_БГ[отм]
    wd = ДЕН_БГ[(отм % 7) or 7]
    if -55 <= отм <= -50:
        return f'Сирна седмица, {wd}'
    if -48 <= отм < -7:
        return f'{редно((отм + 48) // 7 + 1)} седмица на Великия пост, {wd}'
    if 1 <= отм <= 6:
        return f'Светла седмица, {wd}'
    if 8 <= отм <= 48:
        return f'{редно(отм // 7 + 1)} седмица след Пасха, {wd}'
    if 50 <= отм <= 56:
        return f'Седмица след Петдесетница, {wd}'
    return f'Ден {отм:+d} от Пасха'


def триод(L: list[str]) -> list[dict]:
    """Дяловете от глави 49–50, разпределени по ДНИ.

    Разпределението е РЪЧНО — `input/triod_sections.csv`: редът, с който
    започва дялът (сверява се и текстът му), и отместването от Пасха.

    ⚠⚠ ПРАВИЛОТО Е ГРАЖДАНСКИЯТ ДЕН, ЧИЕТО ИМЕ ДЯЛЪТ НОСИ. „Великий
    четверток вечера" (12-те Страстни евангелия) остава в четвъртък — така е
    и в енорийската практика, — макар по устава денят да почва с вечернята
    от предната вечер. Изключение са само вечерните дялове, в които стои
    цялата служба на следващия ден, защото той няма свое заглавие
    (Цветница, отданието на Възнесение, Черешовата задушница, съботата след
    Петдесетница) — те отиват при него.
    """
    with open(ДЯЛОВЕ, encoding='utf-8') as f:
        рд = [r for r in csv.DictReader(f) if not r['line'].startswith('#')]
    индекс = {}
    for r in рд:
        n = int(r['line']) - 1
        if not L[n].startswith(r['starts']):
            sys.exit(f'ред {r["line"]}: очаквах „{r["starts"]}", има „{L[n][:60]}"')
        индекс[n] = [int(x) for x in r['offsets'].split(';')]
    начало = min(индекс)
    край = next(i for i, t in enumerate(L)
                if t.startswith('Глава 51.') and i > начало)
    дни: dict[int, list] = {}
    ред = sorted(индекс)
    for k, n in enumerate(ред):
        до = ред[k + 1] if k + 1 < len(ред) else край
        # ⚠ Съдържание, което продължава предишния дял (напр. „Последование
        # литургии…"), НЕ е в таблицата и си остава в него — делим само
        # там, където таблицата казва.
        блок = L[n:до]
        for отм in индекс[n]:
            дни.setdefault(отм, []).append(блок)
    return [{'offset': o, 'blocks': b} for o, b in sorted(дни.items())]


def main() -> None:
    L = редове()
    г48 = next(i for i, t in enumerate(L) if t.startswith('Глава 48. Месяцеслов'))
    г49 = next(i for i, t in enumerate(L) if t.startswith('Глава 49. Триодион'))
    записи = []   # (id, ord, part, title, body, source, [addresses])

    for д in месецослов(L, г48, г49):
        md = f'{д["month"]:02d}-{д["day"]:02d}'
        з4 = ранг4(д['month'], д['day'])
        глава, *тяло = д['lines']
        body = f'<h3>{абзац(глава, з4)}</h3>' + ''.join(
            f'<p>{абзац(t, з4)}</p>' for t in тяло)
        # ⚠ Редът е ЦЪРКОВНАТА година — от септември, както в книгата.
        ord_ = ((д['month'] - 9) % 12) * 100 + д['day']
        записи.append((f'tip-{md}', ord_, 'menaion', заглавие(глава), body,
                       ИЗТОЧНИК + '48', [md]))

    for д in триод(L):
        o = д['offset']
        # ⚠ Най-отгоре — БЪЛГАРСКОТО име на деня като заглавие; уставните
        # заглавия на дяловете („Во святый и великий пяток вечера.") стават
        # червени подзаглавия със същия клас като „Тропар, глас…".
        части = [f'<h3>{html.escape(име_бг(o))}</h3>']
        for блок in д['blocks']:
            гл, *тяло = блок
            части.append(f'<p class="prayerhead">{абзац(гл, False)}</p>' + ''.join(
                f'<p>{абзац(t, False)}</p>' for t in тяло))
        part = 'triodion' if o < 0 else 'pentecostarion'
        знак = 'm' if o < 0 else 'p'
        записи.append((f'tip-pascha-{знак}{abs(o)}', 2000 + o, part,
                       име_бг(o), ''.join(части),
                       ИЗТОЧНИК + ('49' if o < 0 else '50'), [ключ(o)]))

    # ⚠⚠ ПРОВЕРКИТЕ — ПРЕДИ DROP.
    ids = [r[0] for r in записи]
    if len(ids) != len(set(ids)):
        sys.exit('повтарящ се id')
    празни = [r[0] for r in записи if len(re.sub('<[^>]+>', '', r[4])) < 40]
    if празни:
        sys.exit(f'празни дни: {празни}')
    адреси = [a for r in записи for a in r[6]]
    if len(адреси) != len(set(адреси)):
        from collections import Counter
        sys.exit(f'адрес на два дни: {[a for a, n in Counter(адреси).items() if n > 1]}')

    with sqlite3.connect(БАЗА) as c:
        c.executescript('''
            DROP TABLE IF EXISTS tipikon;
            DROP TABLE IF EXISTS tipikon_days;
            CREATE TABLE tipikon (
                id TEXT PRIMARY KEY, ord INTEGER, part TEXT,
                title TEXT, body TEXT, source TEXT, chars INTEGER);
            CREATE TABLE tipikon_days (id TEXT, address TEXT);
            CREATE INDEX tipikon_days_addr ON tipikon_days(address);
        ''')
        for id_, o, part, t, body, src, addrs in записи:
            c.execute('INSERT INTO tipikon VALUES (?,?,?,?,?,?,?)',
                      (id_, o, part, t, body, src, len(body)))
            for a in addrs:
                c.execute('INSERT INTO tipikon_days VALUES (?,?)', (id_, a))
    мен = sum(1 for r in записи if r[2] == 'menaion')
    print(f'Месецослов: {мен} дни;  Триод и Пентикостар: {len(записи) - мен} дни')
    print(f'общо знаци: {sum(len(r[4]) for r in записи):,}')


if __name__ == '__main__':
    main()

def ключ(отм: int) -> str:
    """Литургичният адрес на ден с отместване `отм` от Пасха.

    ⚠ СЪЩАТА сметка като `readingAddress` в lib/readings_lookup.dart и
    `адрес()` в evangelie_slujebno/scripts/12_extract_cycle.py — промени ли
    се там, се мени и тук. Пасха е неделя (ISO 7).
    """
    wd = (отм % 7) or 7
    if отм < 0:
        return f'T{(70 + отм) // 7 + 1}:{wd}'
    if отм <= 49:
        return f'P{отм // 7 + 1}:{wd}'
    return f'W{(отм - 50) // 7 + 1}:{wd}'



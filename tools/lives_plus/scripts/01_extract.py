#!/usr/bin/env python3
"""Трите книги → `work/units/*.json` + отчет за подбора.

⚠ НИЩО НЕ ПИШЕ В БАЗИ и нищо не струва пари. Пуска се колкото пъти трябва.

    python3 01_extract.py
"""
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(__file__))
from address import infer          # noqa: E402
from common import blocks_of, toc_items   # noqa: E402

КОРЕН = Path(__file__).resolve().parents[1]
ВХОД = КОРЕН / 'input'
РАБОТА = КОРЕН / 'work'

КНИГИ = {
    'vosk': 'Поучения на воскресные дни',
    'nepe': 'Поучения на непереходящие',
    'pril': 'Приложения. Жития святых',
}

# ⚠⚠ ИЗРИЧНО ИЗХВЪРЛЕНИ — решение на потребителя (13.09.2026): остават
# дневните слова и тематичните с естествен дом; отпадат само речите към
# Петър Велики и надгробните слова за ПОИМЕННИ лица.
ИЗХВЪРЛЕНИ = (
    'речь к петру великому',
    'речь преосвященного димитрия',
    'пирамида, или столп',
    'на поминовение окольничего',
    'на поминовение иоанна семеновича',
)

# ⚠ Тематични слова с ЕСТЕСТВЕН ДОМ. Адресът им НЕ е ден, а повод — затова
# е отделен вид („повод"), а не ден от календара.
ПОВОДИ = {
    'во время святых постов': ('fast', 'постните дни'),
    'слово об умерших': ('memorial', 'Дни за помени'),
    'слово на поминовение («да не смущается': ('memorial', 'Дни за помени'),
}

# ⚠ Заглавия без съдържание — дялове на книгата, не текстове.
RE_РАЗДЕЛ = re.compile(
    r'^(часть \d+|поучения и (проповеди|слова)|приложения|'
    r'январ|феврал|март|апрел|май|июн|июл|август|сентябр|октябр|ноябр|декабр)',
    re.I)


def _ръчни() -> dict[str, tuple[str, str]]:
    """`input/address_manual.csv` → {id: (адрес, довод)}."""
    път = КОРЕН / 'input' / 'address_manual.csv'
    if not път.exists():
        return {}
    import csv
    with път.open(encoding='utf-8') as f:
        редове = [r for r in f if not r.lstrip().startswith('#')]
    правила = {r['title_prefix'].strip(): (r['address'].strip(),
                                           (r['why'] or '').strip())
               for r in csv.DictReader(редове) if r.get('title_prefix')}
    # ⚠⚠ БРОЯТ СЕ СВЕРЯВА. Незатворена кавичка кара csv да ПОГЪЛНЕ следващия
    # ред и правило изчезва, без да гръмне никъде — пазачът за „неулучили"
    # не помага, защото загубеното изобщо не влиза в речника.
    очаквани = len(редове) - 1
    if len(правила) != очаквани:
        raise SystemExit(f'⚠ address_manual.csv: {очаквани} реда, разчетени '
                         f'{len(правила)} — провери кавичките')
    return правила


РЪЧНИ = _ръчни()


def _улучва(правило: str, книга: str, заглавие: str) -> bool:
    """Улучва ли правилото това заглавие.

    ⚠ Ключът може да носи и КНИГАТА („vosk:Поучение…"), когато едно и също
    заглавие стои в две книги — иначе правило за едната засяга и другата.
    """
    if ':' in правило:
        к, _, п = правило.partition(':')
        if к in КНИГИ:
            return к == книга and заглавие.startswith(п)
    return заглавие.startswith(правило)


def _запиши(uid, книга, път, заглавие, адрес, довод, блокове, записи):
    (РАБОТА / 'units' / f'{uid}.json').write_text(json.dumps({
        'id': uid, 'book': книга, 'src': път,
        'title_ru': заглавие, 'address': адрес, 'why': довод,
        'blocks_ru': блокове,
    }, ensure_ascii=False, indent=1), encoding='utf-8')
    записи.append({'id': uid, 'book': книга, 'title': заглавие,
                   'address': адрес, 'why': довод,
                   'chars': sum(len(b) for b in блокове),
                   'blocks': len(блокове)})


def main() -> int:
    # ⚠⚠ СТАРИТЕ ФАЙЛОВЕ СЕ ТРИЯТ ПЪРВО. Изхвърлен дял инак остава като
    # осиротял `units/<id>.json` и следващите стъпки честно го намират — тъй
    # че той се появява в базата, макар да е бил махнат. Открито при
    # дубликата на словото за иконите (13.09.2026).
    (РАБОТА / 'units').mkdir(parents=True, exist_ok=True)
    for стар in (РАБОТА / 'units').glob('*.json'):
        стар.unlink()
    записи, отпаднали = [], []
    използвани: set[str] = set()

    for файл in sorted(ВХОД.glob('*.epub')):
        ключ = next((k for k, v in КНИГИ.items() if v in файл.name), '???')
        # ⚠ Свиването по път е ТУК, след като разделите отпаднат — виж
        # докстринга на `toc_items`: „Часть 2" дели файл с първото си слово.
        видени = set()
        for n, (заглавие, път, html) in enumerate(toc_items(str(файл))):
            блокове = blocks_of(html)
            гол = re.sub(r'^\d+\.\s*', '', заглавие).strip()
            if not блокове or RE_РАЗДЕЛ.match(гол):
                continue
            if път in видени:
                continue
            видени.add(път)
            низ = гол.lower()
            ако = next((и for и in ИЗХВЪРЛЕНИ if и in низ), None)
            if ако:
                отпаднали.append((ключ, гол, 'изрично изхвърлено'))
                continue
            # ⚠ РЪЧНИЯТ АДРЕС Е НАД ВСИЧКО. Празен ред значи „изхвърля се" —
            # проверява се за ПРИСЪСТВИЕ на ключа, не за истинност, инак
            # изричното изхвърляне пропада обратно към извеждането.
            uid_ = f'{ключ}-{n:03d}'
            # ⚠ Ключът може да носи и КНИГАТА („vosk:Поучение…"), когато едно
            # и също заглавие стои в две книги. Без това правило за едната
            # би засегнало и другата — а те са различни текстове или, както
            # при иконите, две редакции на един и същ.
            ключ_ръчно = next(
                (k for k in РЪЧНИ if _улучва(k, ключ, гол)), None)
            if ключ_ръчно:
                използвани.add(ключ_ръчно)
                адрес, довод = РЪЧНИ[ключ_ръчно]
                if not адрес:
                    отпаднали.append((ключ, гол, довод))
                    continue
                _запиши(uid_, ключ, път, гол, адрес, 'ръчно: ' + довод,
                        блокове, записи)
                continue
            повод = next(((v, k) for k, v in ПОВОДИ.items() if k in низ), None)
            if повод:
                адрес, довод = повод[0][0], f'повод: {повод[0][1]}'
            else:
                адрес, довод = infer(гол)

            _запиши(f'{ключ}-{n:03d}', ключ, път, гол, адрес, довод,
                    блокове, записи)

    # ⚠ Правило, което не е улучило нищо, е ТИХА ЗАГУБА на решение — гърми.
    неулучили = sorted(set(РЪЧНИ) - използвани)
    if неулучили:
        raise SystemExit('⚠ ръчни правила без съответствие:\n  '
                         + '\n  '.join(неулучили))

    с_адрес = [з for з in записи if з['address']]
    без = [з for з in записи if not з['address']]

    редове = ['# Подборът — за преглед преди превода', '',
              f'- разчетени дяла: **{len(записи)}**',
              f'- с адрес: **{len(с_адрес)}**',
              f'- ЗА РЕШЕНИЕ (без адрес): **{len(без)}**',
              f'- изрично изхвърлени: **{len(отпаднали)}**',
              f'- знаци за превод (само с адрес): '
              f'**{sum(з["chars"] for з in с_адрес):,}**', '',
              '## С адрес', '',
              '| id | адрес | довод | знаци | заглавие |',
              '|---|---|---|---:|---|']
    for з in sorted(с_адрес, key=lambda x: (x['book'], x['address'])):
        редове.append(f'| {з["id"]} | `{з["address"]}` | {з["why"]} | '
                      f'{з["chars"]:,} | {з["title"][:70]} |')
    редове += ['', '## ⚠ ЗА РЕШЕНИЕ — не се гадае', '',
               '| id | знаци | заглавие |', '|---|---:|---|']
    for з in без:
        редове.append(f'| {з["id"]} | {з["chars"]:,} | {з["title"][:80]} |')
    редове += ['', '## Изхвърлени', '']
    for к, т, защо in отпаднали:
        редове.append(f'- {т[:80]} — {защо}')

    (РАБОТА / 'report.md').write_text('\n'.join(редове) + '\n', encoding='utf-8')
    print(f'дяла {len(записи)} | с адрес {len(с_адрес)} | за решение {len(без)}'
          f' | изхвърлени {len(отпаднали)}')
    print(f'знаци с адрес: {sum(з["chars"] for з in с_адрес):,}')
    print(f'→ {(РАБОТА / "report.md").relative_to(КОРЕН.parent.parent)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

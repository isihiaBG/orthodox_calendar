#!/usr/bin/env python3
"""Библейските препратки в словата → ДЕЙСТВАЩИ връзки.

⚠⚠ ЕМИТИРА СЕ СЪЩИЯТ ВИД АДРЕС КАТО В ТОМОВЕТЕ:

    <a href="https://azbyka.ru/biblia/?Mt.5:1-7&amp;bg~utfcs">Мат. 5:1-7</a>

Нарочно — така препратката минава по вече наличния път и се отваря ВЪТРЕ в
приложението (виж „Библейските препратки се отварят ВЪТРЕ" в CLAUDE.md). Нов
вид адрес би искал второ разчитане и втори повод двете да се разминат.

⚠ Кодовете на книгите се четат от `bible.db` (`books.bg_abbr`), НЕ се пишат
на ръка: същият списък храни и надписа под споделен цитат, тъй че разминаване
е невъзможно по устройство.

    python3 05_bible_links.py --dry-run
    python3 05_bible_links.py
"""
import argparse
import json
import re
import sqlite3
import sys
from pathlib import Path

КОРЕН = Path(__file__).resolve().parents[1]
РАБОТА = КОРЕН / 'work'
БИБЛИЯ = КОРЕН.parents[1] / 'assets' / 'db' / 'bible.db'

# ⚠ Пълната база носи всичките 77 книги; основната — също (режат се само
# ПРЕВОДИТЕ, не книгите). Чете се тя, за да няма зависимост от tools/.
def съкращения() -> dict[str, str]:
    db = sqlite3.connect(БИБЛИЯ)
    out = {}
    for code, abbr, short in db.execute(
            'SELECT code, bg_abbr, bg_short FROM books'):
        for вид in (abbr, short):
            if вид:
                out[_ключ(вид)] = code
    # ⚠ Формите, които моделът реално пише, но ги няма в базата. Всяка е
    # СВЕРЕНА срещу съществуващ код — не се измислят.
    допълнително = {
        # руски къси форми, които моделът понякога оставя
        'мт': 'Mt', 'мк': 'Mk', 'лк': 'Lk', 'ин': 'Jn', 'йн': 'Jn',
        'быт': 'Gen', 'исх': 'Ex', 'иез': 'Ezek', 'иов': 'Job',
        # български форми, които базата не дава в този вид
        'бит': 'Gen', 'як': 'Jac', 'яков': 'Jac', 'юда': 'Juda',
        'йов': 'Job', 'сирах': 'Sir', 'песен': 'Song', 'плач': 'Lam',
        'фил': 'Phil', 'флп': 'Phil', 'откр': 'Apok',
        '1пет': '1Pet', '2пет': '2Pet',
        '1йоан': '1Jn', '2йоан': '2Jn', '3йоан': '3Jn',
        # ⚠⚠ ЦАРСТВАТА СА КАПАН: българското „1 Царе" е 1 Царства (1Sam), а
        # „3 Царе" е 3 Царства (1King) — номерът се РАЗМЕСТВА спрямо
        # западното броене. Сверено срещу `books.bg_short` в bible.db.
        '1цар': '1Sam', '1царе': '1Sam', '2цар': '2Sam', '2царе': '2Sam',
        '3цар': '1King', '3царе': '1King', '4цар': '2King', '4царе': '2King',
        '1езд': 'Ezr', '2езд': '2Ezr', 'неем': 'Nehem',
        '1парал': '1Chron', '2парал': '2Chron',
        '1мак': '1Mac', '2мак': '2Mac', '3мак': '3Mac',
        'иис': 'Nav', 'нав': 'Nav', 'съд': 'Judg', 'рут': 'Rth',
        'тов': 'Tov', 'иудит': 'Judf', 'юдит': 'Judf', 'ест': 'Est',
        'екл': 'Eccl', 'прем': 'Solom',
        'иса': 'Is', 'исаия': 'Is', 'числ': 'Num', 'йер': 'Jer',
        'иерем': 'Jer', 'йез': 'Ezek', 'йоил': 'Joel',
        '2пар': '2Chron', '2лет': '2Chron', '1лет': '1Chron',
        'филип': 'Phil', '3езд': '3Ezr', 'пес': 'Song', 'ефес': 'Eph',
        # ⚠ Голото „Цар."/„Царе" се ОСТАВЯ без връзка — не се знае коя от
        # четирите книги е. По-добре без връзка, отколкото към чужда книга.
    }
    for k, v in допълнително.items():
        out.setdefault(k, v)
    return out


def _ключ(s: str) -> str:
    return re.sub(r'[^0-9a-zа-я]', '', s.lower().replace('ё', 'е'))


# „Мат. 5:1-7", „1 Кор. 13:1", „Пс. 33:9", „Бит. 1:1-3, 5"
RE_REF = re.compile(
    r'(?<![\w])([1-3]\s*)?([А-Яа-яЁё]{2,8})\.?\s*'
    r'(\d{1,3}\s*[:,]\s*\d{1,3}(?:\s*[-–]\s*\d{1,3}(?::\d{1,3})?)?'
    r'(?:\s*,\s*\d{1,3}(?:\s*[-–]\s*\d{1,3})?)*)')


def свържи(текст: str, карта: dict[str, str], брой: dict) -> str:
    def _замени(m):
        номер, име, места = m.group(1), m.group(2), m.group(3)
        ключ = _ключ((номер or '') + име)
        код = карта.get(ключ)
        if not код:
            брой.setdefault('непознати', {})
            брой['непознати'][ключ] = брой['непознати'].get(ключ, 0) + 1
            return m.group(0)
        # ⚠ Запетаята между глава и стих е руският запис („Лк.2, 21"); в
        # адреса тя трябва да е ДВОЕТОЧИЕ, инак azbyka.ru я чете като втори
        # пасаж. Разчитането ни също я приема, но само в тази си роля.
        # ⚠⚠ ДЪЛГОТО ТИРЕ НЕ ВЪРВИ В АДРЕСА. Текстът пише „24–15" с „–"
        # (U+2013), а разчитането търси „-": 142 от 1379 връзки излизаха
        # неразчетими, при това МЪЛЧАЛИВО — адресът изглежда напълно
        # правдоподобен. Видимият текст си остава с дългото тире.
        адрес = места.replace(' ', '').replace('–', '-').replace('—', '-')
        адрес = re.sub(r'^(\d{1,3})\s*,\s*', r'\1:', адрес)
        брой['връзки'] = брой.get('връзки', 0) + 1
        return (f'<a href="https://azbyka.ru/biblia/?{код}.{адрес}'
                f'&amp;bg~utfcs">{m.group(0)}</a>')
    # ⚠⚠ ИДЕМПОТЕНТНО ПО УСТРОЙСТВО. Пуснат втори път, изразът би хванал
    # текста ВЪТРЕ във вече направената връзка („Мат. 5:1" между <a> и </a>)
    # и би я обвил повторно. Затова се пипа само онова ИЗВЪН съществуващите
    # котви — същият капан, платен три пъти в другите конвейери.
    части = re.split(r'(<a\b[^>]*>.*?</a>)', текст, flags=re.S)
    out = []
    for ч in части:
        if ч.startswith('<a'):
            # ⚠ Поправя и ВЕЧЕ нанесени връзки с дълго тире — инак скриптът
            # е идемпотентен, но старата грешка остава завинаги.
            out.append(re.sub(
                r'(href="https://azbyka\.ru/biblia/\?[^"]*)',
                lambda m: m.group(1).replace('–', '-').replace('—', '-'), ч))
        else:
            out.append(RE_REF.sub(_замени, ч))
    return ''.join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    if not БИБЛИЯ.exists():
        sys.exit(f'липсва {БИБЛИЯ}')
    карта = съкращения()
    брой = {}
    файлове = sorted((РАБОТА / 'translated').glob('*.json'))
    if not файлове:
        sys.exit('няма преводи')
    пипнати = 0
    for f in файлове:
        x = json.loads(f.read_text(encoding='utf-8'))
        нови = [свържи(b, карта, брой) for b in x['blocks_bg']]
        if нови != x['blocks_bg']:
            пипнати += 1
            if not a.dry_run:
                x['blocks_bg'] = нови
                f.write_text(json.dumps(x, ensure_ascii=False, indent=1),
                             encoding='utf-8')
    print(f'{"БИ СВЪРЗАЛ" if a.dry_run else "свързани"}: '
          f'{брой.get("връзки", 0)} препратки в {пипнати} от {len(файлове)} слова')
    неп = брой.get('непознати', {})
    if неп:
        print(f'⚠ непознати съкращения ({len(неп)}), най-чести:')
        for k, n in sorted(неп.items(), key=lambda kv: -kv[1])[:14]:
            print(f'   {k:14} ×{n}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

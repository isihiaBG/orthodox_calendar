#!/usr/bin/env python3
"""Заглавията → `work/titles_bg.json`.

⚠ Отделна стъпка, защото основният превод работи по АБЗАЦИ и заглавието не е
сред тях. Ако не се преведе, в списъка „Слова за деня" стои руски ред.

⚠ ВСИЧКИТЕ НАВЕДНЪЖ, в едно повикване: заглавията са къси и еднотипни, а
подадени поотделно, моделът избира различна форма за един и същ израз
(„на день памяти" ту „за паметта на", ту „в деня на паметта на"). Заедно ги
вижда наред и ги уеднаквява сам.

    python3 02b_translate_titles.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import importlib.util                                    # noqa: E402

spec = importlib.util.spec_from_file_location(
    'tr', Path(__file__).parent / '02_translate_deepseek.py')
tr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tr)

РАБОТА = Path(__file__).resolve().parents[1] / 'work'

ПРОМПТ = """Ти си опитен преводач на православна църковна литература от руски на български.

Превеждаш ЗАГЛАВИЯ на слова и поучения от св. Димитрий Ростовски.

Правила:
1. Кратко и в утвърдения български църковен стил: „Поучение за паметта на св. Алексий, митрополит Московски“.
2. Имената на светии и празници — в утвърдените български форми („Йоан“, не „Иоанн“; „Успение на Пресвета Богородица“).
3. МАХНИ указанието за дата („месяца января, в 1 день“) — то е излишно, денят се знае от календара.
4. Ако в скоби стои начален стих, запази го в скоби, преведен.
5. Не добавяй номера и не пренареждай.
6. Кавичките са български: „…“.

Входът е номериран списък, по едно заглавие на ред. Отговори със същите номера, същия ред и същия брой редове.
"""


def main() -> int:
    дялове = sorted((РАБОТА / 'units').glob('*.json'))
    единици = [json.loads(f.read_text(encoding='utf-8')) for f in дялове]
    цел = РАБОТА / 'titles_bg.json'
    готови = json.loads(цел.read_text(encoding='utf-8')) if цел.exists() else {}
    липсващи = [x for x in единици if x['id'] not in готови]
    if not липсващи:
        print('всички заглавия са преведени')
        return 0

    k = tr.ключ()
    отчет = {'повиквания': 0, 'вход': 0, 'изход': 0}
    # ⚠ На порции по 40, за да не се разпадне номерирането при дълъг списък.
    for i in range(0, len(липсващи), 40):
        порция = липсващи[i:i + 40]
        tr.ПРОМПТ = ПРОМПТ
        редове = tr.преведи(k, [x['title_ru'] for x in порция], '', отчет)
        for x, bg in zip(порция, редове):
            готови[x['id']] = bg
        print(f'  {i + len(порция)}/{len(липсващи)}', flush=True)

    цел.write_text(json.dumps(готови, ensure_ascii=False, indent=1),
                   encoding='utf-8')
    print(f'готови {len(готови)} заглавия | повиквания {отчет["повиквания"]} '
          f'| изходни токени {отчет["изход"]:,}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

def apply_to(path, dry):
    if not os.path.exists(path):
        return "липсва"
    db = sqlite3.connect(path, timeout=5)
    try:
        rows = {k: t for k, t in db.execute(
            "SELECT key, text FROM fast_explanations")}
        missing = [k for k in TEXTS if k not in rows]
        if missing:
            return "НЯМА ключовете: %s" % ", ".join(missing)
        changed = sum(1 for k, t in TEXTS.items() if rows[k] != t)
        if not dry:
            for k, t in TEXTS.items():
                db.execute("UPDATE fast_explanations SET text = ? WHERE key = ?",
                           (t, k))
            db.commit()
        return "%d от %d реда %s" % (changed, len(TEXTS),
                                     "биха се променили" if dry else "обновени")
    except sqlite3.OperationalError as e:
        if "locked" in str(e):
            return ("ЗАКЛЮЧЕНА (най-вероятно е отворена в sqlitebro — "
                    "затвори я и пусни наново)")
        raise
    finally:
        db.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-backup", action="store_true")
    args = ap.parse_args()

    print("редове за пренаписване: %d" % len(TEXTS))
    for path in TARGETS:
        if not args.dry_run and not args.no_backup and os.path.exists(path):
            bak = "%s.bak-%s" % (path, time.strftime("%Y%m%d-%H%M%S"))
            shutil.copy2(path, bak)
        print("  %-52s %s" % (os.path.relpath(path, REPO),
                              apply_to(path, args.dry_run)))


if __name__ == "__main__":
    main()

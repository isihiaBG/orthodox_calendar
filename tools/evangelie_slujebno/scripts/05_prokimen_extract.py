"""Разчита „Прокимны и аллилуарии без сокращений" в структуриран вид.

  python3 05_prokimen_extract.py        # → work/prokimen_raw.json

⚠ Етикетите („Прокимен", „Стих", „Апостол", „Аллилуиа") се срещат и
НАСРЕД реда, не само в началото му — при част от дяловете целият блок е
на един ред. Затова разчитането е по етикети в текста, а не по редове.
"""
import html
import json
import pathlib
import re
import zipfile

ВХОД = pathlib.Path(__file__).resolve().parents[1] / 'input'
РАБОТА = pathlib.Path(__file__).resolve().parents[1] / 'work'
КНИГА = ВХОД / 'Прокимны и аллилуарии без сокращений.gen.epub'

# ⚠⚠ ЕТИКЕТ БЕЗ ДВОЕТОЧИЕ ПОГЛЪЩАШЕ СЛЕДВАЩИЯ.
#
# „Апостол в Деяниих, зачало 1." свършва С ТОЧКА, а изразът търсеше
# двоеточие — тъй че свойството му се разпростираше напред и изяждаше
# „Аллилуиа, глас 4", чието двоеточие беше първото срещнато. Резултатът:
# стихът на Алилуята се приписваше на ПРОКИМЕНА и той излизаше с два
# стиха вместо с един. Точно това ме подведе да обявя, че стиховете са по
# един — а те наистина са по два в 132 дяла. (11.09.2026.)
#
# ⚠ Лекът е свойството да НЕ МОЖЕ да съдържа друг етикет, а не да се
# добави точка като край: в текста на прокимена има точки в изобилие.
RE_ЕТИКЕТ = re.compile(
    r'(Другий\s+прокимен|Прокимен|Стих|Аллилуиа|Апостол|Евангелие)'
    r'\s*((?:(?!Другий|Прокимен|Стих|Аллилуиа|Апостол|Евангелие)[^:]){0,60}?)'
    r'\s*:\s*', re.I)
RE_ЗАЧ = re.compile(r'зачало\s*(\d+)')

# ⚠ УКАЗАНИЕТО ЗА ЧЕТИВОТО („Апостол в Деяниих, зачало 1.") НЕ Е етикет с
# двоеточие, а изречение, завършващо с ТОЧКА. Изважда се ПРЕДИ деленето по
# етикети — оставено вътре, то се залепя за стиха на прокимена.
RE_ЧЕТИВО = re.compile(
    r'(?:Апостол|Евангелие|Другий)[^.:]{0,80}?зачало\s*\d+[^.]{0,40}\.', re.I)
RE_ГЛАС = re.compile(r'глас\s*(\d+)')

# ⚠⚠ ВГРАДЕН ВТОРИ ПРОКИМЕН. Книгата понякога слага прокимена на светията
# ВЪТРЕ в реда на първия: „…во Изра́или ве́лие и́мя Его́. И святых, глас 4:
# Ди́вен Бог во святы́х…". Оставено, това залепя чужд текст за първия
# прокимен и той не се намира в Писанието. Отрязва се тук; самият втори
# прокимен засега се ПРОПУСКА — за него трябва да се знае ЧИЯ е втората
# памет, а това е същият открит въпрос като адресирането на четивата.
RE_ОПАШКА = re.compile(
    r'\s+(?:И\s+(?:свят|преподобн|Богородиц|апостол|мучен|за\s+упокой)'
    r'|Аллилуиа\s+гласа|Другий\s+прокимен)', re.I)

# ⚠⚠ ОТКЪСНАТА ОПАШКА СЛЕД КРАЯ НА ИЗРЕЧЕНИЕТО. Освен целите етикети по-горе
# остават и парчета от тях — „…лю́дстии. **И**", „…от Мене́. **Святым,**",
# „…да исче́знут. **Аллилуиа,**". Те са начало на ВТОРИ прокимен, отрязано от
# разчитането, и пречат на отрязването: то не намира край и показва ЦЕЛИЯ
# стих. (Забелязано при одита, 13.09.2026.)
#
# ⚠ Признакът е СТРУКТУРЕН: след точка, най-много ТРИ думи, започващи с
# главна буква, и то без своя точка накрая. Цяло изречение не съвпада.
RE_ОТКЪСНАТО = re.compile(
    r'\.\s+((?:[А-ЯЁ][^.\s]*[\s,]*){1,3})$')


def дялове() -> list[tuple[str, str]]:
    z = zipfile.ZipFile(КНИГА)
    toc = z.read('toc.ncx').decode('utf-8', errors='replace')
    вън = []
    for заг, src in re.findall(
            r'<navPoint.*?<text>(.*?)</text>.*?src="([^"]+)"', toc, re.S):
        заг = html.unescape(заг.strip())
        f = src.split('#')[0]
        име = [n for n in z.namelist() if n.endswith(f)]
        if not име:
            continue
        x = z.read(име[0]).decode('utf-8', errors='replace')
        x = re.sub(r'<(p|div|br|h\d)[^>]*>', '\n', x)
        ls = [html.unescape(re.sub(r'<[^>]+>', '', l)).strip()
              for l in x.split('\n')]
        вън.append((заг, ' '.join(l for l in ls if l)))
    return вън


def части(txt: str) -> list[tuple[str, str, str]]:
    поз = list(RE_ЕТИКЕТ.finditer(txt))
    вън = []
    for i, m in enumerate(поз):
        край = поз[i + 1].start() if i + 1 < len(поз) else len(txt)
        вън.append((m.group(1).lower().replace('другий прокимен', 'прокимен2'),
                    m.group(2).strip(), txt[m.end():край].strip()))
    return вън


def main() -> None:
    вън = []
    for заг, txt in дялове():
        четива = RE_ЧЕТИВО.findall(txt)
        # ⚠ Махат се, преди да се дели по етикети — виж [RE_ЧЕТИВО].
        txt_бeз = RE_ЧЕТИВО.sub(' ', txt)
        ч = части(txt_бeз)
        if not any(k.startswith('прокимен') for k, _, _ in ч):
            continue
        запис: dict = {'title': заг, 'prokimena': []}
        текущ = None
        for вид, свойство, тяло in ч:
            if вид.startswith('прокимен'):
                г = RE_ГЛАС.search(свойство)
                тяло = RE_ОПАШКА.split(тяло)[0].strip()
                тяло = RE_ОТКЪСНАТО.sub('.', тяло).strip()
                текущ = {'glas': int(г.group(1)) if г else None,
                         'note': re.sub(r'глас\s*\d+\.?', '', свойство).strip(' .,'),
                         'text': тяло, 'verses': []}
                запис['prokimena'].append(текущ)
            elif вид == 'стих' and текущ is not None and 'alliluia' not in запис:
                текущ['verses'].append(
                    RE_ОТКЪСНАТО.sub('.', RE_ОПАШКА.split(тяло)[0]).strip())
            elif вид == 'аллилуиа':
                г = RE_ГЛАС.search(свойство)
                # ⚠ И АЛИЛУЯТА минава през чистенето — дотук само
                # прокименът и стиховете му, тъй че откъснатите опашки
                # оцеляваха именно тук.
                запис['alliluia'] = {
                    'glas': int(г.group(1)) if г else None,
                    'text': RE_ОТКЪСНАТО.sub(
                        '.', RE_ОПАШКА.split(тяло)[0]).strip(),
                    'verses': []}
                текущ = None
            elif вид == 'стих' and 'alliluia' in запис:
                запис['alliluia']['verses'].append(
                    RE_ОТКЪСНАТО.sub('.', RE_ОПАШКА.split(тяло)[0]).strip())
        з = RE_ЗАЧ.findall(txt)
        запис['readings'] = [x.strip() for x in четива]
        запис['zachala'] = [int(x) for x in з]
        вън.append(запис)
    РАБОТА.mkdir(exist_ok=True)
    (РАБОТА / 'prokimen_raw.json').write_text(
        json.dumps(вън, ensure_ascii=False, indent=1), encoding='utf-8')
    п = sum(len(r['prokimena']) for r in вън)
    с = sum(len(k['verses']) for r in вън for k in r['prokimena'])
    print(f'дялове: {len(вън)} | прокимена: {п} | стихове след тях: {с}')
    print(f'→ work/prokimen_raw.json')


if __name__ == '__main__':
    main()

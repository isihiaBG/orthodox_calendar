"""Съпоставя прокимените и стиховете им със стихове от Писанието.

  python3 06_prokimen_match.py        # → work/prokimen_refs.json

⚠⚠ ЗАЩО ИЗОБЩО. Прокименът е псаломски стих, тъй че текстът му вече е в
`bible.db` на дванайсет езика. Вписан като СВОЙ текст, той би бил
единайсети препис на едно и също нещо и би излизал само на славянски.
Като ПРЕПРАТКА се получава наготово на всеки превод, който човекът е
свалил. (Идея на потребителя, 11.09.2026.)

⚠ Търси се в ЦЯЛОТО Писание, не само в Псалтира: част от прокимените са
от песните на пророците (Дан. 3), а богородичните — от Магнификата
(Лк. 1:46), тоест от Новия завет. Първото пускане гледаше само Стария и
губеше точно тях.
"""
import csv
import json
import pathlib
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _fold import прилика, сгъни  # noqa: E402

КОРЕН = pathlib.Path(__file__).resolve().parents[3]
РАБОТА = pathlib.Path(__file__).resolve().parents[1] / 'work'
ПРАГ = 0.80


def стихове() -> list[tuple[str, int, str, list[str]]]:
    db = sqlite3.connect(КОРЕН / 'assets/db/bible.db')
    вън = []
    for книга, гл, ст, txt in db.execute(
            "SELECT v.book, v.chapter, v.verse, v.text FROM verses v"
            " JOIN books b ON b.code = v.book"
            " WHERE v.lang = 'utfcs'"):
        вън.append((книга, гл, ст, сгъни(txt)))
    return вън


def построй_указател(индекс):
    """префикс (3 букви) → номера на стихове.

    ⚠ БЕЗ него сравненията са 24 000 стиха × 500 текста = милиони, всяко с
    вложен цикъл — първото пускане не свърши за десет минути. С указател
    кандидатите падат до десетки.

    ⚠ Префиксът е ТРИ букви, защото контракциите под титла режат средата на
    думата, но пазят началото: „млть" и „милость" делят „мил"… не — делят
    само „м". Затова се индексират И контракциите: всяка дума дава своя
    3-буквен префикс, а търсенето гледа префиксите на ВСИЧКИ думи от целта.
    """
    от_префикс: dict[str, set[int]] = {}
    for i, (_, _, _, думи) in enumerate(индекс):
        for w in думи:
            if len(w) >= 3:
                от_префикс.setdefault(w[:3], set()).add(i)
    return от_префикс


def намери(текст: str, индекс, от_префикс) -> dict | None:
    """Най-приликащият стих, ако минава [ПРАГ]."""
    цел = сгъни(текст)
    if len(цел) < 3:
        return None
    # ⚠⚠ ПРЕСЯВА СЕ ПО НАЙ-РЕДКИТЕ ДУМИ, не по всички.
    #
    # Обединението по всяка дума влачи хиляди стихове — „гдⷭ҇ь", „бг҃ъ" и
    # „тво́й" ги има навсякъде, — а всяко сравнение е вложен цикъл. Така
    # пускането не свърши за 900 s. Взимат се трите най-редки префикса и се
    # ПРЕСИЧАТ: целта трябва да ги съдържа и трите, тъй че пресичането не
    # може да изгуби верния стих, а кандидатите падат до десетки.
    # ⚠⚠ ПРАЗНИТЕ СПИСЪЦИ СЕ ИЗХВЪРЛЯТ, а не се броят за „най-редки".
    #
    # Дума, която в славянския е ВИНАГИ съкратена („Боже" → „бже",
    # „Господи" → „гди"), няма нито един запис под своя префикс. Взета като
    # най-рядка, тя заемаше едно от трите места за пресяване и кандидатите
    # се свиваха до стихове, каквито не ни трябват. Така Пс. 103:1 — стих с
    # прилика 1,0 — изобщо не влизаше в кандидатите.
    списъци = sorted(
        (сп for w in set(цел) if len(w) >= 3
         for сп in [от_префикс.get(w[:3], set())] if сп),
        key=len)
    if not списъци:
        return None
    # ⚠⚠ ОБЕДИНЕНИЕ на най-редките, а НЕ пресичане.
    #
    # Пресичането изглежда по-точно и е ГРЕШНО: контракцията под титла реже
    # СРЕДАТА на думата, тъй че „милость" (префикс „мил") и „млⷭ҇ть"
    # (префикс „млт") нямат общ префикс и верният стих отпада. Мерено —
    # пресичането свали покритието от 80% на 38%. Редките думи обикновено
    # са обикновени (несвещени) и се пишат изцяло, тъй че обединението на
    # три от тях хваща стиха, а списъците остават къси.
    кандидати: set[int] = set()
    for сп in списъци[:3]:
        кандидати |= сп
    най = None
    for i in кандидати:
        книга, гл, ст, думи = индекс[i]
        r = прилика(цел, думи)
        # ⚠⚠ ВТОРИ ПРИЗНАК: КОЛКО ОТ СТИХА ЗАЕМА ПРОКИМЕНЪТ.
        #
        # Само приликата не стига. Тя мери „каква част от ТЪРСЕНОТО се
        # среща в стиха" — а много дълъг стих съдържа почти всяка дума по
        # СЛУЧАЙНОСТ и печели с 1,0 срещу верния къс стих.
        #
        # Точно така „Спаси, Господи, люди Твоя" (Пс. 27:9) се улавяше в
        # Естир 4:17 — молитвата на Естир, дълга колкото глава. Прокименът
        # заемаше **1,4%** от нея, а излизаше „дословно съвпадение".
        # Показа се на екрана като прокимен от половин страница.
        # (Докладвано от потребителя, 13.09.2026.)
        #
        # ⚠ Не е праг, а ВТОРИ КЛЮЧ при подредбата: първо приликата, после
        # делът. Праг би отрязал законните случаи, където прокименът е къс
        # откъс от дълъг стих (146 такива, мерено).
        дял = len(цел) / max(len(думи), 1)
        ключ = (round(r, 3), дял)
        if най is None or ключ > най[0]:
            най = (ключ, книга, гл, ст)
    if най and най[0][0] >= ПРАГ:
        return {'ref': f'{най[1]}.{най[2]}:{най[3]}',
                'score': round(най[0][0], 3)}
    return None


def ръчни() -> list[tuple[str, str]]:
    """(начало на текста, препратка) — виж input/prokimen_refs_manual.csv.

    ⚠⚠ РЪЧНИТЕ ИМАТ ПРЕВЕС. Две неща убягват на съпоставителя по
    устройство: прокимен, който обхваща ДВА стиха (Магнификатът е
    Лк. 1:46-47, а се сравнява стих по стих), и богослужебна форма в
    МНОЖЕСТВЕНО число („Души их… водворятся" срещу „Душа его…
    водворится"). И в двата случая препратката е вярна и се сверява на
    ръка срещу базата — виж бележката в самия файл.
    """
    п = РАБОТА.parent / 'input' / 'prokimen_refs_manual.csv'
    if not п.exists():
        return []
    with п.open(encoding='utf-8') as f:
        return [(r['text_starts'], r['ref']) for r in csv.DictReader(f)]


def main() -> None:
    поправки = ръчни()

    def ръчна(текст: str) -> str | None:
        for нач, ref in поправки:
            if текст.startswith(нач):
                return ref
        return None

    индекс = стихове()
    от_префикс = построй_указател(индекс)
    print(f'стихове в СЗ (цс): {len(индекс)}')
    данни = json.loads((РАБОТА / 'prokimen_raw.json').read_text(encoding='utf-8'))
    общо = намерени = 0
    for r in данни:
        for k in r['prokimena'] + ([r['alliluia']] if 'alliluia' in r else []):
            for поле, текст in [('ref', k['text'])]:
                общо += 1
                r_ръчна = ръчна(текст)
                m = ({'ref': r_ръчна, 'score': 1.0} if r_ръчна
                     else намери(текст, индекс, от_префикс))
                if m:
                    намерени += 1
                    k['ref'], k['score'] = m['ref'], m['score']
            k['verse_refs'] = []
            for v in k['verses']:
                общо += 1
                r_ръчна = ръчна(v)
                m = ({'ref': r_ръчна, 'score': 1.0} if r_ръчна
                     else намери(v, индекс, от_префикс))
                k['verse_refs'].append(m)
                if m:
                    намерени += 1
    (РАБОТА / 'prokimen_refs.json').write_text(
        json.dumps(данни, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f'текстове: {общо} | намерени в Писанието: {намерени} '
          f'({намерени * 100 // общо}%)')


if __name__ == '__main__':
    main()

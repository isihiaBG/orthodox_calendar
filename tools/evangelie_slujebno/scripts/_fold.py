"""Сгъване на църковнославянски текст до съпоставим вид.

⚠ ДВЕТЕ ГРАФИКИ са една и съща реч, записана различно: базата пази цс
писмо (`ꙋ`, `ѧ`, `ѡ`, титли), а книгата с прокимените — същия текст с
гражданска азбука и ударения. Затова се сгъват ДО ОБЩ ВИД, а не се
превежда едното в другото.

⚠⚠ КОНТРАКЦИИТЕ ПОД ТИТЛА СА ПОДНИЗ на пълната дума — „гди" ⊂ „господи",
„млть" ⊂ „милость", „бгъ" ⊂ „богъ". Оттам [дума_съвпада] няма нужда от
речник на nomina sacra: проверява се дали по-късата е подниз на по-дългата
при еднакви първа и последна буква. Речник би бил краен списък, който
утре ще пропусне съкращение, каквото не сме видели.
"""
import re
import unicodedata as ud

КАРТА = str.maketrans({
    'ꙋ': 'у', 'ѹ': 'у', 'ᲂ': 'о', 'ѡ': 'о', 'ѣ': 'е', 'ѧ': 'я', 'ѩ': 'я',
    'ѫ': 'у', 'і': 'и', 'ї': 'и', 'ѵ': 'и', 'ѳ': 'ф', 'ѕ': 'з', 'ꙗ': 'я',
    'є': 'е', 'ѯ': 'к', 'ѱ': 'п', 'ѻ': 'о', 'ѽ': 'о', 'ѡ': 'о',
})


def сгъни(s: str) -> list[str]:
    """Текстът → списък сгънати думи."""
    s = ud.normalize('NFD', s)
    s = ''.join(c for c in s if not ud.combining(c))
    s = s.lower().translate(КАРТА).replace('ѿ', 'от')
    s = re.sub(r'[^а-я]+', ' ', s)
    # ⚠ „оу" в начало на дума е ЕДИН звук (ᲂу҆пова́хомъ = уповахом).
    s = re.sub(r'\bоу', 'у', s)
    s = re.sub(r'ъ\b', '', s)
    return [w for w in s.split() if w]


def подниз(кратка: str, дълга: str) -> bool:
    """Буквите на `кратка` се срещат в `дълга` в същия ред."""
    it = iter(дълга)
    return all(c in it for c in кратка)


def дума_съвпада(a: str, b: str) -> bool:
    if a == b:
        return True
    кратка, дълга = (a, b) if len(a) <= len(b) else (b, a)
    if len(кратка) < 2:
        return False
    # ⚠ СЪВПАДЕНИЕ ПО СТЪБЛО — за граматическите форми („господи" срещу
    # „господь", „твоѧ̑" срещу „твое"). Иска ЧЕТИРИ общи букви в началото и
    # двете думи да са поне толкова дълги, тъй че „во" не може да мине за
    # „воскликновение". Без него строгото правило по-долу губеше 29 стиха.
    if len(кратка) >= 4 and кратка[:4] == дълга[:4]:
        return True
    # ⚠⚠ КОНТРАКЦИЯТА ПОД ТИТЛА ПАЗИ ПЪРВАТА И ПОСЛЕДНАТА БУКВА — така е
    # устроена („гди" ⊂ „господи", „млть" ⊂ „милость", „нбса" ⊂ „небеса").
    # Само първата НЕ стига: „во" минаваше за контракция на
    # „воскликновение" и отрязването свършваше насред дума — прокименът на
    # Преображение („Блажени людие ведущии восклиновение") се режеше на
    # „…восклиновение: Господи, во". (11.09.2026.)
    if кратка[0] != дълга[0] or кратка[-1] != дълга[-1]:
        return False
    # ⚠ И долна граница за ДЯЛА: най-съкратената истинска контракция е
    # „гди"/„господи" — 0,43. Под 0,35 не е съкращение, а съвпадение.
    if len(кратка) / len(дълга) < 0.35:
        return False
    return подниз(кратка, дълга)


def прилика(a: list[str], b: list[str]) -> float:
    """Дял на думите от `a`, намерени в `b` ПО РЕД."""
    if not a:
        return 0.0
    j = 0
    съвп = 0
    for w in a:
        # ⚠⚠ НЕНАМЕРЕНАТА ДУМА НЕ БИВА ДА ИЗЯЖДА КУРСОРА. Първата версия
        # оставяше `j` на края и оттам НИЩО след нея не съвпадаше — една
        # излишна дума в прокимена („Спаси, ГОСПОДИ, люди Твоя" срещу
        # „Спаси люди твоя") сваляше приликата от 0,88 на 0,125 и стихът
        # изглеждаше ненамерен. Затова курсорът се връща при неуспех.
        k = j
        while k < len(b) and not дума_съвпада(w, b[k]):
            k += 1
        if k < len(b):
            съвп += 1
            j = k + 1
    return съвп / len(a)

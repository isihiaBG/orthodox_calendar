"""Измерва ОТРЯЗВАНЕТО на прокимена спрямо стиха, за всеки език.

  python3 07_prokimen_trim.py        # → work/prokimen_trim.json

⚠⚠ ПРОКИМЕНЪТ Е БИБЛЕЙСКИ ЦИТАТ С ОТРЯЗВАНЕ, не свой текст. Затова се
адресира точно като запазените цитати — `Ps.88:6(0;34)`: стих, отрязано
отпред, отрязано отзад (виж [QuoteAnchor] и bible_ref.dart).

⚠ Отрязването се брои в ЗНАЦИ, а те са различни във всеки превод — тъй че
се мери ЗА ВСЕКИ ЕЗИК поотделно. За църковнославянския е точно (текстът на
прокимена е същият, само в друга графика); за останалите се извежда от
границите на изреченските части.
"""
import json
import pathlib
import re
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _fold import дума_съвпада, прилика, сгъни  # noqa: E402

КОРЕН = pathlib.Path(__file__).resolve().parents[3]
РАБОТА = pathlib.Path(__file__).resolve().parents[1] / 'work'

# ⚠⚠ КОМБИНИРАЩИТЕ ЗНАЦИ СА ЧАСТ ОТ ДУМАТА. `\w` НЕ ги брои за буква
# (те не са alnum), тъй че „ро́дѣ" се режеше на „ро" и „дѣ" и краят на
# отрязването падаше насред думата. Затова класът изброява и диапазоните
# на ударенията, титлите и надредните букви на църковнославянския.
RE_ДУМА = re.compile(
    r'(?:[^\W\d_]|[\u0300-\u036f\u0483-\u0489\u2de0-\u2dff\ua66f])+',
    re.UNICODE)


def думи_с_места(текст: str) -> list[tuple[str, int, int]]:
    """(сгъната дума, начало, край) за всяка дума в текста."""
    вън = []
    for m in RE_ДУМА.finditer(текст):
        с = сгъни(m.group(0))
        if с:
            вън.append((с[0], m.start(), m.end()))
    return вън


def отрежи(прокимен: str, стих: str) -> tuple[int, int] | None:
    """(отрязано отпред, отрязано отзад) в знаци на `стих`.

    ⚠⚠ И НАЧАЛОТО, И КРАЯТ СЕ ИЗБИРАТ ОТ ВСИЧКИ СРЕЩАНИЯ, не първото и
    последното. Прокименът често е ПОЛОВИНА от стиха, а думите му се
    повтарят:

      Пс. 26:1  „Госпо́дь защи́титель живота́ моего́" е ВТОРАТА половина, а
                стихът започва със същата дума („Гдⷭ҇ь просвѣще́нїе моѐ…")
      Пс. 27:1  „…ѿ менє̀ {ѡ҆ мнѣ̀}: да не когда̀ премолчи́ши ѿ менє̀…" —
                краят се повтаря дословно

    Взето първото/последното, отрязването хващаше ту чужда половина, ту
    повторението, и се късаше насред скобата. (Забелязано от потребителя,
    13.09.2026.)

    ⚠ Затова се пробват ВСИЧКИ двойки (начало, край) и печели онази с
    най-добро съвпадение по съдържание; при равенство — по-близката по
    БРОЙ ДУМИ до прокимена.
    """
    цел = сгъни(прокимен)
    места = думи_с_места(стих)
    if not цел or not места:
        return None
    начала = [i for i, (w, _, _) in enumerate(места)
              if дума_съвпада(цел[0], w)]
    краища = [i for i, (w, _, _) in enumerate(места)
              if дума_съвпада(цел[-1], w)]
    if not начала or not краища:
        return None

    най = None
    for i in начала:
        for j in краища:
            if j < i:
                continue
            обхват = [w for w, _, _ in места[i:j + 1]]
            # ⚠ ДВУПОСОЧНО: колко от прокимена е в обхвата И колко от
            # обхвата е в прокимена. Само първото пуска твърде дълъг
            # обхват; само второто — твърде къс.
            оценка = (прилика(цел, обхват) + прилика(обхват, цел)) / 2
            ключ = (round(оценка, 3), -abs(len(обхват) - len(цел)))
            if най is None or ключ > най[0]:
                най = (ключ, i, j)
    if най is None or най[0][0] < 0.6:
        return None
    _, i, j = най
    начало, край = места[i][1], места[j][2]
    # ⚠ Опашката от пунктуация се брои за НУЛА — същото правило като при
    # запазените цитати: маркиран цял стих не бива да дава „(0;1)" заради
    # точката накрая.
    if not стих[край:].strip(' .,;:!?«»"—-'):
        край = len(стих)
    if not стих[:начало].strip(' .,;:«»"—-'):
        начало = 0
    return начало, len(стих) - край


def стихове(език: str) -> dict[str, str]:
    db = sqlite3.connect(КОРЕН / 'assets/db/bible.db')
    return {f'{k}.{g}:{s}': t for k, g, s, t in db.execute(
        "SELECT book, chapter, verse, text FROM verses WHERE lang = ?",
        (език,))}


def всички_текстове(данни):
    """(запис, поле, текст, ref) за всеки прокимен/стих/алилуя с препратка."""
    for r in данни:
        за = r['prokimena'] + ([r['alliluia']] if 'alliluia' in r else [])
        for k in за:
            if k.get('ref'):
                yield k, 'ref', k['text'], k['ref']
            for i, (v, m) in enumerate(zip(k['verses'],
                                           k.get('verse_refs', []))):
                if m:
                    yield k, f'verse{i}', v, m['ref']


def main() -> None:
    данни = json.loads(
        (РАБОТА / 'prokimen_refs.json').read_text(encoding='utf-8'))
    цс = стихове('utfcs')
    общо = ok = цели = 0
    for k, поле, текст, ref in всички_текстове(данни):
        общо += 1
        стих = цс.get(ref)
        if not стих:
            continue
        r = отрежи(текст, стих)
        if r is None:
            continue
        ok += 1
        if r == (0, 0):
            цели += 1
        k.setdefault('trim', {})[поле] = {'utfcs': list(r)}
    (РАБОТА / 'prokimen_trim.json').write_text(
        json.dumps(данни, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f'текстове с препратка: {общо}')
    print(f'  отрязване измерено : {ok} ({ok * 100 // общо}%)')
    print(f'  от тях ЦЕЛИЯТ стих : {цели}')
    print('→ work/prokimen_trim.json')


if __name__ == '__main__':
    main()

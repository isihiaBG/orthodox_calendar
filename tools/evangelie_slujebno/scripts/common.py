#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Общото за двата извора — четене на .epub и разчитане на едно четиво.

⚠ И двете книги адресират четивата САМО по зачало („Евангелие Луки, зачало
54"). Глава и стих няма никъде. Мостът към нашия текст минава през таблицата
`zachala` в `bible.db` — виж CLAUDE.md, „Зачалата — свойство на МЯСТОТО".
"""

import html
import re
import zipfile
from pathlib import Path

ВХОД = Path(__file__).resolve().parents[1] / 'input'

# ⚠ СТРУКТУРНИЯТ ПРИЗНАК: рубриката („На литургии", „В понедельник") е винаги
# <span class="color-red">, а самото четиво я следва като гол текст. Тъй че
# блокът се реже по червените отрязъци, а не по думи.
RE_БЛОК = re.compile(r'<div class="paragraph"[^>]*>(.*?)</div>', re.S)
RE_ЧЕРВЕНО = re.compile(r'<span class="color-red">(.*?)</span>', re.S)
RE_ТАГ = re.compile(r'<[^>]+>')

# Евангелистите стоят в родителен падеж. „Иоанна" се среща и като име на
# светия, тъй че разпознаването е ВИНАГИ в двойка със „зачало".
ЕВАНГЕЛИСТИ = {'матфеа': 'Мф', 'марка': 'Мк', 'луки': 'Лк', 'иоанна': 'Ин'}

# Апостолските книги, както ги нарича книгата („апостол к римляном").
# Ключът е свит до първата значеща дума, за да не се блъскаме в падежите.
RE_ЗАЧАЛО = re.compile(
    r'(?:(' + '|'.join(ЕВАНГЕЛИСТИ) + r')\s*,?\s*)?'
    r'зачал[оа]\s*'
    r'(\d+)\s*([А-В])?'          # 10, 10А, 65В
    r'(?:\s*[–-]\s*(\d+))?'      # 105–106
    r'(\s*от\s+полу)?',
    re.I)


def текст(html_фрагмент: str) -> str:
    т = RE_ТАГ.sub('', html_фрагмент)
    return re.sub(r'\s+', ' ', html.unescape(т)).strip()


class Книга:
    """Един .epub с указателя му."""

    def __init__(self, шаблон: str):
        път = next(p for p in ВХОД.glob('*.epub') if шаблон in p.name)
        self.име = път.name
        self.z = zipfile.ZipFile(път)
        ncx = self.z.read('toc.ncx').decode('utf-8')
        self.записи = []          # [(етикет, файл)] по реда на съдържанието
        for t, s in re.findall(
                r'<navPoint[^>]*>.*?<text>(.*?)</text>.*?src="([^"]+)"', ncx, re.S):
            self.записи.append((re.sub(r'\s+', ' ', html.unescape(t)).strip(),
                                s.split('#')[0]))
        self._имена = self.z.namelist()

    def html_на(self, файл: str) -> str:
        цел = next(n for n in self._имена if n.endswith(файл))
        return self.z.read(цел).decode('utf-8', 'replace')

    def блокове(self, файл: str):
        """Блоковете на един файл, всеки разцепен на (рубрика, текст) двойки.

        Блок без червено се връща като една двойка с празна рубрика — така
        заглавията на дните („1. Начало индикта…") минават по същия път.
        """
        for сурово in RE_БЛОК.findall(self.html_на(файл)):
            части, край = [], 0
            for m in RE_ЧЕРВЕНО.finditer(сурово):
                if m.start() > край:
                    части.append((None, текст(сурово[край:m.start()])))
                части.append((текст(m.group(1)), None))
                край = m.end()
            if край < len(сурово):
                части.append((None, текст(сурово[край:])))
            # сглобяване: всяка рубрика поема текста ВЕДНАГА след себе си
            двойки, рубрика = [], ''
            for вид, стойност in части:
                if вид is not None:
                    if рубрика:
                        двойки.append((рубрика, ''))
                    рубрика = вид
                elif стойност:
                    двойки.append((рубрика, стойност))
                    рубрика = ''
            if рубрика:
                двойки.append((рубрика, ''))
            if двойки:
                yield двойки


def четива(текст_на_четивото: str, подразбиращ_се=None):
    """„Луки, зачало 13." → [{'ев':'Лк','зачало':13,…}].

    ⚠ Евангелистът може да ЛИПСВА при второто четиво в изречение („зачало 63,
    или Иоанна, зачало 52" носи и двете, но „Матфеа, зачало 39" в съседен ред
    не повтаря името). Тогава се наследява последният срещнат.
    """
    навън, последен = [], подразбиращ_се
    for m in RE_ЗАЧАЛО.finditer(текст_на_четивото):
        ев, номер, буква, докъде, от_полу = m.groups()
        if ев:
            последен = ЕВАНГЕЛИСТИ[ев.lower()]
        навън.append({
            'ев': последен,
            'зачало': int(номер),
            'част': буква or '',
            'до': int(докъде) if докъде else None,
            'от_полу': bool(от_полу),
        })
    return навън

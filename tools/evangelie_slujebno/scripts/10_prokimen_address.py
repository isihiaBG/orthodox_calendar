#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Дава АДРЕС на всеки дял с прокимен. Без мрежа.

    python3 10_prokimen_address.py     # → work/prokimen_addressed.json

⚠⚠ АДРЕСЪТ Е ЕДИНСТВЕНИЯТ НАЧИН ДА СЕ ПОКАЖЕ ПРОКИМЕНЪТ. Мерено: 110
зачала носят прокимен, а 40 от тях имат РАЗЛИЧНИ прокимени според паметта
(Евр. зач. 318 носи осем). Прокименът принадлежи на ПАМЕТТА, не на
четивото — за разлика от обръщението „Братя,", което е свойство на
зачалото.

⚠ МЕСЕЧНОТО ЗАГЛАВИЕ („Месяц сентябрь") САМО НЯМА ПРОКИМЕН, тъй че отпада
от `prokimen_raw.json` и с него се губи контекстът за числата подире му.
Затова адресът се смята ТУК, при обхождане на съдържанието ПО РЕД, а не от
готовия json.

Видове адрес (същите, с които се адресира и Теофан — виж CLAUDE.md):

    fixed   „ММ-ДД"   църковна дата от месецослова
    tone    „1".."8"  възкресен прокимен по глас
    weekday „1".."7"  делничен, понеделник=1
    common  ключ      обща служба по чин (светител, мъченик…)
    anchor  име       подвижен спрямо неподвижен празник („[зри] …")
    pascha  име       подвижен спрямо Пасха (Триод и Пентикостар)
"""
import html
import json
import pathlib
import re
import zipfile

ГНЕЗДО = pathlib.Path(__file__).resolve().parents[1]
КНИГА = ГНЕЗДО / 'input' / 'Прокимны и аллилуарии без сокращений.gen.epub'

МЕСЕЦИ = {'сентябрь': 9, 'октябрь': 10, 'ноябрь': 11, 'декабрь': 12,
          'январь': 1, 'февраль': 2, 'март': 3, 'апрель': 4, 'май': 5,
          'июнь': 6, 'июль': 7, 'август': 8}
ДНИ = {'понедельник': 1, 'вторник': 2, 'среду': 3, 'четверток': 4,
       'пяток': 5, 'субботу': 6}

# ⚠ Ключовете на общите служби са МАШИННИ и се свързват с ранга на светията
# в календара (виж „картата ранг → общ чин" в задачите). Руското заглавие се
# пази до тях, за да личи откъде идва.
ОБЩИ = {
    'Служба Пресвятей Богородице': 'bogorodica',
    'Служба святым Небесным Безплотным Силам': 'bezplotni',
    'Служба святым пророком обща': 'prorok',
    'Служба святым Апостолом обща': 'apostol',
    'Служба святителю единому': 'svetitel',
    'Служба святителей обща': 'svetiteli',
    'Служба преподобных, и Христа ради юродивых обща': 'prepodoben',
    'Служба мученика': 'machenik',
    'Служба мучеников обща': 'machenici',
    'Служба священномученика': 'svshtmachenik',
    'Служба священномучеников обща': 'svshtmachenici',
    'Служба преподобномучеников обща.': 'prpmachenici',
    'Служба святых мучениц обща': 'machenici_zheni',
    'Служба преподобных жен обща': 'prepodobni_zheni',
    'Служба исповедников': 'izpovednik',
    'Служба безмездников': 'bezsrebrenik',
    'Служба за мертвыя': 'za_umrelite',
}


def заглавия() -> list[str]:
    """Заглавията от съдържанието, ПО РЕД."""
    z = zipfile.ZipFile(КНИГА)
    toc = z.read('toc.ncx').decode('utf-8', errors='replace')
    return [html.unescape(t.strip()) for t in
            re.findall(r'<navPoint.*?<text>(.*?)</text>', toc, re.S)]


def адреси() -> list[tuple[str, str, str]]:
    """(заглавие, вид, стойност) ПО РЕД.

    ⚠⚠ СПИСЪК, НЕ РЕЧНИК ПО ЗАГЛАВИЕ. Три заглавия се повтарят в книгата —
    „В субботу" (веднъж в Пентикостара, веднъж сред делничните), „На
    литургии" и „8. Святаго великомученика Феодора Стратилата" (юни и
    февруари). Речник по заглавие слепваше двойките и по-късната изяждаше
    по-ранната: делничните прокимени излизаха ПЕТ вместо шест, без нищо да
    гръмне.
    """
    вън: list[tuple[str, str, str]] = []
    месец = None
    треби = False
    for t in заглавия():
        # ⚠ Требите („На крещение человеков", „В нашествии брани") НЕ са
        # памети и нямат място в календара. Разпознават се по дяла, в който
        # влизат, а не по име: имената им нямат общ признак.
        if t.startswith('Прокимени, апостоли и аллилуиаре на всяку потребу'):
            треби = True
            continue
        if треби:
            continue
        m = re.match(r'^Месяц\s+(\w+)', t)
        if m:
            месец = МЕСЕЦИ.get(m.group(1).lower())
            continue
        m = re.match(r'^(\d+)\.\s', t)
        if m and месец:
            вън.append((t, 'fixed', '%02d-%02d' % (месец, int(m.group(1)))))
            continue
        m = re.match(r'^Глас\s+(\d)$', t)
        if m:
            вън.append((t, 'tone', m.group(1)))
            continue
        m = re.match(r'^Во?\s+(\w+)$', t)
        if m and m.group(1).lower() in ДНИ:
            вън.append((t, 'weekday', str(ДНИ[m.group(1).lower()])))
            continue
        if t in ОБЩИ:
            вън.append((t, 'common', ОБЩИ[t]))
            continue
        if t.startswith('[зри]'):
            вън.append((t, 'anchor', t[5:].strip()))
            continue
        вън.append((t, 'pascha', t))
    return вън


def main() -> None:
    карта = адреси()
    данни = json.loads(
        (ГНЕЗДО / 'work/prokimen_trim.json').read_text(encoding='utf-8'))
    по_вид: dict[str, int] = {}
    без = []
    # ⚠ И двете страни се обхождат ПО РЕД, тъй че повтарящо се заглавие
    # получава своя адрес, а не адреса на съименника си. `prokimen_trim`
    # пази реда на съдържанието (виж 05_prokimen_extract.py).
    следващ = 0
    for r in данни:
        вид = стойност = ''
        for i in range(следващ, len(карта)):
            if карта[i][0] == r['title']:
                _, вид, стойност = карта[i]
                следващ = i + 1
                break
        if not вид:
            без.append(r['title'])
            continue
        r['addr_kind'], r['addr'] = вид, стойност
        по_вид[вид] = по_вид.get(вид, 0) + 1
    (ГНЕЗДО / 'work/prokimen_addressed.json').write_text(
        json.dumps(данни, ensure_ascii=False, indent=1), encoding='utf-8')
    print('дялове с прокимен: %d' % len(данни))
    for k in sorted(по_вид, key=lambda x: -по_вид[x]):
        print('   %-9s %d' % (k, по_вид[k]))
    print('без адрес (треби и подобни): %d' % len(без))
    print('→ work/prokimen_addressed.json')


if __name__ == '__main__':
    main()

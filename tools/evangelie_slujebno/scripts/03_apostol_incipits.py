#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""03_apostol_incipits.py — с какво обръщение започва всяко зачало на Апостола.

    input/Апостол…epub  →  work/apostol_incipits.csv

⚠⚠ ЗАЩО ИЗОБЩО. Когато апостолското четиво се чете богослужебно, отпред се
добавя обръщение — „Братие,". Библейският текст го НЯМА, тъй че при показване
трябва да се добави. Сверено дословно:

    Апостол   „Бра́тие, егда́ прии́де Петр во Антиохи́ю…"
    bible.db  „[Заⷱ҇ 202] Є҆гда́ же прїи́де пе́тръ…"

⚠⚠ ОБРЪЩЕНИЯТА СА СЕДЕМ, НЕ ЕДНО. Затова таблицата пази ФОРМУЛАТА, а не флаг
0/1: „Братие" покрива 258 зачала, но има и „Чадо Тимофее" (24), „Возлюбленнии"
(18), „Чадо Тите" (4), а Деянията вървят с „Во дни оны" (53).

⚠ „Павел, посланник…", „Иаков, раб Божий…" и подобните НЕ СА добавка — те са
самите първи думи на посланието. Разпознават се и се отбелязват като `—`.

⚠⚠ ОТДЕЛНО И ОЩЕ НЕРЕШЕНО: богослужебният текст маха и свързващата частица
(„Егда ЖЕ прииде" → „егда прииде"), защото четивото започва наново. Това е
по-дълбока обработка от добавяне на префикс и тук НЕ се пипа — записва се
само обръщението.

⚠ Правилото важи САМО за Апостола. Евангелията имат свои формули („Во время
оно"), но потребителят изрично каза, че за тях добавка не се прави.
"""

import csv
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import Книга, текст

ИЗХОД = Path(__file__).resolve().parents[1] / 'work' / 'apostol_incipits.csv'

# ⚠ Редът има значение: „Чадо Тимофее" трябва да се пробва ПРЕДИ „Чадо".
ФОРМУЛИ = [
    ('Братие', 'Братя'),
    ('Чадо Тимофее', 'Чедо Тимотее'),
    ('Чадо Тите', 'Чедо Тите'),
    ('Возлюбленнии', 'Възлюбени'),
    ('Возлюбленне', 'Възлюбени'),
    ('Во дни оны', 'В ония дни'),
]

# Първите думи на самите послания — НЕ са добавка.
СОБСТВЕНИ = ('Павел', 'Иаков', 'Петр', 'Симон', 'Иуда', 'Иоанн', 'Старец')

КНИГИ = [
    ('Деяния святых Апостол', 'Act'),
    ('Соборное послание ИАКОВЛЕ', 'Jac'),
    ('Соборное послание 1-е св. Ап. Петра', '1Pet'),
    ('Соборное послание 2-е св. Ап. Петра', '2Pet'),
    ('Соборное послание 1-е св. Ап. Иоанна Богослова', '1Jn'),
    ('Соборное послание 2-е св. Ап. Иоанна Богослова', '2Jn'),
    ('Соборное послание 3-е св. Ап. Иоанна Богослова', '3Jn'),
    ('Соборное послание Иудино', 'Juda'),
    ('К римляном послание св. Ап. Павла', 'Rom'),
    ('К коринфяном 1-е послание св. Ап. Павла', '1Cor'),
    ('К коринфяном 2-е послание св. Ап. Павла', '2Cor'),
    ('К галатом послание св. Ап. Павла', 'Gal'),
    ('Ко ефесеем послание св. Ап. Павла', 'Eph'),
    ('К филипписием послание св. Ап. Павла', 'Phil'),
    ('К колоссаем послание св. Ап. Павла', 'Col'),
    ('К солуняном 1-е послание св. Ап. Павла', '1Thes'),
    ('К солуняном 2-е послание св. Ап. Павла', '2Thes'),
    ('К Тимофею 1-е послание св. Ап. Павла', '1Tim'),
    ('К Тимофею 2-е послание св. Ап. Павла', '2Tim'),
    ('К Титу послание св. Ап. Павла', 'Tit'),
    ('К Филимону послание св. Ап. Павла', 'Phlm'),
    ('Ко евреем послание св. Ап. Павла', 'Hebr'),
]

RE_ЗАЧ = re.compile(r'Зачало (\d+)([А-Я])?(?: \(.*\))?$')


def без_ударения(s: str) -> str:
    s = unicodedata.normalize('NFD', s)
    return ''.join(c for c in s if not unicodedata.combining(c))


def main():
    к = Книга('Апостол')
    имена = [t for t, _ in к.записи]
    граници = {}
    for заглавие, код in КНИГИ:
        if заглавие in имена:
            граници[код] = имена.index(заглавие)
    подредени = sorted(граници.items(), key=lambda kv: kv[1])

    редове = []
    видени = set()
    for n, (код, старт) in enumerate(подредени):
        край = подредени[n + 1][1] if n + 1 < len(подредени) else len(имена)
        for t, ф in к.записи[старт + 1:край]:
            m = RE_ЗАЧ.match(t)
            if not m or (код, ф) in видени:
                continue
            видени.add((код, ф))
            тк = текст(к.html_на(ф))
            i = тк.find('Зачало')
            тяло = re.sub(r'^Зачало\s*\d+[А-Я]?\s*', '', тк[i:] if i >= 0 else тк)
            тяло = re.sub(r'^\([^)]*\)\s*', '', тяло)   # „(Неделя первая поста,…)"
            гол = без_ударения(тяло)
            csl = bg = ''
            for цсл, бг in ФОРМУЛИ:
                if гол.startswith(цсл):
                    csl, bg = цсл, бг
                    break
            собствено = not csl and гол.startswith(СОБСТВЕНИ)
            редове.append({
                'book': код,
                'zachalo': int(m.group(1)),
                'part': m.group(2) or '',
                'csl': csl,
                'bg': bg,
                'own_start': '1' if собствено else '',
                'incipit': ' '.join(тяло.split()[:6]),
            })

    # ⚠⚠ ЕДНО ЗАЧАЛО СЕ ЯВЯВА ПО НЯКОЛКО ПЪТИ в съдържанието — по веднъж за
    # всяка своя употреба („Зачало 1 (Во святую и великую неделю Пасхи)" и
    # „Зачало 1 (На Вознесение Господне)"). Текстът е един и същ, тъй че се
    # пази първото срещане; инак таблицата носи дублирани ключове.
    уникални = {}
    for r in редове:
        ключ = (r['book'], r['zachalo'], r['part'])
        уникални.setdefault(ключ, r)
    редове = list(уникални.values())

    ИЗХОД.parent.mkdir(parents=True, exist_ok=True)
    with open(ИЗХОД, 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=[
            'book', 'zachalo', 'part', 'csl', 'bg', 'own_start', 'incipit'],
            delimiter='|')
        w.writeheader()
        w.writerows(редове)

    from collections import Counter
    по_формула = Counter(r['csl'] or ('(свое начало)' if r['own_start'] else '—')
                         for r in редове)
    print(f"зачала: {len(редове)}  в {len(подредени)} книги\n")
    for ф, c in по_формула.most_common():
        print(f"  {c:>4}  {ф}")
    print(f"\n→ {ИЗХОД}")


if __name__ == '__main__':
    main()

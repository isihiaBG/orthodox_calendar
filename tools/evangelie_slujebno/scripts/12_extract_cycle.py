# само цикълът, който е покрит ЦЯЛ — от началото на Триода 2026 нататък.
#
# ⚠ Неподвижният пласт НЕ се ограничава: той е по църковна дата и всяка
# дата е добре дошла, от която и година да идва.
ЦИКЪЛ_ОТ = datetime.date(2026, 2, 1)

# ⚠⚠ АПОСТОЛЪТ И ЕВАНГЕЛИЕТО ИМАТ ОТДЕЛНИ БРОЯЧИ.
#
# Уставът (§1.7, „Отступки и преступки рядовых чтений Евангелия"):
#
#   „След Неделя по Въздвижение започва редът от Лука: веднага се четат
#    редовите евангелия на 18-та седмица (в понеделник — Лк. зач. 10), и
#    нататък по ред." — НЕЗАВИСИМО какъв номер има тази неделя.
#
# Апостолът върви непрекъснато. Оттам въпросът, който самият Устав дава за
# пример: „защо в календара пише 16-та седмица, а евангелията са на 18-та?"
#
# ⚠ Ключовият ден е НЕДЕЛЯТА ПО Въздвижение, не празникът: падне ли
# Въздвижение в неделя, преступката е чак след седмица.
#
# ⚠⚠ ПРЕЗ 2026 Г. ДВЕТЕ СЪВПАДАТ (Неделята по Въздвижение е 18-та), тъй че
# данните НЕ могат да издадат правилото — то се вгражда, а не се извлича.
# Точно затова ключът тук е РАЗДЕЛЕН: инак съвпадението на една година се
# вкаменява като „същия адрес" за всички.
ВЪЗДВИЖЕНИЕ_СЕДМИЦА = 18


def неделя_по_въздвижение(година: int) -> datetime.date:
    """Първата неделя СЛЕД Въздвижение (църковна 09-14)."""
    празник = datetime.date(година, 9, 14) + datetime.timedelta(days=13)
    напред = (7 - празник.isoweekday()) % 7
    # ⚠ Падне ли празникът в неделя, се взима СЛЕДВАЩАТА — „преступката се
    # извършва не веднага на другия ден, а чак след седмица" (Устав).
    return празник + datetime.timedelta(days=напред or 7)


ЦИКЪЛ_СЕДМИЦИ = 17          # редовият кръг преди Въздвижение


def евангелска_седмица(дт: datetime.date, седмица: int) -> int | None:
    """Номерът за ЕВАНГЕЛИЕТО, или None ако денят е в зоната на ОТСТЪПКАТА.

    ⚠⚠ ЗОНАТА НА ОТСТЪПКАТА СЕ ИЗХВЪРЛЯ, а не се вписва. Там четивата в
    нашия извор са СГРЕШЕНИ — превъртат на седмица 1 вместо да повторят
    седмица 11 (сверено с календара на Kotyuk за 2026 и с още един). Вписани,
    те щяха да заемат индекс 18 и да изместят истинските Лукини четива.
    Правилното съдържание идва от седмица 11, която вече е в указателя от
    август; попълването става в приложението (виж [gospelWeekFor]).
    """
    # ⚠ Неделите НЕ участват в скока — виж [gospelWeekFor] в приложението.
    if дт.isoweekday() == 7:
        return седмица
    # ⚠⚠ НЕДЕЛЯТА ОТ ТАЗИ ЦЪРКОВНА ГОДИНА, не от гражданската. Църковната
    # година тече от Пасха до Пасха, тъй че за ден през януари меродавна е
    # неделята от ПРЕДНАТА есен. Без това всеки януарски ден се сравняваше с
    # неделята чак през септември, излизаше „преди Въздвижение" с номер над
    # 30 и се ИЗХВЪРЛЯШЕ като зона на отстъпката — цял месец четива изчезваха
    # мълчаливо. (Същият бъг вече беше поправен в Dart; тук не.)
    пасх_год = дт.year if дт >= ПАСХА[дт.year] else дт.year - 1
    н = неделя_по_въздвижение(пасх_год)
    if дт > н:
        подир = (дт - н).days
        return ВЪЗДВИЖЕНИЕ_СЕДМИЦА + (подир - 1) // 7
    # ⚠ В неделите отстъпка няма (Устав) — номерът им се запазва.
    if седмица > ЦИКЪЛ_СЕДМИЦИ:
        return None
    return седмица

# Етикет пред четивото („На свт.: ", „Веч.: ") — значи, че четивото е на
# ПАМЕТТА или на определена служба, а не редовото за деня.
RE_ЕТИКЕТ = re.compile(r'^([^:]{1,44}):\s+(?=\S)')

# ⚠⚠ ЗАКОТВЕНИ ЧЕТИВА — трети пласт, нито подвижен, нито неподвижен.
#
# „Събота по Въздвижение", „Неделя пред Рождество" и подобните се местят с
# ДЕНЯ ОТ СЕДМИЦАТА на празника: тази година съботата подир Въздвижение е
# 3 октомври, догодина ще е друга дата. Вписани по ЦЪРКОВНА дата (както
# правех отначало), те се заковават за случайното число на една година.
#
# ⚠ Поводът: потребителят посочи, че на 3.X.2026 евангелието е „на събота
# след Въздвижение", а не от седмичния кръг. (11.09.2026.)
#
# ⚠ Ключът е (празник, ден, преди/след). Празникът се дава с ЦЪРКОВНА дата,
# за да важи и за двата стила.
ЗАКОТВЕНИ = {
    'На събота преди Въздвижение': ('09-14', 6, 'before'),
    'На нед. преди Въздвижение':   ('09-14', 7, 'before'),
    'На събота след Въздвижние':   ('09-14', 6, 'after'),
    'На нед. след Въздвижение':    ('09-14', 7, 'after'),
    'На събота преди Рожд.':       ('12-25', 6, 'before'),
    'На събота след Рожд.':        ('12-25', 6, 'after'),
    'На нед. след Рожд.':          ('12-25', 7, 'after'),
    'На събота преди Богоявл.':    ('01-06', 6, 'before'),
    'На нед. преди Богоявл.':      ('01-06', 7, 'before'),
    'На събота след Богоявл.':     ('01-06', 6, 'after'),
    'На нед. след Богоявл.':       ('01-06', 7, 'after'),
}


def адрес(дт: datetime.date) -> tuple[str, int, int]:
    """(дял, седмица, ден) — литургичният адрес.

    ⚠⚠ ТРИОДЪТ ИМА ПРЕВЕС. Последните 70 дни преди Пасха вече не са „по
    Петдесетница", макар броенето от предната Пасха да продължава — инак
    излизат 44 седмици, каквито година няма.
    """
    сл = ПАСХА[дт.year] if дт <= ПАСХА[дт.year] else ПАСХА[дт.year + 1]
    до = (сл - дт).days
    if 0 < до <= 70:
        return ('T', (70 - до) // 7 + 1, дт.isoweekday())
    пр = ПАСХА[дт.year] if дт >= ПАСХА[дт.year] else ПАСХА[дт.year - 1]
    n = (дт - пр).days
    # ⚠ Петдесетница (Пасха+49) е ПОСЛЕДНИЯТ ден на Пентикостара.
    if n <= 49:
        return ('P', n // 7 + 1, дт.isoweekday())
    # ⚠⚠ ЛИТУРГИЧНОТО НОМЕРИРАНЕ, не свое. „Седмица N по Петдесетница" тече
    # от понеделник, а „Неделя N" е НАКРАЯ ѝ: Неделя 1 (Вси Светии) е
    # Пасха+56. Затова се брои от Пасха+50, а не от +49 — инак всичко излиза
    # с една седмица напред и `ВЪЗДВИЖЕНИЕ_СЕДМИЦА = 18` (число от Устава)
    # сочи чужда седмица.
    return ('W', (n - 50) // 7 + 1, дт.isoweekday())


def зимна_седмица(дт: datetime.date) -> int | None:
    """Номерът при ЗИМНАТА отстъпка, или None извън прозореца ѝ.

    ⚠ Огледална на [winterWeekFor] в приложението — променят се ЗАЕДНО.
    Отправната неделя зависи от деня, в който пада Богоявление (три случая,
    Устав §1.7); делниците и съботите се броят назад от 34, неделите — от 32
    (Закхей), а неделите са с една по-малко от седмиците.
    """
    бог = datetime.date(дт.year, 1, 6) + datetime.timedelta(days=13)
    if бог.isoweekday() == 7:
        реф = бог
    elif бог.isoweekday() == 1:
        реф = бог - datetime.timedelta(days=1)
    else:
        реф = бог + datetime.timedelta(days=(7 - бог.isoweekday()) % 7 or 7)
    край = ПАСХА[дт.year] - datetime.timedelta(days=70)
    if not (реф < дт < край):
        return None
    седм = (край - реф).days // 7
    if седм <= 0:
        return None
    стъпка = ((дт - реф).days - 1) // 7 + 1
    общо = седм - 1 if дт.isoweekday() == 7 else седм
    if not (1 <= стъпка <= общо):
        return None
    последна = 32 if дт.isoweekday() == 7 else СТАБИЛНИ
    return последна - общо + стъпка


def църковна(дт: datetime.date) -> str:
    """Църковната дата по СТАР стил — базата е старостилна."""
    ц = дт - datetime.timedelta(days=13)
    return '%02d-%02d' % (ц.month, ц.day)


def поправки() -> list[tuple[str, str, str]]:
    """(сгрешено, вярно, стихове) — виж input/zachalo_errata.csv.

    ⚠⚠ САМО НОМЕРЪТ НА ЗАЧАЛОТО, не стиховете. Одит срещу таблицата
    `zachala` в `bible.db`: от 787 проверими четива **780 са верни** и само
    7 се разминават — единични печатни грешки в номера, докато главата и
    стиховете са точни. Тъй че ВРЪЗКАТА към текста винаги е работела;
    сгрешен е бил само видимият номер.

    ⚠ Поправят се ТУК, а не в `readings`: таблицата е парсната от източник и
    не се пипа (правило на потребителя). Ключът включва и стиховете, за да
    не се пипне друго четиво със същия номер.
    """
    п = ГНЕЗДО / 'input' / 'zachalo_errata.csv'
    if not п.exists():
        return []
    import csv as _csv
    with п.open(encoding='utf-8') as f:
        return [(r['wrong'], r['right'], r['verses'])
                for r in _csv.DictReader(f)]


def main() -> None:
    испр = поправки()

    def поправи(реф: str) -> str:
        for сгр, вярно, стих in испр:
            if сгр in реф and стих in реф:
                return реф.replace(сгр, вярно, 1)
        return реф

    db = sqlite3.connect(КОРЕН / 'assets/db/calendar_old.db')
    # ⚠⚠ ДНИ С ГОСПОДСКИ/БОГОРОДИЧЕН ПРАЗНИК (ранг 1). На тях четивата на
    # деня СА празничните и НЯМАТ етикет — тъй че правилото „без етикет
    # значи редово" ги пращаше в подвижния кръг. Така четивата на Рождество
    # се залепиха за адрес („W", 32, 3) и изникваха на 14 януари.
    # Рангът е обективният признак; гадаене по текста не става.
    празници = {д for (д,) in db.execute(
        "SELECT DISTINCT date FROM saints WHERE rank = 1")}
    закотвени: dict[str, list] = collections.defaultdict(list)
    апостол: dict[str, list] = collections.defaultdict(list)
    евангелие: dict[str, list] = collections.defaultdict(list)
    неподвижни: dict[str, list] = collections.defaultdict(list)
    нестабилни: dict[str, list] = collections.defaultdict(list)
    брой = collections.Counter()

    # ⚠⚠ ЕВАНГЕЛИЕТО НАСЛЕДЯВА ЕТИКЕТА НА АПОСТОЛА ПРЕД СЕБЕ СИ.
    #
    # В базата етикет носят САМО апостолите; четивата вървят по ДВОЙКИ и
    # евангелието е безименно:
    #
    #   apostle | На събота след Въздвижние: 1 Кор. 125 от полу
    #   gospel  | Иоан 30 (8:21-30)          ← същата памет, без етикет
    #
    # Без това правило апостолът отива в закотвения пласт, а евангелието му
    # — в подвижния, и двойката се разкъсва. Същото правило вече ползва и
    # дневният изглед (виж `day_readings.dart`).
    последен_етикет = None
    последна_дата = None
    отложени: list[tuple[datetime.date, str, str]] = []
    # ⚠⚠ ЕВАНГЕЛИЕТО НАСЛЕДЯВА ЕТИКЕТА НА АПОСТОЛА ПРЕД СЕБЕ СИ.
    #
    # В базата етикет носят САМО апостолите; четивата вървят по ДВОЙКИ и
    # евангелието е безименно:
    #
    #   apostle | На събота след Въздвижние: 1 Кор. 125 от полу
    #   gospel  | Иоан 30 (8:21-30)          ← същата памет, без етикет
    #
    # Без това правило апостолът отива в закотвения пласт, а евангелието му
    # — в подвижния, и двойката се разкъсва. Същото правило вече ползва и
    # дневният изглед (виж `day_readings.dart`).
    последен_етикет = None
    последна_дата = None
    for дата, вид, реф in db.execute(
            "SELECT date, type, reference FROM readings ORDER BY date, id"):
        if дата != последна_дата:
            последен_етикет, последна_дата = None, дата
        if дата != последна_дата:
            последен_етикет, последна_дата = None, дата
        y, m, d = map(int, дата.split('-'))
        дт = datetime.date(y, m, d)
        if дт.year not in ПАСХА:
            брой['извън обхвата на пасхалията'] += 1
            continue
        реф = поправи(реф)
        ет = RE_ЕТИКЕТ.match(реф)
        име = ет.group(1).strip() if ет else None
        if вид in ('apostle', 'liturgy'):
            последен_етикет = име
        elif вид == 'gospel' and име is None:
            име = последен_етикет
        # ⚠ ЗАКОТВЕНИТЕ се хващат ПРЕДИ неподвижните: и двете носят етикет,
        # но тези се местят с деня от седмицата на празника.
        if име in ЗАКОТВЕНИ:
            пр, дс_, посока = ЗАКОТВЕНИ[име]
            закотвени['%s|%d|%s' % (пр, дс_, посока)].append(
                {'type': вид, 'ref': реф})
            брой['закотвени'] += 1
            continue
        if име or дата in празници:
            # ⚠ НЕПОДВИЖНО: четиво на паметта — ключира се по ЦЪРКОВНА дата,
            # тъй че важи и за двата стила, и за всяка година. Тук влизат и
            # ВСИЧКИ четива на ден с ранг 1 (виж [празници]).
            неподвижни[църковна(дт)].append(
                {'type': вид, 'ref': реф})
            брой['неподвижни'] += 1
            continue
        if дт < ЦИКЪЛ_ОТ:
            # ⚠⚠ ОТЛАГА СЕ ЗА СЛЕД ОСНОВНИЯ ПРОХОД. Покритият цикъл свършва
            # преди своята зимна отстъпка, тъй че W33 и W34 остават празни —
            # а януари от ПРЕДНИЯ цикъл ги носи. Но данните се обхождат по
            # ДАТА, тъй че този януари идва ПЪРВИ: попълни ли се веднага,
            # основният проход после добавя ВТОРИ запис на същия ключ и
            # четивото излиза двойно. Затова се събира и се слага накрая,
            # само където липсва.
            отложени.append((дт, вид, реф))
            continue
        дял, седм, дс = адрес(дт)
        # ⚠ ЕВАНГЕЛИЕТО СЕ КЛЮЧИРА ПО СВОЯ номер — виж [евангелска_седмица].
        мой = (евангелска_седмица(дт, седм)
               if (дял == 'W' and вид == 'gospel') else седм)
        if мой is None:
            брой['зона на отстъпката (изхвърлено)'] += 1
            continue
        ключ = '%s%d:%d' % (дял, мой, дс)
        if дял == 'W' and мой > СТАБИЛНИ:
            # ⚠ „liturgy" е АПОСТОЛСКО четиво на определена служба — ключира
            # се като апостол, инак приложението не го намира (то търси само
            # „apostle" и „gospel").
            род = 'gospel' if вид == 'gospel' else 'apostle'
            нестабилни['%s:%s' % (род, ключ)].append({'type': вид, 'ref': реф})
            брой['нестабилни (отстъпка)'] += 1
            continue
        (евангелие if вид == 'gospel' else апостол)[ключ].append(
            {'type': вид, 'ref': реф})
        брой['подвижни'] += 1

    # ⚠ ВТОРИ ПРОХОД: зимните седмици от предния цикъл — САМО липсващите.
    for дт, вид, реф in отложени:
        зс = зимна_седмица(дт)
        if зс is None:
            брой['извън покрития цикъл'] += 1
            continue
        к = 'W%d:%d' % (зс, дт.isoweekday())
        карта = евангелие if вид == 'gospel' else апостол
        if к in карта:
            брой['вече има (прескочено)'] += 1
            continue
        карта[к] = [{'type': вид, 'ref': реф}]
        брой['зимни, от предния цикъл'] += 1

    вън = {'apostle': апостол, 'gospel': евангелие, 'fixed': неподвижни,
           'anchored': закотвени,
           'unstable': нестабилни, 'stable_weeks': СТАБИЛНИ,
           'exaltation_week': ВЪЗДВИЖЕНИЕ_СЕДМИЦА}
    (ГНЕЗДО / 'work/cycle.json').write_text(
        json.dumps(вън, ensure_ascii=False, indent=1), encoding='utf-8')
    for k, v in брой.most_common():
        print('   %-26s %d' % (k, v))
    print('   адреси: апостол %d, евангелие %d, неподвижни %d, закотвени %d,'
          ' нестабилни %d' % (len(апостол), len(евангелие), len(неподвижни),
                              len(закотвени), len(нестабилни)))
    print('→ work/cycle.json')


if __name__ == '__main__':
    main()

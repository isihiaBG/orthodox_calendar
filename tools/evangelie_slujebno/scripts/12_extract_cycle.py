СТАБИЛНИ = 34

# ⚠⚠ ПОДВИЖНИЯТ ПЛАСТ СЕ ВЗИМА САМО ОТ ЕДИН ЦИКЪЛ. `readings` покрива
# 14.01.2026 – 13.01.2027, тоест части от ДВЕ църковни години: началото

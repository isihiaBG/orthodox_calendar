#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Четивата → `lib/readings_cycle.dart`. Без мрежа.

    python3 13_gen_cycle_dart.py

⚠ БЕЗ SQLite — по същия довод като при обръщенията и прокимените: данните
са неизменни и само се четат, тъй че се вграждат като `const` и не искат
достъп до диска, нито прегенериране на календарните бази за всяка година.
"""
import json
import pathlib

ГНЕЗДО = pathlib.Path(__file__).resolve().parents[1]
ИЗХОД = pathlib.Path(__file__).resolve().parents[3] / 'lib' / 'readings_cycle.dart'


def d(s: str) -> str:
    return "'" + s.replace('\\', r'\\').replace("'", r"\'").replace('$', r'\$') + "'"


def карта(име, док, данни):
    l = ['/// ' + док.replace('\n', '\n/// '),
         'const Map<String, List<R>> %s = {' % име]
    for ключ in sorted(данни):
        редове = ', '.join('R(%s, %s)' % (d(x['type']), d(x['ref']))
                           for x in данни[ключ])
        l.append('  %s: [%s],' % (d(ключ), редове))
    l.append('};')
    l.append('')
    return l


def main() -> None:
    c = json.loads((ГНЕЗДО / 'work/cycle.json').read_text(encoding='utf-8'))
    l = [
        '// ГЕНЕРИРАН ФАЙЛ — не се редактира на ръка.',
        '// Прави го tools/evangelie_slujebno/scripts/13_gen_cycle_dart.py',
        '//',
        '// ⚠⚠ ЧЕТИВАТА СА ДВА ПЛАСТА, и двата НЕЗАВИСИМИ ОТ ГОДИНАТА И ОТ',
        '// СТИЛА:',
        '//',
        '//   ПОДВИЖЕН    адрес спрямо Пасха — „W12:3" = сряда на 12-та',
        '//               седмица по Петдесетница; „T4:7" = неделя на 4-та',
        '//               седмица от Триода; „P2:1" = понеделник на 2-та',
        '//               седмица от Пентикостара',
        '//   НЕПОДВИЖЕН  ЦЪРКОВНА дата „ММ-ДД"',
        '//',
        '// ⚠⚠ ТОВА Е И ПОПРАВКАТА ЗА НОВ СТИЛ. Църковната дата се смята от',
        '// гражданската по правилото на СТИЛА, тъй че всеки стил намира',
        '// СВОИТЕ памети. Досегашната таблица `readings` беше ключирана по',
        '// гражданска дата от старостилния календар и копирана непроменена',
        '// в новостилната база — там неподвижните четива излизаха с 13 дни',
        '// встрани. Изместване НЕ върши работа: на един и същ физически ден',
        '// двата стила честват РАЗЛИЧНИ светии.',
        '//',
        '// ⚠ Пази се ЦЕЛИЯТ низ („Иак. 55 (3:11-4:6)"), не само зачалото:',
        '// връзката към текста иска глава и стихове. Разчитането минава през',
        '// същия `day_readings.dart`, който вече работи с тези низове.',
        '//',
        '// Сверено: двата пласта възпроизвеждат покрития църковен цикъл',
        '// (01.02.2026 – 13.01.2027) ТОЧНО — 347 от 347 дни.',
        '',
        '/// Един ред четиво: вид („apostle", „gospel", „liturgy") и текстът му.',
        'class R {',
        '  final String type;',
        '  final String ref;',
        '  const R(this.type, this.ref);',
        '}',
        '',
    ]
    l += карта('kReadingsApostle',
               'АПОСТОЛЪТ — ключ „дял+седмица:ден".\n'
               '\n'
               '⚠ Броячът му върви НЕПРЕКЪСНАТО през цялата година.',
               c['apostle'])
    l += карта('kReadingsGospel',
               'ЕВАНГЕЛИЕТО — ключ по СВОЯ номер на седмица.\n'
               '\n'
               '⚠⚠ СЛЕД НЕДЕЛЯТА ПО ВЪЗДВИЖЕНИЕ номерът СКАЧА на 18 и оттам\n'
               'върви по ред — независимо коя по ред е тази неделя (Устав,\n'
               '§1.7). Оттам и въпросът, който самият Устав дава за пример:\n'
               '„защо в календара пише 16-та седмица, а евангелията са на\n'
               '18-та?" Затова ключът е ОТДЕЛЕН от апостолския.\n'
               '\n'
               '⚠ През 2026 г. двете съвпадат (Неделята по Въздвижение е\n'
               '18-та), тъй че данните НЕ могат да издадат правилото — то е\n'
               'вградено в кода, не извлечено.',
               c['gospel'])
    l += карта('kReadingsFixed',
               'Неподвижните — ключ ЦЪРКОВНА дата „ММ-ДД".', c['fixed'])
    l += карта('kReadingsAnchored',
               'ЗАКОТВЕНИТЕ — ключ „църковна дата|ден|before/after".\n'
               '\n'
               '⚠⚠ ТРЕТИ ПЛАСТ, нито подвижен, нито неподвижен. „Събота по\n'
               'Въздвижение" се мести с ДЕНЯ ОТ СЕДМИЦАТА на празника: тази\n'
               'година е 3 октомври, догодина — друга дата. Вписани по\n'
               'църковна дата, те се заковават за случайното число на една\n'
               'година. (Посочено от потребителя, 11.09.2026.)\n'
               '\n'
               '⚠ Празникът се дава с ЦЪРКОВНА дата, за да важи и за двата\n'
               'стила — гражданската му дата се смята от нея по стила.',
               c['anchored'])
    l += карта('kReadingsUnstable',
               '⚠⚠ СЕДМИЦИТЕ, ЗАСЕГНАТИ ОТ ОТСТЪПКАТА.\n'
               '\n'
               'Броят недели между Петдесетница и Триода се мени от 33 до 38,\n'
               'а тези данни носят ВГРАДЕНА отстъпката на 2026 г. (34\n'
               'седмици). Затова стоят отделно и се показват САМО за година\n'
               'със същия брой седмици — инак биха били тихо сгрешени.\n'
               'Правилото още не е изведено; виж отвореното в README-то.',
               c['unstable'])
    l.append('/// Докъде седмиците по Петдесетница са БЕЗ отстъпка.')
    l.append('const int kStableWeeks = %d;' % c['stable_weeks'])
    l.append('')
    l.append('/// Номерът, на който евангелският брояч скача след Неделята')
    l.append('/// по Въздвижение (Устав, §1.7).')
    l.append('const int kExaltationWeek = %d;' % c['exaltation_week'])
    l.append('')
    ИЗХОД.write_text('\n'.join(l), encoding='utf-8')
    print('→ %s  (%.0f KB)' % (ИЗХОД, ИЗХОД.stat().st_size / 1024))
    for k in ('apostle', 'gospel', 'fixed', 'anchored', 'unstable'):
        print('   %-10s %d адреса' % (k, len(c[k])))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""01_extract_gospel.py — шестте пласта на богослужебното Евангелие → JSON.

    input/Евангелие…epub  →  work/gospel.json

Пластовете (виж README.md за пълното описание):
    utrennie    единайсетте възкресни утринни евангелия
    movable     подвижният кръг от Пасха нататък — неделя + делниците ѝ
    lent        Великият пост и Страстната седмица
    menologion  месецословът, септември → август (само 167 от 365 дни!)
    common      общите служби — за дните, които месецословът пропуска

⚠ НИЩО НЕ СЕ ПИШЕ В БАЗИ. Само чете и описва.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common
from common import Книга, четива

ИЗХОД = Path(__file__).resolve().parents[1] / 'work' / 'gospel.json'

МЕСЕЦИ = ['септемврий', 'октоврий', 'ноемврий', 'декемврий', 'ианнуарий',
          'февруарий', 'март', 'априллий', 'маий', 'иуний', 'иулий', 'август']

# Начало на ден в месецослова: „8. Рождество Пресвятыя…"
RE_ДЕН = re.compile(r'^(\d{1,2})\.\s*(.*)$')
# ⚠ „[зри]" НЕ е дата — въвежда подвижен ден, закачен за неподвижен празник
# („[зри] Суббота пред Воздвижением"). Взет за дата, би объркал целия месец.
RE_ЗРИ = re.compile(r'^\[зри\]\s*(.*)$')


def раздел(книга, начало, край=None):
    """Записите от съдържанието между два етикета (без самите граници)."""
    имена = [t for t, _ in книга.записи]
    i = имена.index(начало)
    j = imена_край = len(имена) if край is None else имена.index(край)
    return книга.записи[i + 1:j]


def прочети_прости(книга, записи):
    """Раздел, чиито записи са по един файл: етикет → списък четива."""
    навън = {}
    for етикет, файл in записи:
        редове = []
        for двойки in книга.блокове(файл):
            for рубрика, текст in двойки:
                ч = четива(текст) if текст else []
                if ч or рубрика:
                    редове.append({'рубрика': рубрика, 'четива': ч,
                                   'текст': текст})
        навън[етикет] = редове
    return навън


def прочети_месецослов(книга):
    навън = {}
    for м in МЕСЕЦИ:
        файл = next(f for t, f in книга.записи if t == f'Месяц {м}')
        дни, текущ = {}, None
        for двойки in книга.блокове(файл):
            # блок без рубрика и с една част — заглавие на ден или продължение
            цял = ' '.join(t for _, t in двойки if t)
            if len(двойки) == 1 and not двойки[0][0]:
                m = RE_ДЕН.match(цял)
                if m:
                    текущ = {'ден': int(m.group(1)), 'име': m.group(2),
                             'вид': 'дата', 'четива': []}
                    дни.setdefault(int(m.group(1)), []).append(текущ)
                    continue
                z = RE_ЗРИ.match(цял)
                if z:
                    текущ = {'ден': None, 'име': z.group(1),
                             'вид': 'зри', 'четива': []}
                    дни.setdefault('зри', []).append(текущ)
                    continue
                if текущ is not None and цял:
                    текущ['име'] = (текущ['име'] + ' ' + цял).strip()
                    continue
            if текущ is None:
                continue
            for рубрика, текст in двойки:
                ч = четива(текст) if текст else []
                if ч or рубрика:
                    текущ['четива'].append({'рубрика': рубрика, 'четива': ч,
                                            'текст': текст})
        навън[м] = дни
    return навън


def main():
    к = Книга('Евангелие')
    имена = [t for t, _ in к.записи]

    данни = {'книга': к.име}

    # ── утринните възкресни
    файл = next(f for t, f in к.записи if t == 'Евангелиа утренния воскресныя')
    у = []
    for двойки in к.блокове(файл):
        for рубрика, текст in двойки:
            m = re.match(r'^(\d+)\.$', рубрика or '')
            if m and текст:
                у.append({'n': int(m.group(1)), 'четива': четива(текст)})
    данни['utrennie'] = у

    # ── подвижният кръг и постът
    данни['movable'] = прочети_прости(к, раздел(
        к, 'Сказание еже како на всяк день должно есть чести Евангелие седмиц всего лета',
        'Сказание Евангелий Святыя Четыредесятницы и Страстныя седмицы'))
    данни['lent'] = прочети_прости(к, раздел(
        к, 'Сказание Евангелий Святыя Четыредесятницы и Страстныя седмицы',
        'Евангелиа утренния воскресныя'))

    # ── месецословът
    данни['menologion'] = прочети_месецослов(к)

    # ── общите
    данни['common'] = прочети_прости(к, раздел(
        к, 'Евангелиа обща святым, имже егда творим службу',
        'Евангелиа за упокой по вся дни'))

    ИЗХОД.parent.mkdir(parents=True, exist_ok=True)
    ИЗХОД.write_text(json.dumps(данни, ensure_ascii=False, indent=1),
                     encoding='utf-8')

    # ── отчет
    дни = sum(len([d for d in дни_на_месец if isinstance(d, int)])
              for дни_на_месец in [м.keys() for м in данни['menologion'].values()])
    зри = sum(len(м.get('зри', [])) for м in данни['menologion'].values())
    print(f"утринни възкресни : {len(данни['utrennie'])}")
    print(f"подвижен кръг     : {len(данни['movable'])} записа")
    print(f"пост и Страстна   : {len(данни['lent'])} записа")
    print(f"месецослов        : {дни} дни с дата, {зри} записа [зри]")
    print(f"общи служби       : {len(данни['common'])}")
    print(f"\n→ {ИЗХОД}")


if __name__ == '__main__':
    main()

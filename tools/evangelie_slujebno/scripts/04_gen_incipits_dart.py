ВИД = {
    'Братие': 'brethren',
    'Во дни оны': 'thoseDays',
    'Чадо Тимофее': 'childTimothy',
    'Чадо Тите': 'childTitus',
    'Возлюбленнии': 'beloved',
    'Возлюбленне': 'beloved',
}


def main():
    редове = list(csv.DictReader(open(ВХОД, encoding='utf-8'), delimiter='|'))
    записи = []
    for r in редове:
        # ⚠ ИЗЧЕРПАТЕЛНО: зачало без разпозната формула получава `none`, а не
        # се пропуска. Инак липсващ ключ значи и „няма обръщение", и „не сме
        # го намерили" — а това са различни неща.
        вид = ВИД.get(r['csl']) or 'none'
        записи.append((r['book'], int(r['zachalo']), вид))
    # ⚠ Зачало с ЧАСТ („40В") се свива до номера си: четивата в базата дават
    # само число. Сверено, че при единствения такъв случай (Act 40 и Act 40В)
    # обръщението е ЕДНО И СЪЩО, тъй че свиването не губи нищо. Разминат ли се
    # някога, скриптът спира — по-добре, отколкото да избере мълчаливо.
    свити = {}
    for кн, з, в in записи:
        ключ = (кн, з)
        ако = свити.get(ключ)
        if ако is not None and ако != в:
            raise SystemExit(
                f'⚠ {кн} зач.{з}: две различни обръщения ({ако} и {в}) — '
                'ключът трябва да носи и частта')
        свити[ключ] = в
    записи = [(кн, з, в) for (кн, з), в in свити.items()]

    # ⚠ Ръчните поправки се НАЛАГАТ отгоре — изворът остава непокътнат.
    # Добавят и ключове, каквито в Апостола ги няма (виж файла защо).
    поправки = 0
    if ПОПРАВКИ.exists():
        за_ключ = {(кн, з): i for i, (кн, з, _) in enumerate(записи)}
        for ред in ПОПРАВКИ.read_text(encoding='utf-8').splitlines():
            ред = ред.strip()
            if not ред or ред.startswith('#'):
                continue
            кн, з, вид = (ред.split('|') + ['', '', ''])[:3]
            з = int(з)
            i = за_ключ.get((кн, з))
            if i is None:
                записи.append((кн, з, вид))
            else:
                записи[i] = (кн, з, вид)
            поправки += 1
    if поправки:
        print(f'ръчни поправки: {поправки}')

    записи.sort(key=lambda x: (x[0], x[1]))

    редове_dart = [
        f"  '{кн}|{з}': ApostolIncipit.{в}," for кн, з, в in записи
    ]
    ИЗХОД.write_text(ГЛАВА + '\n'.join(редове_dart) + '\n' + ОПАШКА,
                     encoding='utf-8')

    from collections import Counter
    по_вид = Counter(в for _, _, в in записи)
    print(f'зачала с обръщение: {len(записи)} от {len(редове)}')
    for в, c in по_вид.most_common():
        print(f'  {c:>4}  {в}')
    print(f'\n→ {ИЗХОД}')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""02_extract_apostol.py — пластовете на богослужебния Апостол → JSON.

    input/Апостол…epub  →  work/apostol.json

⚠⚠ УСТРОЙСТВОТО Е ОБЪРНАТО СПРЯМО ЕВАНГЕЛИЕТО. Там рубриката е червена, а
четивото е гол текст подире ѝ; тук ЦЯЛОТО четиво е вътре в червеното:

    <span class="color-red">Апостол к филипписием, <a …>Зачало 240</a>.</span>

Затова блокът се разчита по СЪДЪРЖАНИЕ (изчистен текст), а не по цвят.

⚠⚠ ЗАЧАЛАТА СЕ ЗАСТЪПВАТ В ШЕВОВЕТЕ МЕЖДУ КНИГИТЕ, тъй че номерът САМ НЕ
СТИГА и името на книгата е задължително:

    Деяния 1–51   и   Иаковле 50–57      → зачала 50 и 51 са двусмислени
    2 Петрово 64–68 и 1 Иоаново 68–74    → зачало 68
    К Титу 300–302 и К Филимону 302      → зачало 302

Обратно, името също не стига: „к коринфяном" не казва първо или второ
послание — това го решава номерът (122–166 срещу 167–197). Двете заедно са
еднозначни.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import Книга, текст

ИЗХОД = Path(__file__).resolve().parents[1] / 'work' / 'apostol.json'

RE_КНИГА_ЗАГЛ = re.compile(r'посл|Деяни|Апокал', re.I)
RE_ЗАЧ_ЗАПИС = re.compile(r'Зачало (\d+)([А-Я])?(?: \((.*)\))?$')

# ⚠⚠ ИМЕТО НА КНИГАТА СЕ ТЪРСИ НАЗАД ОТ ЗАЧАЛОТО, не напред от думата
# „апостол". Три причини, всяка срещана в текста:
#   1) думата е ту главна, ту малка — „Апостол к филипписием" срещу
#      „В понедельник: апостол к римляном";
#   2) между нея и книгата има вмъкнати думи — „Апостол преподобномученика
#      единаго, к Тимофею, Зачало 291" (взето отпред, за книга минава
#      „преподобномученика единаго");
#   3) един ред носи ПО НЯКОЛКО четива с различни книги.
# Затова се хващат зачалата, а името е последният откъс преди запетаята.
RE_ЗАЧ = re.compile(r'Зачало\s*(\d+)\s*([А-Я])?')
RE_ИМЕ_ПРЕДИ = re.compile(r'([^,;.:]{1,42})[,\s]*$')

RE_ПРОКИМЕН = re.compile(r'(Прокимен[^:]{0,60}):\s*(.*?)(?:Стих:\s*(.*))?$', re.S)
RE_АЛЛИЛУИА = re.compile(r'(Аллилуиа[^:]{0,40}):\s*(.*?)(?:Стих:\s*(.*))?$', re.S)

МЕСЕЦИ_ГОРЕ = ['СЕПТЕМВРИЙ', 'ОКТОВРИЙ', 'НОЕМВРИЙ', 'ДЕКЕМВРИЙ', 'ИАННУАРИЙ',
               'ФЕВРУАРИЙ', 'МАРТ', 'АПРИЛЛИЙ', 'МАИЙ', 'ИУНИЙ', 'ИУЛИЙ', 'АВГУСТ']


def обхвати_на_книгите(к):
    """книга → (най-малко, най-голямо зачало). Оттам се решава двусмислието."""
    текуща, обхват = None, {}
    for етикет, _ in к.записи:
        m = RE_ЗАЧ_ЗАПИС.match(етикет)
        if m and текуща:
            n = int(m.group(1))
            о = обхват.setdefault(текуща, [n, n])
            о[0], о[1] = min(о[0], n), max(о[1], n)
        elif not етикет.startswith('Зачало') and len(етикет) < 70 \
                and RE_КНИГА_ЗАГЛ.search(етикет):
            текуща = етикет
    return обхват


def четива_в(т, обхват):
    """Всички четива в един изчистен блок, с разрешено двусмислие."""
    навън = []
    for m in RE_ЗАЧ.finditer(т):
        номер, част = int(m.group(1)), m.group(2) or ''
        предх = RE_ИМЕ_ПРЕДИ.search(т[:m.start()])
        име = предх.group(1).strip() if предх else ''
        # кои книги изобщо съдържат такъв номер
        кандидати = [k for k, (a, b) in обхват.items() if a <= номер <= b]
        избрана = кандидати[0] if len(кандидати) == 1 else None
        # ⚠ Уводните думи отпадат ВСИЧКИТЕ, не само предлогът: срещат се
        # „апостол от Петрова", „Деяний", „апостол к римляном". Останел,
        # „апостол" дава корен „апос" и съвпадение не може да има.
        ключ = име.lower()
        # ⚠⚠ „Деяниих"/„Деяний" НЕ е уводна дума, а САМОТО ИМЕ на книгата.
        # Махнато като пълнеж, ключът остава празен и зачала 50 и 51 — които
        # ги има и в Деяния, и в Иаковлевото послание — остават двусмислени.
        if 'деяни' in ключ:
            избрана = next((k for k in кандидати if 'Деяни' in k), избрана)
        for уводна in ('апостол', 'послания', 'послание', 'соборнаго',
                       'единаго'):
            ключ = ключ.replace(уводна, ' ')
        ключ = re.sub(r'\b(к|ко|от|в|во|и)\b', ' ', ключ)
        ключ = re.sub(r'[^а-я]', '', ключ)
        # ⚠ Прякото сравнение по ПЕТ знака не стига: книгата се казва
        # „…Ап. Петра", а препратката „от Петрова" — общото е само „Петр".
        # Затова се пробва все по-къс корен, от 6 знака надолу до 4.
        if избрана is None and ключ:
            for дълж in (6, 5, 4):
                за_търсене = ключ[:дълж]
                if len(за_търсене) < дълж:
                    continue
                съвпадения = [k for k in кандидати
                              if за_търсене in re.sub(r'[^а-я]', '', k.lower())]
                if len(съвпадения) == 1:
                    избрана = съвпадения[0]
                    break
        навън.append({'книга_текст': име, 'зачало': номер, 'част': част,
                      'книга': избрана,
                      'двусмислено': len(кандидати) > 1 and избрана is None})
    return навън


def прочети(к, записи, обхват):
    навън = {}
    for етикет, файл in записи:
        редове = []
        for сурово in re.findall(r'<div class="paragraph"[^>]*>(.*?)</div>',
                                 к.html_на(файл), re.S):
            т = текст(сурово)
            if not т:
                continue
            ред = {'текст': т}
            ч = четива_в(т, обхват)
            if ч:
                ред['четива'] = ч
            for име, изр in (('прокимен', RE_ПРОКИМЕН), ('аллилуиа', RE_АЛЛИЛУИА)):
                m = изр.match(т)
                if m:
                    ред[име] = {'надпис': m.group(1).strip(),
                                'текст': (m.group(2) or '').strip(),
                                'стих': (m.group(3) or '').strip()}
            редове.append(ред)
        навън[етикет] = редове
    return навън


def раздел(к, начало, край=None):
    имена = [t for t, _ in к.записи]
    i = имена.index(начало)
    j = len(имена) if край is None else имена.index(край)
    return к.записи[i + 1:j]


def main():
    к = Книга('Апостол')
    имена = [t for t, _ in к.записи]
    обхват = обхвати_на_книгите(к)

    данни = {'книга': к.име,
             'обхвати': {k: v for k, v in обхват.items()}}

    данни['movable'] = прочети(к, раздел(
        к, 'Как должно читать Апостол в седмицах всего лета',
        'Последование Святыя Четыредесятницы, субботам и неделям св. Великаго поста'),
        обхват)
    данни['lent'] = прочети(к, раздел(
        к, 'Последование Святыя Четыредесятницы, субботам и неделям св. Великаго поста',
        'Прокимени и аллилуиаре воскреснии, литургийнии, 8-ми гласов'), обхват)
    данни['prokimen_glas'] = прочети(к, раздел(
        к, 'Прокимени и аллилуиаре воскреснии, литургийнии, 8-ми гласов',
        'Прокимени и аллилуиаре дневнии'), обхват)
    данни['prokimen_den'] = прочети(к, раздел(
        к, 'Прокимени и аллилуиаре дневнии',
        'Соборник двунадесятим месяцем. Сказание коемуждо празднику и избранным святым, апостолы и прокимены'
        if 'Соборник двунадесятим месяцем. Сказание коемуждо празднику и избранным святым, апостолы и прокимены' in имена
        else next(t for t in имена if t.startswith('Соборник двунадесятим'))), обхват)

    # ── месецословът: всеки ДЕН е свой запис в съдържанието
    мес, текущ = {}, None
    започна = False
    for етикет, файл in к.записи:
        if етикет.startswith('МЕСЯЦ '):
            текущ = етикет[6:].strip().lower()
            мес[текущ] = {}
            започна = True
            continue
        if not започна or текущ is None:
            continue
        if етикет.startswith('Прокимени, апостоли и аллилуиаре общи'):
            break
        m = re.match(r'^(\d{1,2})\.\s*(.*)$', етикет)
        if not m:
            continue
        ден = int(m.group(1))
        редове = прочети(к, [(етикет, файл)], обхват)[етикет]
        мес[текущ].setdefault(ден, []).append({'име': m.group(2), 'редове': редове})
    данни['menologion'] = мес

    данни['common'] = прочети(к, раздел(
        к, 'Прокимени, апостоли и аллилуиаре общи святым, имже егда творим службу',
        'Прокимени, апостоли и аллилуиаре на всяку потребу различнии'), обхват)

    ИЗХОД.parent.mkdir(parents=True, exist_ok=True)
    ИЗХОД.write_text(json.dumps(данни, ensure_ascii=False, indent=1),
                     encoding='utf-8')

    дни = sum(len(v) for v in мес.values())
    двусм = 0
    for раздел_ in ('movable', 'lent', 'common'):
        for редове in данни[раздел_].values():
            for р in редове:
                двусм += sum(1 for c in р.get('четива', []) if c['двусмислено'])
    print(f"книги с обхват    : {len(обхват)}")
    print(f"подвижен кръг     : {len(данни['movable'])} записа")
    print(f"пост и Страстна   : {len(данни['lent'])} записа")
    print(f"прокимени по глас : {len(данни['prokimen_glas'])}")
    print(f"прокимени по ден  : {len(данни['prokimen_den'])}")
    print(f"месецослов        : {дни} дни")
    print(f"общи служби       : {len(данни['common'])}")
    print(f"⚠ неразрешени двусмислия: {двусм}")
    print(f"\n→ {ИЗХОД}")


if __name__ == '__main__':
    main()

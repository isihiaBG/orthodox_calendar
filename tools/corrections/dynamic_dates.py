#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Цитираните двойки дати → живата запушалка „⟦дата:ММ-ДД⟧".

    python3 tools/corrections/dynamic_dates.py --dry-run
    python3 tools/corrections/dynamic_dates.py --only lives-csv lives-db

⚠⚠ ЗАЩО. Преводите носят датите както ги дава руският извор — „1/14
октомври", „27 септември/10 октомври". Това е ЧУЖДА уговорка: изрежда и
двата стила наведнъж и слага водещ онзи, който авторът е избрал. Човек,
отворил приложението по нов стил, чете втора дата, каквато в календара му
я няма; по стар стил вижда подредба, обратна на собствената си настройка.
Затова в текста остава само ЦЪРКОВНАТА дата, а изписването се сглобява при
отваряне — виж lib/church_dates.dart. Това е СТАНДАРТЪТ и за бъдещи текстове.

⚠⚠ ПРЕВРЪЩАТ СЕ САМО ДВОЙКИ, КОИТО СЕ СВЕРЯВАТ. Втората дата трябва да е
точно първата плюс отместването между календарите (днес 13 дни). Не
съвпадне ли — оставя се както си е и влиза в отчета. Инак израз, който само
прилича на двойка („Гл. 47 / 48"), би станал дата и текстът щеше да лъже.

⚠⚠ КОИ КОРПУСИ — НЕ ВСИЧКИ. Запушалката се разгъва в `_buildHtmlFor`
(reader_screen.dart), тъй че важи за житията, словата, справочника и
статиите. Томовете (`lives-epub`) минават през ДРУГ четец, а Теофан и
Оптинските — през MiniReader; там запушалката би излязла като текст.
Затова по подразбиране се пипат само корпусите от `ПОДРАЗБИРАНЕ`.

⚠ Идемпотентен: вече превърнатото не съвпада с израза.
"""
from __future__ import unicode_literals

import argparse
import re
import sys
from datetime import date, timedelta
from os.path import dirname, abspath

sys.path.insert(0, dirname(abspath(__file__)))
import corpora  # noqa: E402

МЕСЕЦИ = ['януари', 'февруари', 'март', 'април', 'май', 'юни',
          'юли', 'август', 'септември', 'октомври', 'ноември', 'декември']
НОМЕР = dict((име, i + 1) for i, име in enumerate(МЕСЕЦИ))
М = '(?:' + '|'.join(МЕСЕЦИ) + ')'

ПОДРАЗБИРАНЕ = ['lives-csv', 'lives-db', 'articles-db', 'paskha-pages',
                'paskha', 'slova', 'slova-db', 'reference']

# Редът е по СПЕЦИФИЧНОСТ: дългата форма („24 юни/7 юли") трябва да опита
# първа, инак късата отхапва началото ѝ.
ДЪЛГА = re.compile(r'(?<![\d⟧])(\d{1,2})\s+(%s)\s*/\s*(\d{1,2})\s+(%s)(?![\wа-я])'
                   % (М, М))
КЪСА = re.compile(r'(?<![\d⟧])(\d{1,2})\s*/\s*(\d{1,2})\s+(%s)(?![\wа-я])' % М)


def отместване(година):
    """Разликата между двата календара. ⚠ Не е закованото 13 — от 2100 е 14."""
    c = година // 100
    return c - c // 4 - 2


class Брояч(object):
    def __init__(self):
        self.ок = 0
        self.оставени = []


def направи(брояч):
    год = date.today().year
    отм = отместване(год)

    def сверява_ли(a_м, a_д, b_м, b_д):
        """Църковна ли е първата, а втората — нейната гражданска?"""
        try:
            a = date(год, a_м, a_д)
        except ValueError:
            return False
        b = a + timedelta(days=отм)
        return (b.month, b.day) == (b_м, b_д)

    def двойка(п_м, п_д, в_м, в_д, цял):
        # ⚠⚠ РЕДЪТ НЕ Е ЕДИН И СЪЩ В ИЗВОРА. Обикновено е „църковна/
        # гражданска" („1/14 октомври"), но пет жития го пишат ОБРАТНО
        # („4 юли/21 юни" — откриване на мощите на прп. Максим Грек).
        # Затова се пробват и двете посоки, а решава СВЕРКАТА: коя от двете
        # дати плюс отместването дава другата. Само по реда не може да се
        # съди — и двата записа са напълно правдоподобни.
        if сверява_ли(п_м, п_д, в_м, в_д):
            брояч.ок += 1
            return '⟦дата:%02d-%02d⟧' % (п_м, п_д)
        if сверява_ли(в_м, в_д, п_м, п_д):
            брояч.ок += 1
            return '⟦дата:%02d-%02d⟧' % (в_м, в_д)
        брояч.оставени.append(цял)
        return цял

    def преобрази(текст):
        if '/' not in текст:
            return текст
        текст = ДЪЛГА.sub(
            lambda m: двойка(НОМЕР[m.group(2)], int(m.group(1)),
                             НОМЕР[m.group(4)], int(m.group(3)), m.group(0)),
            текст)
        return КЪСА.sub(
            lambda m: двойка(НОМЕР[m.group(3)], int(m.group(1)),
                             НОМЕР[m.group(3)], int(m.group(2)), m.group(0)),
            текст)

    return преобрази


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', nargs='*')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    имена = a.only or ПОДРАЗБИРАНЕ
    общо, всички_оставени = 0, []
    for к in corpora.по_име(имена):
        брояч = Брояч()
        промени = к.обходи(направи(брояч), пиши=not a.dry_run)
        общо += брояч.ок
        всички_оставени += брояч.оставени
        if брояч.ок or промени:
            print('  %-14s %4d дати в %d текста' % (к.име, брояч.ок, len(промени)))
    # ⚠ Архивчето се затваря ИЗРИЧНО — то е единственото връщане назад
    # (преводните извори не са в git). Виж apply.py, същият ред.
    if not a.dry_run:
        corpora.РЕЗЕРВ.затвори()
        if corpora.РЕЗЕРВ.път:
            import os
            print('резерв: %s' % os.path.relpath(corpora.РЕЗЕРВ.път, corpora.ROOT))
    print('-' * 58)
    print('превърнати: %d' % общо)
    if всички_оставени:
        уникални = sorted(set(всички_оставени))
        print('оставени (не се сверяват): %d — %s'
              % (len(всички_оставени), '; '.join(уникални[:12])))
    if a.dry_run:
        print('(пробно — нищо не е записано)')
    return 0


if __name__ == '__main__':
    sys.exit(main())

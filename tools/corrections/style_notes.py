КОРПУСИ = ['lives-csv', 'lives-db', 'articles-db', 'paskha', 'paskha-pages', 'reference']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    for _, ляво, дясно in МЕСТА:
        # Веригата би сменяла при всяко пускане.
        assert ляво not in дясно, ляво
    намерени = dict((ляво, 0) for _, ляво, _ in МЕСТА)

    def преобрази(текст):
        for _, ляво, дясно in МЕСТА:
            if ляво in текст:
                намерени[ляво] += текст.count(ляво)
                текст = текст.replace(ляво, дясно)
        return текст

    for к in corpora.по_име(КОРПУСИ):
        промени = к.обходи(преобрази, пиши=not a.dry_run)
        if промени:
            print('  %-14s %d текста' % (к.име, len(промени)))
    if not a.dry_run:
        corpora.РЕЗЕРВ.затвори()
        if corpora.РЕЗЕРВ.път:
            print('резерв: %s' % os.path.relpath(corpora.РЕЗЕРВ.път, corpora.ROOT))
    print('-' * 58)
    for откъде, ляво, _ in МЕСТА:
        print('%3d  %-34s %s' % (намерени[ляво], откъде, ляво))
    if a.dry_run:
        print('(пробно — нищо не е записано)')
    return 0


if __name__ == '__main__':
    sys.exit(main())

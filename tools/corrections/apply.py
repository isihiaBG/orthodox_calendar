#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Масова замяна на думи във всички преведени текстове на проекта.

За какво е. Преводът е машинен и от време на време изплува дума, сгрешена
навсякъде наведнъж („служене" вместо „служение"). Поправянето ѝ на ръка
значи да се обиколят пет конвейера и две бази; този скрипт го прави от един
списък и може да се пуска колкото пъти трябва.

    python3 tools/corrections/apply.py --survey     # какво има, нищо не пише
    python3 tools/corrections/apply.py --dry-run    # какво би сменил
    python3 tools/corrections/apply.py              # нанася
    python3 tools/corrections/apply.py --only optina teofan

Списъкът е в replacements.tsv (по двойка на ред). Къде живеят текстовете —
в corpora.py.

⚠ ИДЕМПОТЕНТЕН Е. Второ пускане не мени нищо, защото замяната е по цели
думи и целта вече не съвпада с търсеното. Единственото изключение би било
двойка, чиято дясна страна пак се търси отляво — затова при зареждането се
проверява и се вика ГРЕШКА.

⚠ След нанасяне СЛЕДВА ПРЕСГЛОБЯВАНЕ. Скриптът пипа изворите; изделията
(двете .epub-и и трите бази) се правят от съответните конвейери — виж
списъка, който излиза накрая.
"""

import argparse
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import corpora  # noqa: E402

ТУК = os.path.dirname(os.path.abspath(__file__))
СПИСЪК = os.path.join(ТУК, 'replacements.tsv')


# --------------------------------------------------------------------------
# Прости двойки от TSV
# --------------------------------------------------------------------------

_ЛАТИНСКИ_ДВОЙНИЦИ = set('aAeEocCpPxXyBHKMTuiI')


def _без_латиница(номер, дума):
    """Спира латинско „a" насред кирилска дума.

    Изглежда еднакво, а никога не съвпада — правилото просто мълчи. Тук
    вече веднъж влезе такова „a" в „наважденията" и се хвана случайно.
    """
    има_кирилица = any('Ѐ' <= з <= 'ӿ' for з in дума)
    лоши = [з for з in дума if з in _ЛАТИНСКИ_ДВОЙНИЦИ]
    if има_кирилица and лоши:
        raise SystemExit(
            'ред %d: латинско „%s" в кирилската дума „%s" — изглежда еднакво, '
            'но никога няма да съвпадне.' % (номер, лоши[0], дума))


def прочети_списък(път=СПИСЪК):
    двойки = []
    with io.open(път, encoding='utf-8') as f:
        for номер, ред in enumerate(f, 1):
            ред = ред.rstrip('\n')
            if not ред.strip() or ред.lstrip().startswith('#'):
                continue
            части = [ч.strip() for ч in ред.split('\t') if ч.strip()]
            if len(части) < 2:
                raise SystemExit('ред %d: липсва табулация — %r' % (номер, ред))
            откъде, накъде = части[0], части[1]
            _без_латиница(номер, откъде)
            _без_латиница(номер, накъде)
            if откъде == накъде:
                continue
            двойки.append((откъде, накъде))
    # проверка за верижност: дясната страна не бива да се търси отляво
    леви = {а for а, _ in двойки}
    for а, б in двойки:
        if б in леви:
            raise SystemExit(
                'ВЕРИГА: „%s" → „%s", а „%s" също се заменя. Скриптът щеше '
                'да мени два пъти при всяко пускане.' % (а, б, б))
    return двойки


def _със_същата_главна(образец, замяна):
    """Пренася главната буква от намереното върху замяната."""
    if образец[:1].isupper() and замяна[:1].islower():
        return замяна[:1].upper() + замяна[1:]
    return замяна


def правило_за_двойка(откъде, накъде):
    """Съвпадение по цяла дума, гъвкаво САМО за първата буква.

    ⚠ Пълно IGNORECASE е капан. „по завръщането Си" (за Христа) би съвпаднало
    с реда „по завръщането си" и главното „Си" щеше да падне мълчаливо в
    двата случая, където го има. Затова се разрешава друга главна буква само
    отпред — там тя идва от началото на изречението, не от смисъла.
    """
    първа = откъде[:1]
    ако_главна = ('[%s%s]' % (първа.upper(), първа.lower())
                  if първа.upper() != първа.lower() else re.escape(първа))
    рег = re.compile(r'\b%s%s\b' % (ако_главна, re.escape(откъде[1:])))

    def смени(текст):
        return рег.sub(lambda m: _със_същата_главна(m.group(0), накъде), текст)

    return смени


# --------------------------------------------------------------------------
# Именувано правило: Богомайка
# --------------------------------------------------------------------------
#
# Тук е нужно решение по КОНТЕКСТ, което TSV не може да изрази.
#
# В български членът стои върху ПЪРВОТО име в групата. Затова
# „Пречиста-ТА Богомайка" е вярно (членът е върху определението), а
# „иконата на Богомайка" е грешно — там определение няма и членът трябва да
# е върху съществителното. Преводачът е сгрешил точно това: от 267 срещания
# 93 стоят нечленувани без определение.
#
# Замяната поправя грешката пътьом, защото избира целевата форма по
# същия признак:
#
#     има членувано определение   → „Майка Божия"    (Пречистата Майка Божия)
#     няма                        → „Божията Майка"  (иконата на Божията Майка)
#     звателна „Богомайко"        → „Майко Божия"
#
# ⚠ „Полагане на Ризата Богомайка" иска и предлог. Правилото на потребителя
# (17.08.2026): когато двете „на" се струпват, първото отпада —
# „Полагане ризата на Божията Майка", не „Полагане на Ризата на Божията
# Майка".

# Определения, върху които може да стои членът.
_ЧЛЕНУВАНО = re.compile(r'(ата|ята|ото|ето|ият|ия|ите|ъта)$')

# Думи, които се вмъкват МЕЖДУ определението и съществителното, без да
# отменят члена: „Пречистата МУ Богомайка", „родилата ГО Богомайка".
_ВМЕЖДУ = {'Му', 'Си', 'Ми', 'Ѝ', 'Го', 'Я', 'Тебе', 'Негова', 'Неговата'}

# Нечленувани определения в апозиция: „Дева Богомайка", „Пречиста Богомайка"
# (след притежателно: „Неговата Пречиста Богомайка"). Пред тях
# съществителното също остава нечленувано.
_АПОЗИЦИЯ = {'Пречиста', 'Пресвета', 'Пренепорочна', 'Преблагословена',
             'Дева', 'Владичица', 'Царица'}

_РЕГ_БОГОМАЙКА = re.compile(r'\b(Богомайк(?:ата|а|о))\b')

# Названието на празника: „Полагане на Ризата Богомайка". Тук освен липсващия
# предлог има и струпване на две „на" — първото отпада.
_РЕГ_ПОЛАГАНЕ = re.compile(
    r'\b(Полагане|Положение)\s+на\s+'
    r'([Рр]изата|[Рр]иза|[Пп]ояса|[Пп]оясът|[Пп]ояс)\s+(?:на\s+)?Богомайка\b')

# Същото без „Полагане": „чудотворната Риза Богомайка" — само липсващ предлог.
_РЕГ_ВЕЩ = re.compile(
    r'\b([Рр]изата|[Рр]иза|[Пп]ояса|[Пп]оясът|[Пп]ояс)\s+Богомайка\b')

# Две места, където членът трябва да иде върху ПРИЛАГАТЕЛНОТО, а не върху
# съществителното: „При това Пресвета Богомайка му посочила" (подлог).
# Общото правило не може да ги хване — за него апозицията е достатъчна.
_ТОЧКОВИ = [
    ('При това Пресвета Богомайка', 'При това Пресветата Богомайка'),
    ('помощта на Пресвета Богомайка', 'помощта на Пресветата Богомайка'),
    # В апозиция след „Дева" общото правило дава граматически вярното, но
    # тромаво „Дева Майка Божия". Установеното название е друго (17.08.2026).
    ('Дева Богомайка', 'Дева Богородица'),
]
_ТОЧКОВИ = [(re.compile(r'\b%s\b' % re.escape(а)), б) for а, б in _ТОЧКОВИ]


def _членувано_определение(преди):
    """Има ли пред съществителното определение, което носи члена.

    Гледат се последните няколко думи, не целият предхождащ текст: житието е
    сто килобайта, а решението зависи най-много от три думи наляво.
    """
    думи = re.findall(r'[^\s<>«»„“”"\'(),;:.!?—–-]+', преди[-120:])
    i = len(думи) - 1
    # прескачаме вмъкнатите местоимения и нечленуваните апозиции
    while i >= 0 and (думи[i] in _ВМЕЖДУ or думи[i] in _АПОЗИЦИЯ):
        i -= 1
    if i < 0:
        return False
    if i != len(думи) - 1 and думи[len(думи) - 1] in _АПОЗИЦИЯ:
        # „Дева Богомайка", „Пречиста Богомайка" — апозиция; съществителното
        # остава нечленувано независимо какво стои преди нея.
        return True
    return bool(_ЧЛЕНУВАНО.search(думи[i]))


def правило_богомайка(текст):
    # 1) точковите
    for рег, б in _ТОЧКОВИ:
        текст = рег.sub(б, текст)

    # 2) названието на празника — липсващият предлог плюс махането на
    #    първото „на": „Полагане ризата на Божията Майка"
    текст = _РЕГ_ПОЛАГАНЕ.sub(
        lambda m: '%s %s на Богомайка'
                  % (m.group(1), m.group(2)[:1].lower() + m.group(2)[1:]),
        текст)

    # 3) същото без „Полагане" — само липсващият предлог
    текст = _РЕГ_ВЕЩ.sub(lambda m: '%s на Богомайка' % m.group(1), текст)

    # 4) същинската замяна
    def смени(m):
        форма = m.group(1)
        if форма.endswith('о'):
            return 'Майко Божия'
        if форма.endswith('ата'):
            return 'Божията Майка'
        return ('Майка Божия' if _членувано_определение(текст[:m.start()])
                else 'Божията Майка')

    return _РЕГ_БОГОМАЙКА.sub(смени, текст)


ИМЕНУВАНИ = [('богомайка', правило_богомайка)]


# --------------------------------------------------------------------------

def сглоби(двойки, само_именувани=None):
    правила = [правило_за_двойка(а, б) for а, б in двойки]
    for име, ф in ИМЕНУВАНИ:
        if само_именувани is None or име in само_именувани:
            правила.append(ф)

    def преобрази(текст):
        for п in правила:
            текст = п(текст)
        return текст

    return преобрази


def оглед(корпуси, думи):
    """Брои срещанията на дадени низове, без да пипа нищо."""
    броячи = {д: 0 for д in думи}
    примери = {д: [] for д in думи}
    for к in корпуси:
        def брой(текст, к=к):
            ниско = текст.lower()
            for д in думи:
                for m in re.finditer(re.escape(д.lower()), ниско):
                    броячи[д] += 1
                    if len(примери[д]) < 3:
                        а = max(0, m.start() - 45)
                        примери[д].append('%-11s …%s…' % (
                            к.име, текст[а:m.end() + 45].replace('\n', ' ')))
            return текст
        к.обходи(брой, пиши=False)
    return броячи, примери


def словоформи(корпуси, стъбла):
    """Всички ЦЕЛИ думи, започващи с дадено стъбло, с броевете им.

    Това е стъпката ПРЕДИ да се допише ред в replacements.tsv: скриптът не
    скланя, тъй че всяка форма иска свой ред, а на око се пропускат точно
    редките („нарочитем", „страстотърпецо").
    """
    от_стъбло = {с: {} for с in стъбла}
    регове = [(с, re.compile(r'\b%s[а-яА-Я]*\b' % re.escape(с), re.IGNORECASE))
              for с in стъбла]
    for к in корпуси:
        def брой(текст, _=None):
            for с, рег in регове:
                for m in рег.finditer(текст):
                    д = m.group(0)
                    от_стъбло[с][д] = от_стъбло[с].get(д, 0) + 1
            return текст
        к.обходи(брой, пиши=False)
    return от_стъбло


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--dry-run', action='store_true',
                   help='показва промените, без да пише')
    p.add_argument('--forms', nargs='+', metavar='СТЪБЛО',
                   help='изважда всички словоформи по стъбло')
    p.add_argument('--survey', nargs='*', metavar='ДУМА',
                   help='само брои (без думи — думите от списъка)')
    p.add_argument('--only', nargs='+', metavar='КОРПУС',
                   help='ограничава до изброените корпуси')
    p.add_argument('--limit', type=int, default=12,
                   help='колко примера да покаже на корпус')
    args = p.parse_args()

    корпуси = corpora.по_име(args.only)
    двойки = прочети_списък()

    if args.forms:
        for с, форми in словоформи(корпуси, args.forms).items():
            print('%s*  (%d форми, %d срещания)'
                  % (с, len(форми), sum(форми.values())))
            for д, n in sorted(форми.items(), key=lambda x: -x[1]):
                print('   %5d  %s' % (n, д))
        return

    if args.survey is not None:
        думи = args.survey or sorted({а for а, _ in двойки} | {'Богомайк'})
        броячи, примери = оглед(корпуси, думи)
        for д in думи:
            print('%5d  %s' % (броячи[д], д))
            for пр in примери[д]:
                print('        %s' % пр[:150])
        return

    преобрази = сглоби(двойки)
    пиши = not args.dry_run
    общо = 0
    try:
        for к in корпуси:
            промени = к.обходи(преобрази, пиши=пиши)
            общо += len(промени)
            print('%-11s %5d текста' % (к.име, len(промени)))
            for адрес, стар, нов in промени[:args.limit]:
                print('      %s' % адрес)
    finally:
        corpora.РЕЗЕРВ.затвори()
    print('-' * 60)
    if corpora.РЕЗЕРВ.път:
        print('резерв: %s' % os.path.relpath(corpora.РЕЗЕРВ.път, corpora.ROOT))
        print('  назад: tar xzf %s -C .'
              % os.path.relpath(corpora.РЕЗЕРВ.път, corpora.ROOT))
    print('%s: %d текста' % ('щеше да пипне' if args.dry_run else 'променени',
                             общо))
    if пиши and общо:
        print("""
СЛЕДВА ПРЕСГЛОБЯВАНЕ на изделията от пипнатите извори:
  lives-epub  → cd tools/Translate_lives/scripts && python3 04_build_epub.py
  reference   → cd tools/reference_gen/Translate/scripts && python3 03_build_db.py
  teofan      → cd tools/translate_Teofan/scripts && python3 03_build_db.py
  optina      → cd tools/translate_Optina/scripts && python3 04_build_db.py
  lives       → базата вече е поправена на място (както в 13_bible_links_bg.py)""")


if __name__ == '__main__':
    main()

def _mk(t):
    """{…} → червено; останалото екранирано."""
    out = []
    for i, part in enumerate(re.split(r'[{}]', t)):
        if part:
            e = html.escape(part, quote=False)
            out.append(R0 + e + R1 if i % 2 else e)
    return ''.join(out)


_PREFIX = re.compile(N(r'^((?:' + re.escape(R0) + r'[^<]*' + re.escape(R1) + r'\s*)+)'))
_RESP = re.compile(N(r'^Ли́къ: Гдⷭ҇и поми́лꙋй'))
_PETITION = re.compile(N(r'^(?:Е҆щѐ мо́лимсѧ|Ѡ҆ )'))


def _plain(h):
    return html.unescape(re.sub(r'<[^>]+>', '', h))


def _split(b):
    """(префикс-HTML, тяло-HTML, тяло-текст), всичко в NFD."""
    h = N(b['html'])
    m = _PREFIX.match(h)
    pre = m.group(1) if m else ''
    # префиксът е само етикет („Дїа́конъ:", „Та́же", „["), не цял червен ред
    if pre and _plain(h[len(pre):]).strip() == '':
        pre = ''
    body = h[len(pre):]
    return pre, body, _plain(body)


def _starts(text, keys):
    return any(text.startswith(N(k)) for k in keys)


def apply(units, log):
    for u in units:
        bl = u['blocks']
        k = 0
        while k < len(bl):
            b = bl[k]
            pre, body, text = _split(b)
            whole = _plain(N(b['html']))
            if _starts(text, ИЗТРИЙ) or _starts(whole, ИЗТРИЙ) or _starts(text, ИЗТРИЙ_С_РОЛЯ):
                log.append(('изтрито', C(whole)[:70]))
                with_role = _starts(text, ИЗТРИЙ_С_РОЛЯ)
                del bl[k]
                if with_role and k > 0 and bl[k - 1]['kind'] == 'rubric' \
                        and _plain(bl[k - 1]['html']).rstrip().endswith(':'):
                    log.append(('изтрито', C(_plain(bl[k - 1]['html']))[:70]))
                    del bl[k - 1]
                    k -= 1
                if k < len(bl) and _RESP.match(N(_plain(bl[k]['html']))):
                    prev = _split(bl[k - 1])[2] if k > 0 else ''
                    if not _PETITION.match(prev):
                        del bl[k]
                continue
            for key, new in ПАРАГРАФ:
                if text.startswith(N(key)):
                    if callable(new):
                        nb = new(body)
                    elif b['kind'] == 'rubric' and new.startswith('{') and new.endswith('}'):
                        nb = N(html.escape(new[1:-1], quote=False))   # целият ред е червен
                    else:
                        nb = N(_mk(new))
                    b['html'] = C(pre + nb)
                    if not (isinstance(new, str) and new.startswith('{') and new.endswith('}')):
                        b['kind'] = 'text'
                    log.append(('заменено', C(whole)[:70]))
                    if key == 'Сꙋпрꙋ́гꙋ є҆гѡ̀':
                        for j, t in enumerate(GE_AFTER):
                            bl.insert(k + 1 + j, {'kind': 'text', 'html': C(N(_mk(t)))})
                            log.append(('вмъкнато', t[:70]))
                        k += len(GE_AFTER)
                    break
            else:
                h0 = h = N(b['html'])
                for pat, new in ОТКЪС:
                    h2 = re.sub(N(pat), N(_mk(new)), h, flags=re.S)
                    if h2 != h:
                        log.append(('откъс', C(whole)[:70]))
                        h = h2
                if h != h0:
                    b['html'] = C(h)
            k += 1

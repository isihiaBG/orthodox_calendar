#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Мести описанията на илюстрациите ПОД самите илюстрации.

Вход/изход: `work/parsed/*.json` (пипа ги на място)
⚠ Пуска се СЛЕД `09_place_images.py` и ПРЕДИ `06_apply.py`.

## Защо

В извора надписът стои ПРЕД картинката („Св. Гавриил Лесновски. Детайл от
мозайка…" и чак после изображението), а понякога между двете има и заглавие.
Пренесено едно към едно, това дава описание точно под заглавието на житието —
където най-малко му е мястото — а картинката изплува няколко абзаца по-долу.

## Кое се мести и кое НЕ

⚠ Само описание, до което ИМА картинка в рамките на [WINDOW] блока. Няма ли —
не се пипа: то или описва изображение, което не сме свалили, или изобщо не е
надпис.

⚠ Пазачи срещу фалшиви положителни, всеки заради истински случай:

  „Той паднал пред иконата и казал:"   — РАЗКАЗ, не надпис. Хваща се по
                                         завършващото двоеточие.
  „Текстът и иконата са заети от…"     — бележка за източника на житието.
  „Манастирът е издигнат край…"        — същински текст, споменал икона.

Затова условията са ТРИ наведнъж: къс блок, характерна дума за изображение и
картинка наблизо. Поотделно всяко от тях пропуска.
"""

from __future__ import annotations

import argparse
import json
import re

from common import WORK

RE_TAG = re.compile(r'<[^>]+>')
BLOCK = re.compile(r'<img[^>]*>|<h3>.*?</h3>|<p[^>]*>.*?</p>', re.S)

# Думи, характерни за надпис под изображение.
RE_CAPTION_WORD = re.compile(
    r'(стенопис|мозайка|икона|фрагмент|детайл|фреска|миниатюра|гравюра|'
    r'литография|скулптура|худ\.)', re.I)

# ⚠ Разказ, не надпис: „…и казал:", „…му отговорил:". Двоеточието накрая
# въвежда пряка реч и е сигурният признак.
RE_NARRATIVE = re.compile(r':\s*$')

# ⚠ Бележки за произхода на ТЕКСТА, не на картинката.
RE_SOURCE_NOTE = re.compile(
    r'^\s*(текстът|източник|снимк[аи]те\s+са|материал)', re.I)

MAX_CAPTION = 260      # по-дълъг блок е същински текст
LONG_CAPTION = 200     # над това се иска картинка НЕПОСРЕДСТВЕНО отгоре
WINDOW = 3             # колко блока напред/назад се търси картинка

# ⚠ Надписът е ИМЕННА ФРАЗА („Св. Прохор Пшински. Стенопис от ХV в…"), а
# текстът от житието е ИЗРЕЧЕНИЕ („На двамата братя се наложило да…"). Оттам
# и двата списъка по-долу: единият познава началото на надпис, другият —
# началото на разказ.
RE_CAPTION_START = re.compile(
    r'^\s*(\(|свв?\.|св\s|преп\.|прп\.|папа|икона|стенопис|мозайка|детайл|'
    r'фрагмент|фреска|миниатюра|изглед|гроб|част\s+от|общ\s+вид)', re.I)

# ⚠ Начала, които издават изречение от разказа. Хванати от истински случаи,
# всичките КЪСИ и стоящи непосредствено след картинка — тоест минаващи през
# всички други проверки: „На двамата братя…", „След освобождаването…",
# „Подир смъртта на св. Методий…".
RE_SENTENCE_START = re.compile(
    r'^\s*(на\s|след\s|подир\s|при\s|веднъж|много|така|тогава|затова|'
    r'оттогава|той\s|тя\s|те\s|тези|този|тази|в\s+това|според|сред\s|'
    r'учениците|всяко|син\s+на|'
    # ⚠ Подлог на ТВЪРДЕНИЕ, не име на изобразеното: „Манастирът е издигнат
    # край родното село…" се промъкваше, защото по-нататък в него се среща
    # описателна дума. Надписът назовава какво СЕ ВИЖДА; това разказва.
    r'манастирът|храмът|църквата|обителта|мощите\s+на\s+светеца)', re.I)

# ⚠ Глаголна конструкция веднага след подлога — вторият признак за твърдение.
# Държи се отделно, защото хваща и случаи, които не започват с известна дума.
RE_PREDICATE = re.compile(
    r'^\S+\s+(е|са|бе|бил[аио]?|представлява|се\s+намира|се\s+издига)\s', re.I)

# ⚠ Същият признак, но с ПО-ДЪЛГА ръка: минало деятелно причастие („бил",
# „била", „били") до шестата дума издава РАЗКАЗ, независимо колко думи стои
# подлогът. Надписът назовава изобразеното и няма сказуемо.
#
# Поводът: „Св. мъченик Лазар Български бил от Дебелдял, край Габрово…" е
# самото кратко животоописание, а минаваше за надпис — започва със „Св.",
# стои под картинка, и глаголът му е ПЕТИ, тъй че [RE_PREDICATE] (която
# гледа само втората дума) не го хващаше. Взет за надпис, текстът на
# житието се озова в курсив под чуждо изображение.
# (Докладвано от потребителя, 01.09.2026.)
#
# ⚠ Само „бил/била/било/били" — НЕ и „е"/„са". Те се срещат и в законни
# надписи („Иконата е от XV в."), докато миналото причастие е белег на
# повествование.
RE_PAST_PREDICATE = re.compile(
    r'^(?:\S+\s+){0,5}(бил|била|било|били)\s', re.I)


def is_caption(text: str, after_image: bool = False) -> bool:
    """Надпис на изображение ли е този блок.

    [after_image] — стои ли непосредствено под картинка. Тогава мярката е
    по-снизходителна: там надпис без описателна дума е обичаен („Папа
    Йоан-Павел II на гроба на св. Кирил").
    """
    t = text.strip()
    if not t or len(t) > MAX_CAPTION:
        return False

    # ⚠ ДЪЛГИЯТ блок е надпис САМО когато стои непосредствено под картинка.
    # Разграничението е емпирично (30.08.2026): надписът на Климент Охридски
    # е 251 знака и е истински — стои под изображението си; а два блока при
    # Пимен Зографски със същата дължина съдържат „стенопис“, но са
    # ИЗРЕЧЕНИЯ от житието и не стоят под нищо. Без това условие вторите
    # минаваха за надписи.
    if len(t) > LONG_CAPTION and not after_image:
        return False
    if RE_NARRATIVE.search(t):          # „…и казал:" — пряка реч, не надпис
        return False
    if RE_SOURCE_NOTE.match(t):         # бележка за произхода на текста
        return False
    if RE_SENTENCE_START.match(t):      # изречение от разказа
        return False
    if RE_PREDICATE.match(t):           # подлог + сказуемо = твърдение
        return False
    if RE_PAST_PREDICATE.match(t):      # „…бил от Дебелдял" = разказ
        return False

    if RE_CAPTION_WORD.search(t):
        return True
    # Без описателна дума се приема само ако стои под картинка И започва
    # като именна фраза.
    return after_image and bool(RE_CAPTION_START.match(t))


def rearrange(html: str) -> tuple[str, int]:
    """Премества надписите под картинките им. Връща (нов html, брой)."""
    blocks = [m.group(0) for m in BLOCK.finditer(html)]
    if not blocks:
        return html, 0
    kinds = ['img' if b.startswith('<img') else
             ('h3' if b.startswith('<h3') else 'p') for b in blocks]
    texts = [RE_TAG.sub('', b).strip() for b in blocks]

    moved = 0
    # (индекс на надписа, индекс на картинката) — събират се първо, за да не
    # се местят индексите под краката на обхождането.
    plan: list[tuple[int, int]] = []
    taken: set[int] = set()

    for i, kind in enumerate(kinds):
        if kind != 'p':
            continue
        # Вече е точно под картинка — нищо за правене.
        if i and kinds[i - 1] == 'img':
            continue

        # Най-близката картинка: първо НАПРЕД (в извора надписът стои ПРЕД
        # изображението), после назад.
        target = None
        for j in range(i + 1, min(i + 1 + WINDOW, len(kinds))):
            if kinds[j] == 'img' and j not in taken:
                target = j
                break
        if target is None:
            for j in range(i - 1, max(i - 1 - WINDOW, -1), -1):
                if kinds[j] == 'img' and j not in taken:
                    target = j
                    break
        if target is None:
            continue

        # ⚠ Проверката се прави ЗНАЕЙКИ, че наблизо ИМА картинка. Без това
        # надпис без описателна дума не се разпознаваше: „Гробът на св.
        # Константин-Кирил Философ в църквата „Сан Клементе", Рим" няма нито
        # „стенопис", нито „икона", тъй че оставаше обикновен абзац —
        # неоткъснат от текста и над картинката вместо под нея.
        # (Докладвано от потребителя, 31.08.2026.)
        if not is_caption(texts[i], after_image=True):
            continue
        taken.add(target)
        plan.append((i, target))

    if not plan:
        return html, 0

    # Сглобяване наново: всеки блок си остава на място, освен преместените
    # надписи, които се вмъкват веднага след своята картинка.
    after: dict[int, list[int]] = {}
    dropped: set[int] = set()
    for cap, img in plan:
        after.setdefault(img, []).append(cap)
        dropped.add(cap)
        moved += 1

    out: list[str] = []
    for idx, block in enumerate(blocks):
        if idx in dropped:
            continue
        out.append(block)
        for cap in after.get(idx, []):
            out.append(blocks[cap])


    return '\n'.join(out), moved


# ⚠ Къс текст ИЗЦЯЛО В СКОБИ е сведение на собствен ред, не надпис на
# картинка: „(† 14 февруари 869 година)", „(Превод от гръцки…)". Скобата
# стои там още от източника — тя пази буквицата да не се лепне за него.
#
# Получава СВОЙ клас (`centernote`), защото е ЦЕНТРИРАН, докато надписът е
# подравнен вляво под изображението си. Двата приличат по вид, но играят
# различна роля (уточнено от потребителя, 31.08.2026).
MAX_CENTER_NOTE = 200


# ⚠ БЕЛЕЖКА ЗА ИЗТОЧНИКА на самото четиво — не е разказ и не бива да носи
# буквица. Стои като обикновен абзац и когато се падне ПЪРВА след заглавие,
# `splitDropCap` ѝ дава инициал: при св. Лазар Български буквицата се
# озоваваше върху „† Траянополский епископ Иларион, Пространен православен
# месецослов, изд. Тавор." вместо върху първите думи на житието.
# (Докладвано от потребителя, 01.09.2026.)
#
# ⚠ Признаците са НАЧАЛОТО (кръстче или знак за право) ИЛИ издателска дума,
# и ВИНАГИ къс блок. Само издателската дума не стига — „изд." се среща и в
# разказ; само кръстчето — също, с него започват и бележки за кончина.
RE_PUBLISHER_NOTE = re.compile(
    r'(^\s*[†©]|\bизд\.|\bиздателство|месецослов)', re.I)
MAX_SOURCE_NOTE = 220


def is_source_note(text: str) -> bool:
    t = text.strip()
    return len(t) <= MAX_SOURCE_NOTE and bool(RE_PUBLISHER_NOTE.search(t))


def is_center_note(text: str, after_image: bool = False) -> bool:
    """Кратко сведение в скоби, което стои центрирано на собствен ред.

    [after_image] — стои ли блокът непосредствено под картинка.
    """
    t = text.strip()
    if not (t.startswith('(') and t.endswith(')')):
        return False
    if len(t) > MAX_CENTER_NOTE:
        return False
    # ⚠ Номерирана бележка под линия („(2) Лествицата…") НЕ е това: тя е
    # същински текст и е дълга. Разпознава се по цифра веднага след скобата.
    if re.match(r'^\(\d+\)', t):
        return False
    # ⚠ СКОБИТЕ НЕ РЕШАВАТ, когато блокът стои под картинка и назовава
    # изобразеното: „(Посещението на Авраам… Икона от преп. Андрей Рубльов…)"
    # е НАДПИС в скоби, не самостоятелно сведение. Взет за centernote, той
    # губи връзката с картинката си: в широк изглед `computeRegions` търси
    # `class="caption"`, за да го задържи под нея, тъй че този влизаше в
    # обтичащия текст и се озоваваше ОТСТРАНИ на илюстрацията.
    # (Докладвано от потребителя, 31.08.2026.)
    #
    # ⚠ Мярката е ОПИСАТЕЛНАТА ДУМА, не самото стоене под картинка. Иначе
    # „(† 14 февруари 869 година)", паднало се под изображение, също би
    # станало надпис — а то не описва нищо от него.
    if after_image and RE_CAPTION_WORD.search(t):
        return False
    return True


def fix_orphan_captions(html: str) -> tuple[str, int]:
    """Надпис, останал ПРЕД картинката си, слиза под нея.

    ⚠ Пуска се СЛЕД [mark_captions] — там се слагат класовете, а тази
    функция ги чете. Сложена вътре в [rearrange], тя не работи изобщо:
    там надписите са още обикновени абзаци.

    Случаят е реален (св. Кирил и св. Климент, 31.08.2026): две картинки
    една след друга с по един надпис. Пренареждането слага и двата надписа
    под ПЪРВАТА, тъй че вторият увисва без изображение над себе си, а
    втората картинка остава без надпис. Отвън: „коментар, който не е
    асоцииран с картинката".
    """
    blocks = [m.group(0) for m in BLOCK.finditer(html)]
    if not blocks:
        return html, 0
    moved = 0
    changed = True
    while changed:
        changed = False
        for i in range(len(blocks) - 1):
            a, b = blocks[i], blocks[i + 1]
            if 'class="caption"' not in a or not b.startswith('<img'):
                continue
            # Има ли картинката вече свой надпис под себе си?
            nxt = blocks[i + 2] if i + 2 < len(blocks) else ''
            if 'class="caption"' in nxt:
                continue
            blocks[i], blocks[i + 1] = b, a
            moved += 1
            changed = True
            break
    return '\n'.join(blocks), moved


def has_image_near(kinds: list[str], i: int) -> bool:
    """Има ли илюстрация в рамките на [WINDOW] блока около `i`.

    Същата мярка, с която `move_captions` търси на коя картинка принадлежи
    надписът — нарочно, за да не се разминат двете: текст, достатъчно близо
    да бъде преместен, е достатъчно близо и да бъде стилизиран.
    """
    lo = max(0, i - WINDOW)
    hi = min(len(kinds), i + WINDOW + 1)
    return any(kinds[j] == 'img' for j in range(lo, hi) if j != i)


def mark_captions(html: str) -> tuple[str, int]:
    """Дава `class="caption"` на надписите под илюстрациите.

    ⚠ Пуска се СЛЕД пренареждането, върху вече подредения текст: тогава
    „стои непосредствено под картинка" е надежден признак и се налага
    по-малко гадаене по думи.

    ⚠ Блок, който ВЕЧЕ носи клас (`memorydate`, `prayerhead`), не се пипа —
    той е класифициран по-рано и по друг признак. Без тази проверка редът
    „Чества се на 5 декември" под картинка би станал надпис на илюстрация.
    """
    blocks = [m.group(0) for m in BLOCK.finditer(html)]
    if not blocks:
        return html, 0
    kinds = ['img' if b.startswith('<img') else
             ('h3' if b.startswith('<h3') else 'p') for b in blocks]

    marked = 0
    out: list[str] = []
    for i, block in enumerate(blocks):
        if kinds[i] != 'p' or 'class=' in block[:12]:
            out.append(block)
            continue
        text = RE_TAG.sub('', block).strip()
        after_image = i > 0 and kinds[i - 1] == 'img'
        # ⚠ Скобите се проверяват ПЪРВИ: те са центрирано сведение, не надпис
        # на картинка, и получават свой клас.
        if is_source_note(text):
            out.append(
                re.sub(r'^<p>', '<p class="centernote">', block, count=1))
            marked += 1
        elif is_center_note(text, after_image=after_image):
            out.append(
                re.sub(r'^<p>', '<p class="centernote">', block, count=1))
            marked += 1
        # ⚠ НАДПИС СЕ ДАВА САМО КОГАТО НАБЛИЗО ИМА КАРТИНКА — но „наблизо"
        # значи В ПРОЗОРЕЦА, не „непосредствено отгоре".
        #
        # Двата провала, между които минава това условие, са РАЗЛИЧНИ и всеки
        # е бил истински (01.09.2026):
        #
        #   без никакво условие → надпис без нито една картинка наоколо пак
        #     получаваше курсив. „Св. Климент Охридски, икона от XIV-XV в. от
        #     църквата…" стоеше в края на житието му, на 9000 знака от
        #     най-близката илюстрация, и описваше нищо.
        #
        #   `after_image` (само непосредствено отдолу) → надпис, който стои
        #     ПРЕД своята картинка и не е могъл да се премести, губеше класа
        #     си. А без клас `splitDropCap` го смята за първи абзац и му дава
        #     БУКВИЦА: при св. Лазар Български инициалът изяде „С"-то и
        #     надписът се изписа „в. Лазар Български…".
        #
        # ⚠ Не всеки надпис може да се премести: когато една картинка има
        # кандидат и отпред, и отзад, `taken` я дава на първия, а вторият
        # остава на мястото си. Тогава класът е единственото, което го пази
        # от буквицата.
        elif has_image_near(kinds, i) and is_caption(text, after_image=after_image):
            out.append(re.sub(r'^<p>', '<p class="caption">', block, count=1))
            marked += 1
        else:
            out.append(block)
    return '\n'.join(out), marked


RE_IMG_ALT = re.compile(r'<img\b[^>]*\balt="([^"]*)"[^>]*>', re.I)


def _fold(t: str) -> str:
    """Само букви и цифри, с малки букви — за сравняване на текстове."""
    return re.sub(r'[^0-9a-zа-яёіѣѫ]', '', t.lower())


def split_alt_prefixed(html: str) -> tuple[str, int]:
    """Отлепя надпис, СЛЕПЕН с началото на следващия абзац.

    ⚠⚠ ИСТИНСКИ СЛУЧАЙ, докладван от потребителя (06.09.2026) върху готов PDF:

        <img … alt="Папа Адриан II (в средата с ореол) посреща …">
        <p>Папа Адриан II (в средата с ореол) посреща … (XI век)Облечен в
        такова всеоръжие, той с брата си бил изпратен …</p>

    Забележи, че между „(XI век)" и „Облечен" НЯМА нищо — нито интервал, нито
    нов ред. В извора двете са разделени с таг (курсив или `<br>`), а
    сваляното на таговете ги е слепило. Оттам надписът се озовава като начало
    на РАЗКАЗА: не получава клас `caption`, не отива под картинката си, а на
    страницата се чете като първо изречение на абзаца.

    ⚠ ПРИЗНАКЪТ Е ТОЧЕН, НЕ ЕВРИСТИЧЕН: абзацът започва дословно със същия
    текст, който стои в `alt` на картинката непосредствено преди него. Затова
    тук няма праг по дължина и няма списък с думи — сравнява се съдържание.

    ⚠ Сравнява се СГЪНАТО (само букви и цифри): в `alt` кавичките са
    `&quot;`, а в текста са истински, и на места има вмъкнати нови редове.
    """
    parts = re.split(r'(<img\b[^>]*>)', html)
    out: list[str] = []
    fixed = 0
    for k, part in enumerate(parts):
        out.append(part)
        m = RE_IMG_ALT.fullmatch(part.strip()) if part.strip().startswith('<img') else None
        if m is None:
            continue
        alt = _fold(m.group(1))
        if len(alt) < 25:
            continue                      # твърде къс, за да е сигурен признак
        if k + 1 >= len(parts):
            continue
        след = parts[k + 1]
        pm = re.search(r'<p([^>]*)>(.*?)</p>', след, re.S)
        if pm is None:
            continue
        вътре = pm.group(2)
        плосък = RE_TAG.sub('', вътре)
        if not _fold(плосък).startswith(alt):
            continue
        # ⚠ Режем в СУРОВИЯ текст, като броим сгънатите знаци — така
        # вмъкнатите тагове и нови редове не местят разреза.
        брой = 0
        рез = None
        for i, ch in enumerate(плосък):
            if _fold(ch):
                брой += 1
                if брой == len(alt):
                    рез = i + 1
                    break
        if рез is None:
            continue
        # ⚠ ПУНКТУАЦИЯТА СЛЕД ПОСЛЕДНАТА БУКВА ВЛИЗА В НАДПИСА. Сгънатото
        # броене спира на буква, а „…(XI век)" завършва със СКОБА — без това
        # тя остава да виси в началото на разказа: „)Облечен в такова…".
        while рез < len(плосък) and not _fold(плосък[рез]):
            рез += 1
        глава, опашка = плосък[:рез].strip(), плосък[рез:].strip()
        if not опашка:
            continue                      # цял абзац = надпис; друга стъпка
        нов = (f'<p class="caption">{глава}</p>\n'
               f'<p{pm.group(1)}>{опашка}</p>')
        parts[k + 1] = след[:pm.start()] + нов + след[pm.end():]
        fixed += 1
    # ⚠ Списъкът се сглобява НАКРАЯ: горе се пипа `parts[k + 1]`, тоест
    # елемент, който `out` още не е поел.
    return ''.join(parts), fixed


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()

    total = touched = marked_total = 0
    for path in sorted((WORK / 'parsed').glob('*.json')):
        rec = json.loads(path.read_text(encoding='utf-8'))
        if '<img' not in rec['life_html']:
            continue
        # ⚠ РЕДЪТ Е РЕШАВАЩ и е платен с два опита (30.08.2026):
        #
        #   1. rearrange      — премества надписите под картинките им
        #   2. mark_captions  — разпознава ги и им слага клас
        #
        # ⚠ Изключването на нежелана илюстрация НЕ Е тук, а в отделна
        # ПОСЛЕДНА стъпка (`11_exclude.py`) — виж докстринга ѝ защо.
        new_html, moved = rearrange(rec['life_html'])
        new_html, marked = mark_captions(new_html)
        new_html, fixed = fix_orphan_captions(new_html)
        moved += fixed
        # ⚠ НАКРАЯ: отлепя надпис, слепен с началото на следващия абзац.
        # Пуска се след останалите, защото създава НОВ блок с клас `caption`
        # — а те разчитат кои блокове вече са надписи.
        new_html, split = split_alt_prefixed(new_html)
        marked += split
        if not moved and not marked:
            continue
        total += moved
        marked_total += marked
        touched += 1
        print(f'  {rec["name_core"][:42]:44} премести {moved}, стил {marked}')
        if not args.dry_run:
            rec['life_html'] = new_html
            path.write_text(json.dumps(rec, ensure_ascii=False, indent=2),
                            encoding='utf-8')

    print(f'\nпреместени: {total}   стилизирани: {marked_total}'
          f'   в {touched} жития')
    if args.dry_run:
        print('--dry-run: нищо не е записано')


if __name__ == '__main__':
    main()

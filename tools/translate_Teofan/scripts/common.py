# Съкращенията на библейските книги. Взимат се от машинния код в
# препратката (`Jac.2:14`), а НЕ се превеждат от модела — иначе 443-те
# препратки излизат с 443 различни хрумвания.
#
# Ползват се КЪСИТЕ форми („Мт." вместо „Мат."), защото са по-разпознаваеми
# и защото оригиналът пише по същия начин („Мф., Мк., Лк., Ин."). Наборът е
# нарочно уеднаквен: щом евангелистите са къси, къси са и посланията.
BOOK_BG = {
    'Gen': 'Бит.', 'Ex': 'Изх.', 'Deut': 'Втор.', 'Ps': 'Пс.',
    'Prov': 'Притч.', 'Solom': 'Прем.', 'Sir': 'Сир.', 'Is': 'Ис.',
    'Joel': 'Иоил.', 'Am': 'Ам.', 'Zah': 'Зах.',
    'Mt': 'Мт.', 'Mk': 'Мк.', 'Lk': 'Лк.', 'Jn': 'Ин.',
    'Act': 'Деян.', 'Jac': 'Иак.', '1Pet': '1 Пет.', '2Pet': '2 Пет.',
    '1Jn': '1 Ин.', '2Jn': '2 Ин.', '3Jn': '3 Ин.', 'Rom': 'Рим.',
    '1Cor': '1 Кор.', '2Cor': '2 Кор.', 'Gal': 'Гал.', 'Eph': 'Еф.',
    'Phil': 'Фил.', 'Col': 'Кол.', '1Thes': '1 Сол.', '1Tim': '1 Тим.',
    '2Tim': '2 Тим.', 'Hebr': 'Евр.', 'Apok': 'Откр.',
}


def bulgarian_ref(code):
    """`Jac.2:14` → `Иак.2:14`. Непозната книга се връща както е дошла.

    Надписът се пресъздава от кода, а не се взима от оригинала, за да е
    еднакъв навсякъде: книгата пише ту „Иак.2,14", ту „Иак. 2:14".
    """
    book, dot, rest = code.partition('.')
    if not dot or book not in BOOK_BG:
        return code
    return BOOK_BG[book] + rest

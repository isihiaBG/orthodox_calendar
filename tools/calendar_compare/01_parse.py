#!/usr/bin/env python3
"""pravoslavieto_calendar.htm → work/theirs.json: {ММ-ДД: [запис, …]}.

Страницата е https://pravoslavieto.com/1/calendar.htm (свалена 27.09.2026),
календар по НОВ стил за 2013/2014 г. Датата там Е църковната дата, тъй че
неподвижните памети се сравняват с нашите по ММ-ДД на calendar_new.db.

⚠ Записите за ден са слепени в един поток; делят се по началото на ново
име („Св.", „Свв.", „Събор", „Пренасяне"…), тоест приблизително — затова
сверката после сравнява ПО ДУМИ, а не по цели записи.
"""
import html, json, re
from pathlib import Path

КОРЕН = Path(__file__).resolve().parent
МЕСЕЦИ = ['Януари', 'Февруари', 'Март', 'Април', 'Май', 'Юни', 'Юли',
          'Август', 'Септември', 'Октомври', 'Ноември', 'Декември']


def разчисти(x: str) -> str:
    x = re.sub(r'(?s)<!--.*?-->', ' ', x)   # ⚠ редакторските бележки на сайта
    x = html.unescape(re.sub(r'<[^>]+>', ' ', x))
    return re.sub(r'[\s\xa0]+', ' ', x).strip()


# Начало на нов запис вътре в деня.
RE_ЗАПИС = re.compile(
    r'(?<=[.)\]]) (?=(?:Св\.|Свв\.|Светител|Свети |Събор|Пренасяне|Поклонение|'
    r'Възпоменание|Блажен|Праведн|Старец|Старецът|Намиране|Обновяване|'
    r'Прославяне|Икона|Чудото|Отдание|Предпразненство|Попразненство|Навечерие))')


def main():
    t = (КОРЕН / 'pravoslavieto_calendar.htm').read_text(encoding='utf-8')
    t = re.sub(r'(?s)<!--.*?-->', ' ', t)
    # ⚠ Първата половина на страницата е кратък списък „ЦЪРКОВНИ ПРАЗНИЦИ" —
    # месеците там не са <h2>. Истинският календар е под <h2>Месец</h2>.
    части = re.split(r'<h2>\s*(' + '|'.join(МЕСЕЦИ) + r')\s*</h2>', t)
    дни = {}
    for i in range(1, len(части), 2):
        месец = МЕСЕЦИ.index(части[i]) + 1
        for m in re.finditer(r'(?s)<p[^>]*>\s*(?:<a name="[^"]*"></a>\s*)*(?:<b>\s*)?(\d{1,2})(?:\s*</b>)?(?:&nbsp;|\s)+(.*?)</p>', части[i + 1]):
            ден = int(m.group(1))
            s = разчисти(m.group(2))
            if not s:
                continue
            записи = [x.strip(' .*†') for x in RE_ЗАПИС.split(s) if len(x.strip(' .*†')) > 3]
            дни.setdefault(f'{месец:02d}-{ден:02d}', []).extend(записи)
    (КОРЕН / 'work').mkdir(exist_ok=True)
    (КОРЕН / 'work' / 'theirs.json').write_text(
        json.dumps(дни, ensure_ascii=False, indent=1), encoding='utf-8')
    print('дни:', len(дни), 'записи:', sum(len(v) for v in дни.values()))
    for k in ['01-01', '03-28', '06-19', '12-31']:
        print(k, дни.get(k, []))


if __name__ == '__main__':
    main()

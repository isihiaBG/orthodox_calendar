#!/usr/bin/env python3
"""Сверка: work/theirs.json (pravoslavieto.com, нов стил) срещу нашия
calendar_new.db за 2026 г. → work/report.md.

Търсят се САМО НАШИ пропуски и разминавания — техните не ни интересуват.

Сравнява се ПО ДУМИ: от всеки техен запис се взимат думите с главна буква
(имената и прозвищата), без титлите; запис е „намерен", ако поне половината
от тях (и поне една) се срещат сред нашите памети на същата дата.

⚠ Думите се сгъват: без ударения, й→и, ф→т (у нас θ се предава с „т" от
25.09.2026, у тях често с „ф"), ъ/ь махнати. И се сравнява ПРЕФИКС от 5
букви, защото склоненията и прозвищата се разминават („Габровски" /
„Габровския").

Категории в отчета:
  А  не се намира НИКЪДЕ в нашия календар — кандидат за пропуск;
  Б  у нас е на ДРУГА дата — кандидат за разминаване (или законна втора памет).
"""
import json, re, sqlite3, unicodedata
from collections import defaultdict
from pathlib import Path

КОРЕН = Path(__file__).resolve().parent
БАЗА = КОРЕН.parents[1] / 'assets' / 'db' / 'calendar_new.db'

ТИТЛИ = set('''св свв свети светия светител светители преподобни преподобна
преподобномъченик преподобномъченица мъченик мъченица мъченици мъченичество
свещеномъченик свещеномъченици свещеноизповедник изповедник апостол апостоли
пророк пророчица праведни праведен праведна блажени блажена благоверни
благоверен великомъченик великомъченица епископ архиепископ патриарх папа
митрополит игумен цар царица княз княгиня безсребреници чудотворец
равноапостолни равноапостолна старец старецът събор пренасяне мощите
възпоменание преподобните отци нова година неделя седмица иконата икона
дева дякон дякониса мощи чудото светите'''.split())


def сгъни(w: str) -> str:
    w = unicodedata.normalize('NFD', w.lower()).replace('́', '')
    w = unicodedata.normalize('NFC', w)
    w = w.replace('й', 'и').replace('ф', 'т').replace('ъ', '').replace('ь', '')
    return w


def думи(s: str) -> set:
    s = re.sub(r'\([^)]*\)', ' ', s)          # скобите: години, пояснения
    out = set()
    for w in re.findall(r'[А-ЯЁA-Z][а-яёѝa-ź-]+', s):
        f = сгъни(w)
        if len(f) < 4 or f in ТИТЛИ:
            continue
        out.add(f[:5])
    return out


def main():
    theirs = json.loads((КОРЕН / 'work' / 'theirs.json').read_text(encoding='utf-8'))
    db = sqlite3.connect(БАЗА)
    ours = defaultdict(list)          # ММ-ДД → [имена]
    for d, n, mov in db.execute(
            "SELECT date, name, movable FROM saints WHERE date LIKE '2026-%'"):
        if mov:
            continue
        ours[d[5:]].append(n)
    всички = [(k, n, думи(n)) for k, v in ours.items() for n in v]
    по_дата = {k: set().union(*(думи(n) for n in v)) for k, v in ours.items()}
    from collections import Counter
    честота = Counter(w for _, _, nw in всички for w in nw)

    А, Б, намерени, пропуснати = [], [], 0, 0
    for k in sorted(theirs):
        for e in theirs[k]:
            ws = думи(e)
            # подвижните — паднали на датата от 2013/2014 — не се сверяват
            if not ws or re.search(r'НЕДЕЛЯ|СЕДМИЦА|ПАСХА|ВЕЛИКДЕН|Неделя|седмица|'
                                    r'Задушница|задушница|заговезни|Заговезни', e):
                пропуснати += 1
                continue
            тук = по_дата.get(k, set())
            if len(ws & тук) * 2 >= len(ws):
                намерени += 1
                continue
            # ⚠ За ДРУГА дата съвпадението е по-строго: поне две общи думи,
            # или една-единствена, но РЯДКА (среща се в ≤ 3 наши памети).
            # Иначе общо име („Григорий", „Яков") вързва чужди светии.
            def силно(nw):
                общи = ws & nw
                if len(общи) >= 2 and len(общи) * 3 >= len(ws) * 2:
                    return True
                return len(ws) == 1 and len(общи) == 1 and честота[next(iter(общи))] <= 3
            другаде = [(dk, n) for dk, n, nw in всички if nw and dk != k and силно(nw)]
            if другаде:
                Б.append((k, e, другаде[:3]))
            else:
                А.append((k, e))
    r = ['# Сверка с pravoslavieto.com/1/calendar.htm (нов стил)', '',
         f'Намерени на същата дата: **{намерени}**; '
         f'на друга дата у нас: **{len(Б)}**; не се намират: **{len(А)}**; '
         f'пропуснати (подвижни/без име): {пропуснати}.', '',
         '## А. Не се намират в нашия календар', '']
    r += [f'- `{k}` {e}' for k, e in А]
    r += ['', '## Б. У нас са на друга дата', '']
    for k, e, др in Б:
        r.append(f'- `{k}` {e}')
        for dk, n in др:
            r.append(f'    - у нас `{dk}`: {n}')
    (КОРЕН / 'work' / 'report.md').write_text('\n'.join(r) + '\n', encoding='utf-8')
    print(r[2])


if __name__ == '__main__':
    main()

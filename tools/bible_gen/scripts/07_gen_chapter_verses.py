#!/usr/bin/env python3
"""Последният стих на всяка глава → `lib/bible_chapter_verses.dart`.

ЗАЩО ИЗОБЩО. `_parseCrossChapter` в `lib/bible_ref.dart` разчита препратка
през няколко глави („Евр. 7:26-8:2") на пасажи и за ПЪРВАТА глава трябва да
знае докъде стига тя. Дотук там стоеше запушалка 999 — „таван над всяка
възможна номерация". Работеше за маркирането, но ИЗЛИЗАШЕ НА ЕКРАНА:
надписът над пасажа, заглавието в лентата и подписът при споделяне се
строят от `whereLabel`, тъй че човек виждаше „2 Кор. 4:17-999".

⚠⚠ ВПИСВА СЕ САМО ГЛАВА, ЗА КОЯТО ВСИЧКИ ПРЕВОДИ СА СЪГЛАСНИ. Броят стихове
НЕ е един и същ навсякъде — Септуагинтата и масоретският текст се разминават
и по състав, и по номерация. Мерено върху пълната база (12 превода): 270 от
1361 глави имат разногласие, почти всичките в Стария завет. Впишем ли там
едно число, надписът ще обещава стих, какъвто в показвания превод няма.
Затова разногласните се пропускат и за тях остава старото поведение.

⚠ Мерено и в другата посока: измежду главите, които РЕАЛНО трябват на
проекта (54 за четивата + 5 в житията и томовете), разногласие има в НУЛА —
всичките са новозаветни. Тоест пропускането не струва нищо днес.

⚠ ЧЕТЕ ПЪЛНАТА БАЗА (`output/bible_full.db`), не `assets/db/bible.db`. В
assets стоят само двата вградени превода, а съгласието трябва да се мери по
всичките дванайсет — инак глава, по която bg и utfcs случайно съвпадат, би
влязла с число, което гръцкият опровергава.

Пускане:
    python3 tools/bible_gen/scripts/07_gen_chapter_verses.py
"""
import sqlite3
import sys
from pathlib import Path

КОРЕН = Path(__file__).resolve().parents[3]
БАЗА = КОРЕН / 'tools/bible_gen/output/bible_full.db'
ИЗХОД = КОРЕН / 'lib/bible_chapter_verses.dart'


def main() -> int:
    if not БАЗА.exists():
        print(f'липсва {БАЗА}\n'
              'Пълната база се прави с:\n'
              '    python3 04_build_db.py --out ../output/bible_full.db',
              file=sys.stderr)
        return 1

    db = sqlite3.connect(БАЗА)
    редове = db.execute("""
        SELECT book, chapter, lang, MAX(CAST(verse AS INTEGER))
        FROM verses WHERE CAST(verse AS INTEGER) > 0
        GROUP BY book, chapter, lang
    """).fetchall()

    по_глава: dict[tuple[str, int], set[int]] = {}
    for книга, глава, _, последен in редове:
        по_глава.setdefault((книга, глава), set()).add(последен)

    съгласни = {к: next(iter(v)) for к, v in по_глава.items() if len(v) == 1}
    разногласни = len(по_глава) - len(съгласни)

    # Подредбата е по реда на книгите в Писанието, за да е четим изходът.
    ред = dict(db.execute('SELECT code, ord FROM books'))
    книги: dict[str, dict[int, int]] = {}
    for (книга, глава), последен in съгласни.items():
        книги.setdefault(книга, {})[глава] = последен

    редове_dart = []
    for книга in sorted(книги, key=lambda k: (ред.get(k, 9999), k)):
        глави = книги[книга]
        най = max(глави)
        # ⚠ Списък по ИНДЕКС на главата, не карта: главите са плътни 1..N и
        # списъкът е и по-къс за четене, и по-бърз за търсене. Нулата значи
        # „не се знае" — така разногласната глава не иска отделно множество.
        числа = ','.join(str(глави.get(i, 0)) for i in range(1, най + 1))
        редове_dart.append(f"  '{книга}': [{числа}],")

    ИЗХОД.write_text(
        '// ГЕНЕРИРАН ФАЙЛ — не се редактира на ръка.\n'
        '// Прави го tools/bible_gen/scripts/07_gen_chapter_verses.py\n'
        '//\n'
        '// Последният стих на всяка глава — за да се разчита препратка през\n'
        '// няколко глави („Евр. 7:26-8:2") с ИСТИНСКОТО число, а не със\n'
        '// запушалка.\n'
        '//\n'
        '// ⚠⚠ ВПИСАНА Е САМО ГЛАВА, ПО КОЯТО ВСИЧКИТЕ 12 ПРЕВОДА СА СЪГЛАСНИ.\n'
        '// Броят стихове се разминава между Септуагинтата и масоретския\n'
        f'// текст — {разногласни} от {len(по_глава)} глави, почти всичките в\n'
        '// Стария завет. Там стои 0 и се пада на старото поведение: по-добре\n'
        '// без число, отколкото число, каквото в показвания превод го няма.\n'
        '//\n'
        '// ⚠ Нулата значи „не се знае", а НЕ „глава без стихове".\n'
        '\n'
        '/// Последният стих на всяка глава, по книга. Индексът е глава − 1.\n'
        'const Map<String, List<int>> kChapterLastVerse = {\n'
        + '\n'.join(редове_dart) + '\n};\n',
        encoding='utf-8')

    print(f'глави общо {len(по_глава)}, съгласни {len(съгласни)}, '
          f'разногласни {разногласни}')
    print(f'→ {ИЗХОД.relative_to(КОРЕН)} '
          f'({ИЗХОД.stat().st_size / 1024:.1f} KB)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

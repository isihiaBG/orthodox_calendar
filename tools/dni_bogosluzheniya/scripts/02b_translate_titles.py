#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Заглавията на главите → `work/titles_bg.json`.

⚠ Отделна стъпка: основният превод работи по АБЗАЦИ и заглавието не е сред тях.
Без нея в дневния изглед стои руски ред.

⚠⚠ ЗАГЛАВИЯТА СА СТРУКТУРНИ И ЧЕСТО НЕСАМОСТОЯТЕЛНИ — „Утреня", „Вторая
неделя", „Поучительность праздника". Това НЕ се поправя в превода: главата се
показва в СВОЯ ден, тъй че „Утреня" на Велики петък е напълно ясно. Опитът да
се дописва контекст („Утреня на Велики петък") кара модела да гадае.

⚠ ВСИЧКИТЕ НАВЕДНЪЖ, на порции по 40 — инак моделът избира различна форма за
един и същ израз („Богослужение" ту „Богослужение", ту „Служба").

    python3 02b_translate_titles.py
"""
import importlib.util
import json
from pathlib import Path

ТУК = Path(__file__).resolve().parent
КОРЕН = ТУК.parent
РАБОТА = КОРЕН / 'work'

spec = importlib.util.spec_from_file_location(
    'tr', КОРЕН.parent / 'lives_plus' / 'scripts' / '02_translate_deepseek.py')
tr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tr)

ПРОМПТ = """Ти си опитен преводач на православна църковна литература от руски на български.

Превеждаш ЗАГЛАВИЯ НА ГЛАВИ от книгата „Дни богослужения на Православната църква" на прот. Григорий Дебольски — наръчник за смисъла и службите на църковните дни.

Правила:
1. Кратко и в утвърдения български църковен стил.
2. Имената на светии и празници — в утвърдените БЪЛГАРСКИ форми: „Йоан“, не „Иоанн“; „Теодор“, не „Феодор“; „Атанасий“, не „Афанасий“; „Успение на Пресвета Богородица“.
3. Богослужебните названия са утвърдените български: „Утреня“, „Вечерня“, „Литургия“, „Часове“, „Бдение“, „Велики понеделник“, „Велика събота“, „Петдесетница“, „Четиридесетница“.
4. Числителните за недели остават числителни: „Вторая неделя“ → „Втора неделя“.
5. НЕ дописвай контекст, който го няма в заглавието, и не обяснявай.
6. Кавичките са български: „…“.

Входът е номериран списък, по едно заглавие на ред. Отговори със същите номера, същия ред и същия брой редове.
"""


def main() -> int:
    единици = [json.loads(f.read_text(encoding='utf-8'))
               for f in sorted((РАБОТА / 'units').glob('*.json'))]
    цел = РАБОТА / 'titles_bg.json'
    готови = json.loads(цел.read_text(encoding='utf-8')) if цел.exists() else {}
    липсващи = [x for x in единици if x['id'] not in готови]
    if not липсващи:
        print('всички %d заглавия са преведени' % len(готови))
        return 0

    k = tr.ключ()
    отчет = {'повиквания': 0, 'вход': 0, 'изход': 0}
    for i in range(0, len(липсващи), 40):
        порция = липсващи[i:i + 40]
        tr.ПРОМПТ = ПРОМПТ
        редове = tr.преведи(k, [x['title_ru'] for x in порция], '', отчет)
        if len(редове) != len(порция):
            raise SystemExit('моделът върна %d реда вместо %d — '
                             'номерирането се е разпаднало'
                             % (len(редове), len(порция)))
        for x, bg in zip(порция, редове):
            готови[x['id']] = bg
        цел.write_text(json.dumps(готови, ensure_ascii=False, indent=1),
                       encoding='utf-8')
        print('  %d/%d' % (i + len(порция), len(липсващи)), flush=True)

    print('готови %d заглавия | повиквания %d | изходни токени %s'
          % (len(готови), отчет['повиквания'], format(отчет['изход'], ',')))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

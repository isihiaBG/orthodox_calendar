/// Готовият текст за език, или `null`, ако не се добавя нищо.
///
/// ⚠ Липсващият език НЕ Е грешка — виж [kIncipitText]: при гръцкия, ивритa и
/// подобните обръщението е славянска добавка и просто не важи.
String? apostolIncipitText(String book, int zachalo, String lang) {
  final kind = apostolIncipitFor(book, zachalo);
  if (kind == null || kind == ApostolIncipit.none) return null;
  return kIncipitText[kind]?[lang];
}

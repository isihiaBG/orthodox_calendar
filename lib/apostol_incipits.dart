/// Кое обръщение носи зачалото.
enum ApostolIncipit {
  /// „Братя," — посланията към църкви. Най-честото (227 зачала).
  brethren,

  /// „В ония дни," — Деянията.
  thoseDays,

  /// „Чедо Тимотее," / „Чедо Тите," — пастирските послания.
  childTimothy,
  childTitus,

  /// „Възлюбени," — съборните послания.
  beloved,

  /// ⚠⚠ ИЗРИЧНО „НЯМА ОБРЪЩЕНИЕ" — 26 зачала.
  ///
  /// Такива са онези, които започват със самия текст на посланието („Па́вел,
  /// раб Бо́жий…", „Многоча́стне и многообра́зне…"). Записва се ИЗРИЧНО, а не
  /// с липсващ ключ: инак „няма обръщение" и „не знаем" изглеждат еднакво, а
  /// това са различни неща. Липсващ ключ значи ПРОПУСК, който трябва да се
  /// провери в книгата.
  none,
}


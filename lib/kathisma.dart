// kathisma.dart
//
// Разделението на Псалтира на катизми.
//
// Богослужебният Псалтир е разделен на 20 катизми — дялове, които се четат
// подред, по един на служба, тъй че за седмица се изчита целият Псалтир (а
// през Великия пост — два пъти). Това НЕ е деление на книгата, а на четенето:
// в самото Писание псалмите са просто 1 до 151.
//
// ⚠ Оттук следва къде се ползва и къде НЕ:
//
//   табът „Псалтир"      по катизми — той е за молитвено четене
//   книгата в Стария завет   на куп, 1..151 — там Псалтирът е книга от
//                            Писанието и делението би било чуждо
//
// Затова разделението живее тук, а не в `bible.db`: базата носи Писанието
// такова, каквото е, а катизмите са богослужебна подредба ВЪРХУ него.
// Същото разграничение ще потрябва пак, когато дневният изглед започне да
// показва коя катизма се чете днес.
//
// Псалом 151 нарочно НЕ Е в нито една катизма — той стои извън броя и в
// гръцката, и в славянската традиция. Затова [KathismaTable.extraFor] го
// намира сам, вместо да бъде вписан на ръка: подадат ли се утре 150 псалма
// вместо 151, допълнителните просто ще излязат празни.

import 'package:flutter/foundation.dart';

/// Една катизма: номер и обхват на псалмите в нея (включително двата края).
@immutable
class Kathisma {
  final int number;
  final int from;
  final int to;

  const Kathisma(this.number, this.from, this.to);

  /// Номерата на псалмите в нея.
  List<int> get psalms => [for (var p = from; p <= to; p++) p];

  int get count => to - from + 1;

  /// Как се изписва обхватът: „Пс. 1–8" или „Пс. 118" при единствен.
  String get range => from == to ? 'Пс. $from' : 'Пс. $from–$to';
}

/// Двайсетте катизми.
///
/// ⚠ Границите са по СЛАВЯНСКАТА (и гръцката) номерация на псалмите — същата,
/// която ползва и източникът на текстовете. При еврейската номерация
/// повечето псалми са с един номер напред и таблицата НЕ БИ СЕ ПОДРЕДИЛА.
///
/// Катизма 17 е един-единствен псалом — 118-и, „Непорочни". Той е най-дългият
/// в Псалтира (176 стиха) и сам съставя дял; това не е грешка в таблицата.
const List<Kathisma> kKathismata = [
  Kathisma(1, 1, 8),
  Kathisma(2, 9, 16),
  Kathisma(3, 17, 23),
  Kathisma(4, 24, 31),
  Kathisma(5, 32, 36),
  Kathisma(6, 37, 45),
  Kathisma(7, 46, 54),
  Kathisma(8, 55, 63),
  Kathisma(9, 64, 69),
  Kathisma(10, 70, 76),
  Kathisma(11, 77, 84),
  Kathisma(12, 85, 90),
  Kathisma(13, 91, 100),
  Kathisma(14, 101, 104),
  Kathisma(15, 105, 108),
  Kathisma(16, 109, 117),
  Kathisma(17, 118, 118),
  Kathisma(18, 119, 133),
  Kathisma(19, 134, 142),
  Kathisma(20, 143, 150),
];

/// Помощни сметки върху таблицата.
class KathismaTable {
  KathismaTable._();

  /// Всички псалми, покрити от катизмите (1–150).
  static Set<int> get covered => {
        for (final k in kKathismata) ...k.psalms,
      };

  /// Псалмите, които НЕ влизат в нито една катизма.
  ///
  /// Смята се, вместо да се впише: така никой псалом не може да изчезне
  /// мълчаливо от таба, каквото и да носи базата. При днешните 151 глави
  /// това е точно 151-ви.
  static List<int> extraFor(int totalPsalms) {
    final have = covered;
    return [
      for (var p = 1; p <= totalPsalms; p++)
        if (!have.contains(p)) p,
    ];
  }

  /// Коя катизма съдържа даден псалом (или `null`, ако е извън тях).
  static Kathisma? forPsalm(int psalm) {
    for (final k in kKathismata) {
      if (psalm >= k.from && psalm <= k.to) return k;
    }
    return null;
  }
}

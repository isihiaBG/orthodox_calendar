// church_dates.dart
//
// ЖИВИТЕ ДАТИ НА ПРАЗНИЦИ В ЧЕТИВАТА — „⟦дата:09-01⟧" се изписва според
// това в какъв режим е календарът В МОМЕНТА НА ОТВАРЯНЕ.
//
// ⚠⚠ ЗАЩО ИЗОБЩО. Преведените статии цитират датите както ги дава изворът —
// „14 септември по нов стил (1 септември – по «старому»)". Това е ЧУЖДА
// уговорка: тя изрежда и двата стила наведнъж и слага водещ онзи, който
// авторът е избрал. Човек, отворил приложението по нов стил, чете за втора
// дата, каквато никъде в календара му не се среща; а по стар стил вижда
// подредба, обратна на неговата настройка. Затова в текста стои само
// ЦЪРКОВНАТА дата, а изписването се сглобява при всяко отваряне.
//
// ⚠ Същият похват вече се ползва два пъти: `⟦пост⟧` в справочника
// (reference_text.dart) и `⟦пасха±N⟧` в сказанието за Великден
// (pascha_dates.dart). Тук е третият и е СТАНДАРТЪТ за всяко бъдещо четиво:
// цитирана дата на празник се вписва като запушалка, не като число.
//
// Трите изхода (уговорени с потребителя, 19.09.2026):
//
//     нов стил              1 септември              една дата, БЕЗ знак
//     стар, водеща гражд.   14 сеп / ⛪ 1 сеп
//     стар, водеща църк.    ⛪ 1 сеп / 14 сеп
//
// ⚠ Знакът е САМО църквицата, и САМО пред църковната дата. Телевизорът
// (с който календарът бележи гражданската) нарочно го няма — в календара
// двете иконки стоят една срещу друга и се четат като двойка, а насред
// изречение телевизорът изглежда грубо. (Изрично от потребителя.)
//
// ⚠ Знакът върви ПРЕД своята дата и в двата случая — както навсякъде в
// приложението (виж `dualDateSpans` в dual_date_text.dart). Инак в единия
// режим той е отпред, а в другия отзад, и двете изписвания престават да
// изглеждат като едно и също нещо.
//
// ⚠ Единичната дата е с ПЪЛНОТО име на месеца, двойната — със съкратеното.
// Едната е част от изречението и се чете като дума; другата е справка и
// трябва да се побере, без да разкъсва реда.
// ⚠⚠ ЗАЩО ФУНКЦИИТЕ ПРИЕМАТ СТИЛА КАТО ПАРАМЕТЪР, вместо да го четат сами
// от `AppSettings`: четивото се подготвя във ФОНОВ ИЗОЛАТ (`compute()` в
// reader_screen.dart), а изолатът тръгва със СВОЯ памет — статичните полета
// там са каквито ги заварва обявлението им, не каквото човекът е избрал.
// Тъй че прочетени вътре, те ВИНАГИ даваха „стар стил, водеща гражданска"
// и датите изглеждаха заковани: смениш календара, а четивото не мръдва.
// (Докладвано от потребителя, 20.09.2026.)
//
// ⚠ Празен параметър значи „питай AppSettings" — за повикванията от
// главния изолат (PDF-ът, тестовете), където полетата са истинските.
library;

import 'app_settings.dart';
import 'paschalion_offset.dart';
import 'style_dates.dart';

const List<String> _months = [
  'януари', 'февруари', 'март', 'април', 'май', 'юни',
  'юли', 'август', 'септември', 'октомври', 'ноември', 'декември',
];

const List<String> _monthsShort = [
  'яну', 'фев', 'мар', 'апр', 'май', 'юни',
  'юли', 'авг', 'сеп', 'окт', 'ное', 'дек',
];

final RegExp _placeholder = RegExp(r'⟦дата:(\d{2})-(\d{2})⟧');

/// Отместването между двата календара — за ТЕКУЩАТА година.
///
/// ⚠ Не е закованото 13: от 1 март 2100 г. става 14 (виж paschalion_offset).
/// Датата в запушалката е ЦЪРКОВНА, тъй че гражданската се смята от нея.
int _offset() => julianOffset(DateTime.now().year);

/// „⟦дата:09-01⟧" → готовото HTML за текущия режим.
///
/// Църквицата излиза като таг `<hram></hram>`, който четецът рисува с
/// `Icons.church` (виж `_hramExtension` в reader_screen.dart).
///
/// ⚠ Тагът се ЗАТВАРЯ изрично. Самозатварящият се `<hram/>` поглъща
/// остатъка от абзаца — същият капан, документиран при `<znak>`.
String _full(int m, int d) => '$d ${_months[m - 1]}';
String _short(int m, int d) => '$d ${_monthsShort[m - 1]}';

/// Двойката „гражданска / църковна" в реда, избран от човека.
///
/// ⚠ ЕДНО МЯСТО за двата вида дати — неподвижната (по църковно ММ-ДД) и
/// подвижната (спрямо Пасха). Разминат ли се, едно и също изречение се
/// изписва по два начина в две съседни четива.
String _pairHtml(DateTime civil, DateTime church, bool oldFirst) {
  // ⚠ Имената са на латиница — кирилско име в Dart гърми с „Illegal
  // character" (платено седем пъти в един ден).
  final cerk = _short(church.month, church.day);
  final grazh = _short(civil.month, civil.day);
  return oldFirst
      ? '<hram></hram>$cerk / $grazh'
      : '$grazh / <hram></hram>$cerk';
}

String churchDateHtml(int month, int day, {bool? oldStyle, bool? oldFirst}) {
  final old = oldStyle ?? AppSettings.isOldStyle;
  if (!old) return _full(month, day);
  // Гражданската дата на същия ден. ⚠ Не се смята с `Duration` — виж
  // style_dates.dart защо; тук и без това няма истинска дата, а само
  // (месец, ден), тъй че годината служи само за преливането през месец.
  final civil = DateTime(DateTime.now().year, month, day + _offset());
  return _pairHtml(civil, DateTime(civil.year, month, day),
      oldFirst ?? AppSettings.oldStyleFirst);
}

/// Същото, но за дата, която е ГРАЖДАНСКА по произход — подвижните
/// празници спрямо Пасха („⟦пасха+7⟧" в сказанието за Великден).
///
/// ⚠⚠ ДВАТА ВИДА СЕ РАЗЛИЧАВАТ САМО ПРИ НОВ СТИЛ, и това не е дребно.
/// При неподвижния празник записаното ММ-ДД Е новостилната дата (виж
/// „ПРИ НОВ СТИЛ ГРАЖДАНСКАТА ДАТА Е ЦЪРКОВНАТА" в CLAUDE.md). Пасха
/// обаче пада на един и същи ФИЗИЧЕСКИ ден в двата стила, тъй че там
/// меродавна е гражданската дата, а църковната се смята от нея.
String civilDateHtml(DateTime civil, {bool? oldStyle, bool? oldFirst}) {
  if (!(oldStyle ?? AppSettings.isOldStyle)) {
    return _full(civil.month, civil.day);
  }
  return _pairHtml(civil, toChurchDate(civil),
      oldFirst ?? AppSettings.oldStyleFirst);
}

/// Заменя всички запушалки за дати в готовото HTML.
String expandChurchDates(String html, {bool? oldStyle, bool? oldFirst}) =>
    html.replaceAllMapped(
        _placeholder,
        (m) => churchDateHtml(int.parse(m.group(1)!), int.parse(m.group(2)!),
            oldStyle: oldStyle, oldFirst: oldFirst));

/// Същото, но за гол текст (заглавия, надписи) — там таг не може да влезе,
/// тъй че църквицата се подменя с думата. Ползва се от PDF-а и от всяко
/// място, което показва заглавие без HTML.
String expandChurchDatesPlain(String text) =>
    expandChurchDates(text).replaceAll('<hram></hram>', 'църк. ');

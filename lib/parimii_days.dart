class ParimiaReading {
  final String service;
  final String label;
  final String book;
  final List<String> refs;

  /// Свободна компилация — отваря се в книгата „Паримии", не в Библията.
  final bool compiled;
  const ParimiaReading(this.service, this.label, this.book, this.refs,
      {this.compiled = false});
}


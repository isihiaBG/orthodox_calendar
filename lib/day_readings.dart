/// Как се ИЗПИСВА книгата в реда. Евангелията с пълно име (така е и в
/// печатните календари), посланията — със съкращението си.
const Map<String, String> _kDisplay = {
  'Mt': 'Матей', 'Mk': 'Марк', 'Lk': 'Лука', 'Jn': 'Йоан',
};

String _fold(String s) =>
    s.toLowerCase().replaceAll(RegExp(r'[^а-я0-9]'), '');

/// „Лк. 113 (24:12-35)" → едно четиво. `null`, ако не е четиво.
///
/// ⚠ „от полу" („от средата на зачалото") се ЗАПАЗВА в изписването, но не
/// мени препратката: главата и стиховете в скоби вече са точни.
ReadingLine? _lineFrom(String raw) {
  final m = RegExp(
    // ⚠ ЛАТИНСКИ БУКВИ ВЪТРЕ В КИРИЛСКАТА ДУМА. В базата стои „Иoaн." с
    // латинско „o" и „a" — изглежда еднакво и никога не съвпада. Същият
    // капан е записан и за tools/corrections (виж CLAUDE.md). Затова класът
    // допуска и латиница, а `_fold` после я изхвърля.
    r'^((?:[1-3]\s*)?(?:[А-Яа-яЁёA-Za-z]+\.?\s*){1,2}?)\s*'
    // ⚠ Зачалото се признава само ако подире му ИДВАТ СКОБИ. Инак „Бит.
    // 1:1-20" би прочело „1" за зачало, а то е глава.
    // ⚠ Зачалото понякога носи излишна точка — „Марк 8. (2:14-17)".
    r'(?:(\d+)\.?\s*(от\s+полу)?\s*\(([^)]*)\)'
    r'|([\d:,\s–-]+))\s*$',
  ).firstMatch(raw.trim());
  if (m == null) return null;

  final code = _kBookCode[_fold(m.group(1)!)];
  if (code == null) return null;

  final zach = m.group(2);
  final otPolu = m.group(3) != null;
  // ⚠ Група 4 е „в скоби" (четиво със зачало), група 5 — „без скоби"
  // (старозаветна паримия). Едната от двете винаги е празна.
  final verses = (m.group(4) ?? m.group(5))?.trim();

  final b = StringBuffer(_kDisplay[code] ?? m.group(1)!.trim());
  if (zach != null) b.write(', зач. $zach');
  if (otPolu) b.write(' от полу');
  if (verses != null && verses.isNotEmpty) b.write(', гл. $verses');

  // ⚠ Връзката иска ГЛАВА И СТИХОВЕ. Зачалото не стига — bible.db адресира
  // по стих, а превод зачало→стихове тук няма.
  BibleRef? ref;
  if (verses != null && verses.isNotEmpty) {
    // ⚠ Точката и запетаята значи същото като запетаята — „13:24-30; 36-43".
    // Това е ЕДИНСТВЕНАТА нормализация тук: останалите повредени записи
    // („11-27:30", „8:1-5:185" — общо 7 от 1500) НЕ се гадаят. По-добре ред
    // без връзка, отколкото връзка към ГРЕШНИ стихове.
    final parsed = parseBibleRef('$code.${verses.replaceAll(';', ',')}');
    if (parsed.passages.isNotEmpty) ref = parsed;
  }
  return ReadingLine(b.toString(), ref);
}

/// Един запис от базата → етикет и четивата в него.
///
/// ⚠ ЕДИН ЗАПИС МОЖЕ ДА НОСИ НЯКОЛКО ЧЕТИВА: „1 час: Деян. 33 (13:25-32)
/// Мат. 5 (3:1-11)". Режат се по затварящата скоба, а не по интервал.
(String?, List<ReadingLine>) _parseRow(String raw) {
  var s = raw.trim();
  String? label;

  final colon = s.indexOf(':');
  // ⚠⚠ ДВОЕТОЧИЕ ИМА И ВЪТРЕ В СТИХОВЕТЕ („Притч. 1:1-20"). Признакът НЕ е
  // дължината — той е какво стои СЛЕД двоеточието: етикетът се следва от име
  // на книга (буква), а стиховете — от цифра. Дотук се гледаше само
  // дължината и „Притч. 1" минаваше за етикет, а книгата изчезваше.
  if (colon > 0 &&
      colon <= 32 &&
      !s.substring(0, colon).contains('(') &&
      // ⚠ „2 Тим.", „1 Кор." ЗАПОЧВАТ С ЦИФРА. Правило „след двоеточието
      // трябва да е буква" ги отхвърля и „На мчка: 2 Тим. 292" изпада.
      // Затова се допуска и водеща цифра 1–3, но САМО с интервал подире ѝ —
      // така „1:1-20" (стихове) си остава отхвърлено.
      RegExp(r'^\s*(?:[1-3]\s+)?[А-Яа-яЁёA-Za-z]')
          .hasMatch(s.substring(colon + 1))) {
    label = s.substring(0, colon).trim();
    s = s.substring(colon + 1).trim();
  }

  // ⚠⚠ ЕТИКЕТ БЕЗ ДВОЕТОЧИЕ — „Веч. Бит. 1:1-20". „Веч." (вечерня) е
  // указание за службата, а не част от името на книгата; слети, дават
  // „вечбит", каквото няма в картата, и всичките паримии изпадаха.
  //
  // ⚠ РЕЗЕРВНО правило, СЛЕД двоеточието: приложено първо, то отрязваше
  // „Утр." и от „Утр. Ев. 7: Иоан 63", с което чупеше 237 реда наведнъж.
  if (label == null) {
    for (final p in const ['Веч.', 'Утр.', 'Лит.']) {
      if (s.startsWith('$p ')) {
        label = p.substring(0, p.length - 1);
        s = s.substring(p.length).trim();
        break;
      }
    }
  }

  final lines = <ReadingLine>[];
  for (final part in _splitReadings(s)) {
    final l = _lineFrom(part);
    if (l != null) lines.add(l);
  }
  // ⚠ Ред, от който не излезе НИТО ЕДНО четиво, е БЕЛЕЖКА, а не боклук —
  // „Царските часове от Навечерие на Богоявление се пренасят на Петък".
  // Изхвърлен, той изчезва безследно, а носи указание за деня.
  if (lines.isEmpty && s.length > 12) {
    return (label, [ReadingLine(raw.trim(), null, isNote: true)]);
  }
  return (label, lines);
}

/// Разцепва „Деян. 33 (13:25-32) Мат. 5 (3:1-11)" на две.
List<String> _splitReadings(String s) {
  final out = <String>[];
  var start = 0;
  var depth = 0;
  for (var i = 0; i < s.length; i++) {
    if (s[i] == '(') depth++;
    if (s[i] == ')') {
      depth--;
      if (depth == 0) {
        out.add(s.substring(start, i + 1));
        start = i + 1;
      }
    }
  }
  if (start < s.length && s.substring(start).trim().isNotEmpty) {
    out.add(s.substring(start));
  }
  return out.where((x) => x.trim().isNotEmpty).toList();
}

/// Записите за един ден → групи, готови за рисуване.
///
/// ⚠ Редовете БЕЗ етикет отиват под „Лит.:" — те са четивата на самия ден.
/// Редът им се пази какъвто е в базата: изворът ги е подредил богослужебно.
List<ReadingGroup> groupReadings(List<String> rows) {
  final groups = <String, List<ReadingLine>>{};
  final order = <String>[];
  for (final row in rows) {
    final (label, lines) = _parseRow(row);
    if (lines.isEmpty) continue;
    final key = (label == null || label.isEmpty) ? 'Лит.' : label;
    if (!groups.containsKey(key)) {
      groups[key] = [];
      order.add(key);
    }
    groups[key]!.addAll(lines);
  }
  return [for (final k in order) ReadingGroup(k, groups[k]!)];
}

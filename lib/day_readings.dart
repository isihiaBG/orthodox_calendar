// day_readings.dart
//
// Евангелските и апостолските четива за деня — разчитане на записите от
// таблицата `readings` и превръщането им в АКТИВНИ ВРЪЗКИ към четеца.
//
// ⚠⚠ ЗАПИСИТЕ СА ТЕКСТ, не структура. Изворът им е парснат отвън и носи
// всичко в един низ:
//
//     Утр. Ев. 7: Иоан 63 (20:1-10)
//     На Богородица: Флп. 240 (2:5-11)
//     Притч. 10-11                     ← паримия, без зачало
//
// Разчита се на три части: ЕТИКЕТ (по избор, преди двоеточието), КНИГА със
// ЗАЧАЛО, и глава със стихове в скоби. Само третата дава връзка към текста —
// зачалото само по себе си не стига, защото `bible.db` адресира по стих.
//
// ⚠ Съществуващите `readings` са ПО СТАРИЯ СТИЛ за неподвижната част (виж
// CLAUDE.md). Подвижната е вярна за двата стила, защото Пасха пада на една и
// съща гражданска дата и в двете бази.

import 'bible_ref.dart';

/// Едно четиво: „Лк. 113 (24:12-35)".
class ReadingLine {
  /// Как да се изпише — „Лука, зач. 113, гл. 24:12-35".
  final String display;

  /// Препратката към текста, или `null` (паримия без глава, повреден запис).
  final BibleRef? ref;

  /// Бележка ли е това, а не четиво — „Царските часове се пренасят на…".
  ///
  /// ⚠ Такива редове НЕ се изхвърлят: те носят истинско указание за деня, а
  /// изхвърлени, изчезват безследно. Рисуват се като текст, без връзка.
  final bool isNote;

  const ReadingLine(this.display, this.ref, {this.isNote = false});

  bool get tappable => ref != null && ref!.passages.isNotEmpty;
}

/// Група четива под общо заглавие — „Утр. Ев. 5", „Лит.:", „На светителя:".
class ReadingGroup {
  final String title;
  final List<ReadingLine> lines;
  const ReadingGroup(this.title, this.lines);
}


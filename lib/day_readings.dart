/// Записите за един ден → групи, готови за рисуване.
///
/// ⚠⚠ ЕВАНГЕЛИЕТО НАСЛЕДЯВА ЕТИКЕТА НА АПОСТОЛА ПРЕД СЕБЕ СИ.
///
/// Изворът подрежда четивата в ДВОЙКИ — апостол, после евангелие, — а
/// етикетът стои само на апостола:
///
///     apostle | Гал. 202 (2:11-16)          ← без етикет = на деня
///     gospel  | Марк 21 (5:24-34)           ← на деня
///     apostle | На ап.: Тит. 300 (…)        ← на апостола
///     gospel  | Мат. 11 (5:14-19)           ← СЪЩО на апостола
///
/// Без това правило второто евангелие попадаше при четивата на деня и не се
/// виждаше на кого е. (Докладвано от потребителя, 07.09.2026.)
///
/// Измерено: 576 от 657-те литургийни евангелия са непосредствено
/// предшествани от апостол, а само 17 носят СВОЙ етикет — тъй че двойката е
/// правилото, а не изключението.
///
/// ⚠ Утринното евангелие НЕ участва в двойките: то е от друга служба и
/// винаги си носи етикет („Утр. Ев. 7").
///
/// ⚠ Редовете БЕЗ етикет отиват под „Лит." — те са четивата на самия ден.
/// Редът им се пази какъвто е в базата: изворът ги е подредил богослужебно.
List<ReadingGroup> groupReadings(List<ReadingRow> rows) {
  final groups = <String, List<ReadingLine>>{};
  final order = <String>[];
  String? lastApostleLabel;

  // ⚠ Кои редове са част от дванайсетте страстни — определя се ПРЕДИ цикъла,
  // защото признакът е ПОРЕДИЦАТА, а не отделният ред: Мк 67, Лк 111 и Мф 113
  // се четат и на часовете на Велики петък, но там са с етикет.
  final passion = _passionIndexes(rows);

  for (var idx = 0; idx < rows.length; idx++) {
    final (type, raw) = rows[idx];
    final passionNo = passion[idx];
    var (label, lines) =
        _parseRow(raw, isApostle: type == 'apostle' || type == 'liturgy');
    if (lines.isEmpty) continue;

    final isMatins = (label ?? '').startsWith('Утр');
    // ⚠ И видът „liturgy" задава етикета: това са апостолски четива на
    // определена служба („Вас. лит.: Евр. 311", „На лит.: 1 Кор. 143"), тъй
    // че евангелието подире им се отнася към ТЯХ. Пропуснат, редът наследява
    // етикета на по-предния апостол и излиза при чужда памет.
    if (type == 'apostle' || type == 'liturgy') {
      lastApostleLabel = label;
    } else if (type == 'gospel' && label == null && !isMatins) {
      // Евангелие без свой етикет — взима този на апостола пред себе си.
      label = lastApostleLabel;
    }
    if (isMatins) lastApostleLabel = null;

    // ⚠ Страстните евангелия са ЕДИН дял с номерирани редове, както ги дава
    // и календарът на Kotyuk („1-е. Ин., 46 зач…"), а не дванайсет отделни
    // заглавия. Номерът застава пред самия ред.
    if (passionNo != null) {
      lines = [
        for (final l in lines)
          ReadingLine('$passionNo. ${l.display}', l.ref,
              zachalo: l.zachalo,
              isNote: l.isNote, isApostle: l.isApostle)
      ];
    }
    final key = passionNo != null
        ? kPassionTitle
        : (label == null || label.isEmpty) ? 'Лит.' : label;
    if (!groups.containsKey(key)) {
      groups[key] = [];
      order.add(key);
    }
    groups[key]!.addAll(lines);
  }
  // ⚠⚠ ГРУПИТЕ СЕ ПОДРЕЖДАТ ПО РЕДА НА СЛУЖБИТЕ, не по реда в базата.
  //
  // Изворът невинаги ги е записал хронологично: на Велики петък „Веч.:
  // 1 Кор." стои ПЪРВИ ред, а вечернята е последната служба на деня, тъй че
  // излизаше над часовете. (Докладвано от потребителя, 07.09.2026, със
  // справка от календара на Kotyuk.)
  //
  // ⚠ Подредбата е УСТОЙЧИВА: непознат етикет пази мястото си спрямо
  // съседите. Само познатите се местят — нищо не се преподрежда на сляпо.
  final ordered = [for (final k in order) ReadingGroup(k, groups[k]!)];
  ordered.sort((a, b) => _serviceRank(a.title).compareTo(_serviceRank(b.title)));
  return ordered;
}

/// Четивата, които РЕАЛНО се падат на този ден.
///
/// ⚠⚠ ДВАНАЙСЕТТЕ СТРАСТНИ СЕ ПРЕНАСЯТ ЗА СЛЕДВАЩИЯ ДЕН.
///
/// В базата те стоят на ВЕЛИКИ ЧЕТВЪРТЪК, защото там често се четат физически
/// — когато се прави бдение и петъчната утреня се служи предварително. Но
/// принадлежат на утренята на ВЕЛИКИ ПЕТЪК, а тя е първата служба на деня.
/// (Уточнено от потребителя, 07.09.2026.)
///
/// Затова: махат се от деня, в който са записани, и се долепят НАЙ-ОТПРЕД към
/// следващия. Правилото е симетрично, тъй че не може да ги покаже два пъти,
/// нито да ги изгуби.
///
/// ⚠ Това е кръпка върху ЗАВАРЕНИ данни. При генерирането четивата ще се
/// поставят направо на верния ден и функцията ще стане излишна.
List<ReadingRow> effectiveRows(
    List<ReadingRow> today, List<ReadingRow> yesterday) {
  final out = <ReadingRow>[];

  final fromYesterday = _passionIndexes(yesterday);
  if (fromYesterday.isNotEmpty) {
    final keys = fromYesterday.keys.toList()..sort();
    for (final i in keys) {
      out.add(yesterday[i]);
    }
  }

  final todayPassion = _passionIndexes(today);
  for (var i = 0; i < today.length; i++) {
    if (!todayPassion.containsKey(i)) out.add(today[i]);
  }
  return out;
}

/// Кои редове образуват дванайсетте страстни евангелия: индекс → номер (1..12).
///
/// ⚠ Иска се ЦЯЛАТА поредица, и то последователна. Частично съвпадение не се
/// приема: три от дванайсетте (Мк 67, Лк 111, Мф 113) се четат и на часовете
/// на Велики петък, тъй че отделният ред не е признак.
Map<int, int> _passionIndexes(List<ReadingRow> rows) {
  final out = <int, int>{};
  for (var start = 0; start + kPassionGospels.length <= rows.length; start++) {
    var ok = true;
    for (var k = 0; k < kPassionGospels.length; k++) {
      final (type, raw) = rows[start + k];
      if (type != 'gospel') {
        ok = false;
        break;
      }
      final bz = _bookZachalo(raw);
      if (bz == null || bz != kPassionGospels[k]) {
        ok = false;
        break;
      }
    }
    if (ok) {
      for (var k = 0; k < kPassionGospels.length; k++) {
        out[start + k] = k + 1;
      }
      return out;
    }
  }
  return out;
}

/// Кога през деня се служи това — по-малкото е по-рано.
///
/// ⚠ Стойността по подразбиране (50) е В СРЕДАТА нарочно: непознат етикет
/// остава между литургията и вечернята, вместо да отскача в единия край.
/// Заедно с устойчивото сортиране това значи, че непознатото не се пипа.
int _serviceRank(String title) {
  final t = title.toLowerCase();
  if (t.startsWith('утр')) return 10;
  // ⚠⚠ СТРАСТНИТЕ ЕВАНГЕЛИЯ СА НА УТРЕНЯТА НА ВЕЛИКИ ПЕТЪК И СА ПЪРВИ.
  //
  // Физически често се четат в ЧЕТВЪРТЪК ВЕЧЕР — когато се прави бдение и
  // петъчната утреня се служи предварително. Но принадлежат на ПЕТЪКА, а
  // утренята е преди часовете. (Уточнено от потребителя, 07.09.2026.)
  if (t == kPassionTitle.toLowerCase()) return 5;
  // Часовете: 1-ви, 3-ти, 6-ти, 9-ти — по числото в етикета.
  final hour = RegExp(r'^(\d+)\s*час').firstMatch(t);
  if (hour != null) return 20 + int.parse(hour.group(1)!);
  if (t.startsWith('лит') || t.startsWith('на лит')) return 40;
  if (t.startsWith('вас. лит')) return 40;
  if (t.startsWith('веч')) return 80;
  return 50;
}

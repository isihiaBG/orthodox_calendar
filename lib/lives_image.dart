//
// Илюстрациите в житията, четени от БАЗАТА — икони, стенописи и мозайки към
// житията на българските светии (виж tools/lives_bg/).
//
// Защо изобщо е нужно: описанията на тези изображения („Стенопис от ХV в. в
// църквата…") стоят в самия текст на житието. Пояснение без картинка се чете
// като недоглеждане — по-лошо от липсата и на двете.
//
// Роднина на [BookImageExtension], но по-прост: там байтовете идват от .epub
// архива и относителният път се разрешава спрямо главата; тук файловете са в
// `assets/lives_images/` и адресът в текста вече е пълният път до тях
// (слага го `09_place_images.py`).
//
// ⚠ Липсва ли файлът, НЕ СЕ РИСУВА НИЩО — по същото правило като при
// книгите. Счупена иконка насред житие е по-лоша от липсваща картинка, а и
// текстът около нея продължава да се чете смислено.

import 'package:flutter/material.dart';
import 'package:flutter_html/flutter_html.dart';

/// Максимална височина на илюстрация, като дял от височината на екрана.
///
/// ⚠ Има го, защото някои изображения в източника са високи и тесни (цели
/// иконописни пана). Без таван такова заема целия екран и четенето спира: за
/// да продължи, човек трябва да „превърти" картинката, без да е искал.
/// ⚠ Вдигнат от 0.55 на 0.72 (31.08.2026). При 0.55 всяка ПОРТРЕТНА картинка
/// (по-висока от 1:0.6) се свиваше, за да се вмести — и ширината я следваше,
/// тъй че изображението излизаше видимо по-тясно от колоната. Симптомът се
/// четеше като „картинките не се разпъват", а причината беше таванът, не
/// правилото за разтягане.
///
/// Сметнато за Honor 400 (~415×915 dp): при 0.55 картинка 300×500 излизаше
/// 302 dp вместо 375; при 0.72 се побира цяла.
const double kLivesImageMaxHeightFactor = 0.72;

/// Колко от ширината на екрана НЕ е на разположение на картинката — двата
/// странични отстъпа на четивото плюс малко въздух.
///
/// ⚠ Изважда се предварително, защото ширината се смята ТУК, а не се оставя
/// на `BoxFit`: вътре в `WidgetSpan` няма кой да наложи горна граница и
/// широка картинка би излязла извън страницата.
const double kLivesImagePageInset = 40;

// ⚠ `kLivesImageMaxUpscale` ГО НЯМА ВЕЧЕ (01.09.2026). Таванът на
// разтягането се оказа причината илюстрациите да излизат по-тесни от
// колоната — въпрос, който се връщаше няколко пъти, все с ново число (1.6,
// после 2.2), и все недостатъчно. Няма число, което да върши работа за
// всички размери в изворите; затова правилото е просто: картинката заема
// цялата ширина. Не го връщай, без потребителят изрично да поиска.

class LivesImageExtension extends HtmlExtension {
  const LivesImageExtension();

  @override
  Set<String> get supportedTags => {'img'};

  @override
  InlineSpan build(ExtensionContext context) {
    final src = context.attributes['src'];
    if (src == null || !src.startsWith('assets/')) {
      // Чужд адрес (мрежов или остатък от източника) — не се рисува.
      // Приложението чете офлайн и не тегли картинки в движение.
      return const TextSpan(text: '');
    }

    final ctx = context.buildContext!;
    final media = MediaQuery.maybeOf(ctx);
    final screenH = media?.size.height ?? 800;
    final screenW = media?.size.width ?? 400;

    // ⚠ СЪОТНОШЕНИЕТО ИДВА ОТ АТРИБУТИТЕ, не от самия файл. `Image.asset` не
    // знае размерите си, преди файлът да се зареди, а оформлението става
    // ПРЕДИ това — без предварително съотношение картинката получава нулева
    // височина и се свива до височината на текстовия ред. Отвън това
    // изглежда като тънка ивица от няколко пиксела: точно този бъг беше
    // докладван на 30.08.2026.
    //
    // Затова `05_parse.py` пренася `width`/`height` от извора (той ги дава за
    // всичките 73 картинки), а тук от тях се смята мястото предварително.
    final w = double.tryParse(context.attributes['width'] ?? '') ?? 0;
    final h = double.tryParse(context.attributes['height'] ?? '') ?? 0;

    // Ширината, с която реално разполагаме: страницата минус отстъпите ѝ.
    final available = screenW - kLivesImagePageInset;
    final maxHeight = screenH * kLivesImageMaxHeightFactor;

    double drawW = available;
    double drawH;
    if (w > 0 && h > 0) {
      drawH = available * h / w;
      // Високите пана се свиват по височина, а ширината ги следва — инак
      // едно изображение заема целия екран и четенето спира, докато човек
      // го превърти.
      if (drawH > maxHeight) {
        drawH = maxHeight;
        drawW = maxHeight * w / h;
      }
      // ⚠ БЕЗ ТАВАН НА РАЗТЯГАНЕТО (решено от потребителя, 01.09.2026).
      //
      // Тук стоеше [kLivesImageMaxUpscale] — „дребна картинка се разтяга, но
      // до предел, инак се размазва". На теория вярно; на практика точно то
      // остави илюстрациите по-тесни от колоната и въпросът се връщаше
      // отново и отново. Изображенията в изворите са 250–650 px широки, а
      // редът е ~375 dp: при таван 2.2 се засягаха тъкмо най-дребните, а
      // те и без това са малцина. Илюстрацията заема ЦЯЛАТА ширина; ако
      // някъде излезе зърнеста, това е по-малката цена от вечно недоразпъната
      // картинка.
      //
      // ⚠ Ограничението по ВИСОЧИНА отгоре ОСТАВА — то е друго нещо и пази
      // четенето от изображение, което заема целия екран.
    } else {
      // Без размери в тага — резервира се разумна кутия. Не бива да е 0.
      drawH = available * 0.66;
    }

    return WidgetSpan(
      child: Padding(
        // По-широк отстъп отдолу: под картинката обикновено стои надписът ѝ
        // („Стенопис от ХV в…") и той трябва да се чете като неин, а не като
        // начало на следващия абзац.
        padding: const EdgeInsets.only(top: 14, bottom: 6),
        child: Align(
          alignment: Alignment.center,
          child: SizedBox(
            width: drawW,
            height: drawH,
            child: Image.asset(
              src,
              fit: BoxFit.contain,
              // ⚠ Без това липсващ файл хвърля изключение при рисуване и
              // цялото житие остава празно — една липсваща картинка не бива
              // да отнася четивото със себе си.
              errorBuilder: (_, __, ___) => const SizedBox.shrink(),
            ),
          ),
        ),
      ),
    );
  }
}

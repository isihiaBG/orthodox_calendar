// ПЪЛНОТО име на всяка книга — за заглавието най-отгоре на библейското
// четиво („Матей гл.5", „Галатяни зач.214, гл.6:2-10").
//
// ⚠⚠ ИМЕТО Е РАЗГЪВАНЕ НА СЪКРАЩЕНИЕТО ОТ ЛИНКОВЕТЕ, а не трета форма.
// Правилото е на потребителя (16.09.2026): „Гал." → „Галатяни", „Мат." →
// „Матей". Така човек вижда едно и също нещо, назовано по един и същи
// начин, независимо дали чете препратка в житие или заглавие над текста.
//
// ⚠ ТУК СТОЯТ САМО РАЗЛИЧАВАЩИТЕ СЕ — 27 от 77. За останалите 50 името в
// съдържанието (`books.bg_short`) вече е точно каквото трябва: „Битие",
// „Псалтир", „2 Царства", „Премъдрост Соломонова", „Исаия". Пълен препис би
// значел 77 реда, които трябва да се поддържат съгласувани с базата — а
// разминаването би личало само на един екран.
//
// ⚠ Изрично изброени, а НЕ изведени с правило. Опитът да се махне „От "/„До "
// и да се премести числото отпред се проваля в десетина случая („От Иоана" →
// „Иоана", а трябва „Йоан"; „Иакова" → „Иаков"), а грешката би била тиха.
// В този проект засичането по име вече е струвало скъпо.
//
// ⚠ Три от тях са избрани НАРОЧНО в по-дългата си форма (потвърдено от
// потребителя):
//   1 Петрово  — не „1 Петър": послание е, не човек;
//   1 Йоаново  — не „1 Йоан": инак се бърка с евангелието „Йоан";
//   Иаков      — не „Яков": така е и в съкращението („Иак."), и в
//                българското Писание.


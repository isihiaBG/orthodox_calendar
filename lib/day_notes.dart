/// Бележка, закотвена за ДЕН ОТ СЕДМИЦАТА около неподвижен празник.
class AnchoredDayNote {
  /// Църковната дата на празника, „ММ-ДД".
  final String feast;

  /// ISO ден от седмицата (6 = събота).
  final int weekday;

  /// Преди празника (или след него).
  final bool before;
  final String text;
  const AnchoredDayNote(this.feast, this.weekday, this.before, this.text);
}

const List<AnchoredDayNote> kAnchoredDayNotes = [
  AnchoredDayNote('11-08', DateTime.saturday, true,
      'Архангелова задушница — всеобщ помен на починалите.'),
];

/// Бележките за деня, в реда: подвижни, неподвижни, закотвени.
///
/// ⚠ Отместването от Пасха се мери в UTC — същият довод като в
/// [readingAddress]: иначе смяната на лятното време реже един ден.
List<String> dayNotes(DateTime date, String churchMonthDay,
    {required bool oldStyle}) {
  final d = DateTime.utc(date.year, date.month, date.day);
  final out = <String>[];
  final fromPascha = d.difference(paschaOf(d.year)).inDays;
  out.addAll(kPaschaDayNotes[fromPascha] ?? const []);
  out.addAll(kFixedDayNotes[churchMonthDay] ?? const []);
  for (final a in kAnchoredDayNotes) {
    if (d.weekday != a.weekday) continue;
    final m = int.parse(a.feast.substring(0, 2));
    final day = int.parse(a.feast.substring(3));
    final feast = civilDateOfChurch(d.year, m, day, oldStyle: oldStyle);
    final diff = feast.difference(d).inDays;
    if (a.before ? (diff >= 1 && diff <= 7) : (diff <= -1 && diff >= -7)) {
      out.add(a.text);
    }
  }
  // ⚠ Един и същ текст не се повтаря (напр. празник, паднал се в ден с
  // подвижна бележка със същия смисъл).
  return out.toSet().toList();
}

library;

import 'readings_lookup.dart';

enum DayNoteKind { typikon, practice, custom }

class DayNote {
  final String text;
  final DayNoteKind kind;

  /// Четивото, към което сочи връзката (`tip-…`, `dni-…`, `azb-…`).
  final String slug;

  /// Дословният откъс, който се маркира.
  final String passage;

  const DayNote.typikon(this.text, this.slug, this.passage)
      : kind = DayNoteKind.typikon;
  const DayNote.practice(this.text, this.slug, this.passage)
      : kind = DayNoteKind.practice;
  const DayNote.custom(this.text)
      : kind = DayNoteKind.custom,
        slug = '',
        passage = '';

  bool get hasLink => slug.isNotEmpty && passage.isNotEmpty;
}


// cover_flow.dart
//
// Разлистване на корици по подобие на стария Cover Flow от iTunes: тесте
// изправени напред карти, от които централната стои с лице към човека, а
// съседните са завъртени навътре и застъпени една зад друга, всяка със
// своето отражение под нея.
//
// Контролът НЕ знае нищо за книги. Получава списък изображения и връща
// избраното — така утре същият механизъм може да разлиства и друго, а
// смяната на кориците не иска нито ред тук.
//
// ─── Как е устроено ────────────────────────────────────────────────────
//
// ФИЗИКАТА идва от скрит `PageView`. Свободното плъзгане с инерция и
// щракването в най-близката корица са точно неговото поведение и няма
// смисъл да се пише наново; от него се взима само числото `page` (дробно,
// напр. 4.37). Самите корици се рисуват ОТДЕЛНО, в `Stack`.
//
// ⚠ Рисуването НЕ може да стане със самия PageView. Той нарежда децата си
// по ред на индекса, тъй че корицата отдясно ляга ВЪРХУ централната —
// точно обратното на нужното. Затова редът се решава тук, по разстоянието
// до центъра (виж `_paintOrder`).
//
// ГЕОМЕТРИЯТА на всяка корица се смята от едно-единствено число: `d`,
// разстоянието ѝ до центъра в „корици" (0 = централната, +1 = първата
// вдясно). От него излизат отместването, ъгълът, мащабът и блясъкът.

import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:flutter/scheduler.dart';

/// Съотношението на кориците (ширина към височина). Томовете са 479×741.
const double kCoverAspect = 479 / 741;

// ⚠ ФИЗИКАТА НАРОЧНО Е СТАНДАРТНАТА на `PageView` (`PageScrollPhysics`):
// най-много ЕДНА корица на жест и винаги подравнено спиране.
//
// Изкушението е да се напише своя — с триене и закръгляне до най-близката
// корица, — за да може силното хвърляне да прелети няколко тома. Опитано и
// съзнателно отхвърлено (14.08.2026): тестето започва да прескача, а точно
// тук човек ИЗБИРА и ПРЕГЛЕЖДА, не пътува. Дванайсет корици не са толкова
// много, че да се бърза през тях.
//
// Мекотата НЕ идва оттам, а от догонването (виж `_follow` по-долу).

class CoverFlow extends StatefulWidget {
  /// Кориците, отляво надясно.
  final List<ImageProvider> covers;

  final int initialIndex;

  /// Викa се при СМЯНА на централната корица (докато се плъзга — при всяко
  /// прещракване, не в края на движението).
  final ValueChanged<int>? onSelected;

  /// Тап върху ЦЕНТРАЛНАТА корица. Страничните само се докарват в средата.
  final ValueChanged<int>? onOpen;

  const CoverFlow({
    super.key,
    required this.covers,
    this.initialIndex = 0,
    this.onSelected,
    this.onOpen,
  });

  @override
  State<CoverFlow> createState() => CoverFlowState();
}

class CoverFlowState extends State<CoverFlow> {
  // ── Наглед на тестето ───────────────────────────────────────────────
  //
  // Стойностите са нагласяни по око срещу оригинала. Държат се заедно и с
  // имена, защото всяка от тях се пипа поотделно при донастройване.

  /// Ъгълът, на който застават страничните корици (радиани).
  static const double _sideAngle = 1.02; // ≈ 58°

  /// Колко се смалява една странична корица.
  static const double _sideScale = 0.78;

  /// Разстояние от центъра до първата странична корица, в ширини.
  ///
  /// Определя и КОЛКО РАЗСТОЯНИЕ имат разминаващите се корици при
  /// разлистване. Стегне ли се твърде много, излизащата и влизащата се
  /// засичат в средата, докато и двете са едри. Голямата част от онзи
  /// сблъсък обаче се дължеше на бавното завъртане, не на теснотията — щом
  /// корицата почна да се отвръща веднага (виж `_turn`), разстоянието можа
  /// да се върне почти до първоначалното и разминаването стана по-близко и
  /// по-живо.
  static const double _firstGap = 0.66;

  /// Разстояние между две съседни СТРАНИЧНИ корици. Доста по-малко от
  /// [_firstGap] — така те се застъпват като тесте, вместо да се наредят
  /// като витрина. Сгъстеното тесте и по-далечното начало вървят заедно:
  /// цялото се отдръпва от централната, без да заеме повече място.
  static const double _sideGap = 0.17;

  /// Скоростта на корицата ПРЕЗ САМАТА СРЕДА, в ширини за корица разстояние
  /// (виж `_offsetFor`). Нула значи „замира с лице към човека" и прави пътя
  /// ѝ ъглест; колкото по-близо до [_firstGap], толкова по-равномерно минава
  /// покрай зрителя.
  static const double _centerSpeed = 0.56;

  // Обмислено и ОТЛОЖЕНО (14.08.2026): избързване на отиващата си корица —
  // щом подмине средата, тя леко ускорява и се дръпва от идващата. Добавка
  // `sin(π·|d|)`, различна за двете страни, тъй че иска и посоката на
  // движението. След оправянето на траекторията (виж `_centerSpeed`)
  // разминаването и без това престана да изглежда като засичане, а всяка
  // несиметрия е нов повод за трепване. Да се добави само ако при бързо
  // прелистване пак се вижда сблъсък.

  // ── Каквото зависи от ориентацията ──────────────────────────────────
  //
  // Легналият екран не е просто по-широк — той е ДРУГ изглед. Встрани има
  // място за цялото тесте, а на височина мястото е малко и не бива да се
  // харчи за отражение. Затова трите числа по-долу имат по две стойности, а
  // работната се избира при разполагането (виж build).

  /// Докъде се трупат корици встрани. Отвъд това не се рисуват — иначе
  /// далечните само ядат кадри. Легнало се показват всичките дванайсет:
  /// иначе отстрани зее празно.
  static const double _spanTall = 4.0;
  static const double _spanWide = 11.0;

  /// Каква част от полагащата се височина заема тестето. Легнало се взима
  /// всичко — там височината е тясното място.
  static const double _fillTall = 0.92;
  static const double _fillWide = 1.0;

  /// Въздух НАД тестето, дял от височината на контрола.
  ///
  /// Без него корицата опира в тавана на контрола, а легнало — направо в
  /// ъгъла на телефона. Взима се от височината ПРЕДИ да се смята корицата,
  /// тъй че е истинско поле, а не изместване на вече готово тесте.
  static const double _topAirTall = 0.05;
  static const double _topAirWide = 0.07;

  double _span = _spanTall;

  /// Полето отгоре от последното разполагане — влиза и в улучването с пръст,
  /// и в [centerCoverRect].
  double _padTop = 0;

  /// Допълнително смаляване на ВСЯКА следваща корица навътре в тестето.
  ///
  /// При оригинала всички странични са с еднакъв ръст. Тук нарочно се
  /// смаляват мъничко — 3,5% на корица — колкото окото да усети дълбочина.
  /// Разликата между първата и последната става около 10%: забележимо, ако
  /// се вгледаш, и незабележимо, ако не се вгледаш. Слезе ли под това,
  /// тестето става плоско; вдигне ли се, заприличва на стълба.
  static const double _depthShrink = 0.965;

  /// Потъмняването по навлизане в тестето — задните корици са в сянка.
  ///
  /// ⚠ Не е стъпка по корица, а ДЯЛ ОТ ПЪТЯ до последната видима. Иначе при
  /// две различни дълбочини на тестето (изправено 4, легнало 11) едната от
  /// двете задължително излиза сбъркана: с постоянна стъпка легналото опира
  /// в тавана още при петата корица и останалите шест стоят еднакво черни —
  /// точно „заден ред с една и съща тъмнина", който не искаме.
  ///
  /// Степента под 1 хвърля повечето потъмняване в началото, но оставя всяка
  /// следваща корица мъничко по-тъмна от предната чак до края.
  static const double _dimFirst = 0.16; // при първата странична
  static const double _dimMax = 0.80; // при най-задната
  static const double _dimCurve = 0.72;

  /// Силата на перспективата.
  static const double _perspective = 0.0016;

  /// Отражението: каква част от височината на корицата заема и колко ярко
  /// започва под нея. Легнало е по-късо — там всеки пиксел височина, отишъл
  /// в отражение, е пиксел, отнет от самата корица.
  static const double _reflectTall = 0.42;
  static const double _reflectWide = 0.26;
  static const double _reflectAlpha = 0.30;

  double _reflect = _reflectTall;

  /// Времеконстантата на догонването, в секунди.
  ///
  /// Тестето НЕ повтаря пръста едно към едно — то се СТРЕМИ към мястото, на
  /// което пръстът го вика, и за това време изминава около две трети от
  /// оставащото разстояние. Оттам идва мекотата: рязкото дръпване се
  /// изглажда, а щракването в края престава да е щракване.
  ///
  /// ⚠ Числото е тясно. Под 0,06 ефектът се губи и движението става право
  /// копие на пръста; над 0,20 тестето заплува подир жеста и се усеща като
  /// закъснение, а не като плавност.
  static const double _follow = 0.11;

  /// Каква част от изгледа е една корица. Решава колко пръст е нужен за една
  /// стъпка; при 1.0 се иска цял екран влачене и разлистването е мъчително.

  late final PageController _pc;
  late final Ticker _ticker;
  Duration _lastTick = Duration.zero;

  /// Мястото, на което тестето СЕ РИСУВА — догонва [_rawPage].
  ///
  /// Държи се извън състоянието нарочно: сменя се на всеки кадър и през
  /// `setState` би преизграждало и `PageView`-а, и слоя с тапа.
  late final ValueNotifier<double> _shown;

  int _index = 0;

  @override
  void initState() {
    super.initState();
    _index = widget.initialIndex.clamp(0, widget.covers.length - 1);
    _shown = ValueNotifier<double>(_index.toDouble());
    // viewportFraction решава КОЛКО пръст е нужен за една корица. При 1.0
    // се иска цял екран влачене, което прави разлистването мъчително.
    _pc = PageController(initialPage: _index, viewportFraction: 0.32);
    _pc.addListener(_wake);
    _ticker = Ticker(_tick);
  }

  @override
  void dispose() {
    _pc.removeListener(_wake);
    _ticker.dispose();
    _pc.dispose();
    _shown.dispose();
    super.dispose();
  }

  /// Събужда догонването — при всяко движение на плъзгача, включително
  /// докато инерцията след жеста още тече.
  void _wake() {
    if (!_ticker.isActive) {
      _lastTick = Duration.zero;
      _ticker.start();
    }
  }

  /// Един кадър от догонването.
  ///
  /// Изравни ли се с целта, тикерът СПИРА. Иначе екранът би се
  /// преизчертавал шейсет пъти в секунда и когато нищо не мърда.
  void _tick(Duration now) {
    final dt = _lastTick == Duration.zero
        ? 1 / 60
        : (now - _lastTick).inMicroseconds / 1e6;
    _lastTick = now;

    final target = _rawPage;
    final gap = target - _shown.value;
    if (gap.abs() < 0.0008) {
      _shown.value = target;
      _ticker.stop();
      _settle(target);
      return;
    }
    // Експоненциално догонване — еднакво при всяка честота на кадрите.
    _shown.value += gap * (1 - math.exp(-dt / _follow));
    _settle(_shown.value);
  }

  /// Кой том е „избраният" — по РИСУВАНОТО положение, не по пръста. Иначе
  /// надписът долу се сменя, преди корицата да е стигнала до средата.
  void _settle(double at) {
    final p = at.round().clamp(0, widget.covers.length - 1);
    if (p != _index) {
      setState(() => _index = p);
      widget.onSelected?.call(p);
    }
  }

  /// Където пръстът (или инерцията след него) вика тестето. Преди първото
  /// разполагане контролерът още няма размери и `page` гърми — тогава важи
  /// индексът.
  double get _rawPage {
    if (!_pc.hasClients || _pc.position.hasContentDimensions == false) {
      return _index.toDouble();
    }
    return _pc.page ?? _index.toDouble();
  }

  int get index => _index;

  /// Размерите на корицата от последното разполагане. Пазят се, за да може
  /// [centerCoverRect] да отговори, без да ги пресмята наново.
  double _lastW = 0;
  double _lastH = 0;

  /// Къде точно на ЕКРАНА стои централната корица.
  ///
  /// Нужно е на екрана домакин, за да продължи движението ѝ извън контрола —
  /// при отваряне на тома тя политва към човека и се стапя (виж
  /// library_screen.dart). Затова е публично: контролът знае геометрията си,
  /// а домакинът не бива да я пресмята повторно и да се разминава с нея.
  Rect? centerCoverRect() {
    final box = context.findRenderObject() as RenderBox?;
    if (box == null || !box.hasSize || _lastH == 0) return null;
    final origin = box.localToGlobal(Offset.zero);
    return Rect.fromCenter(
      center: origin + Offset(box.size.width / 2, _centerY(box.size.height)),
      width: _lastW,
      height: _lastH,
    );
  }

  /// Височината, на която стои средата на КОРИЦАТА (без отражението ѝ).
  ///
  /// ⚠ Тръгва от [_padTop], не от нулата. Тестето се центрира в остатъка
  /// след полето отгоре, тъй че сметка по цялата височина дава средата на
  /// контрола, а не на корицата. Разликата е половин поле и се вижда: при
  /// отваряне на том летящото копие се явяваше по-нависоко от истинската
  /// корица и тапът изглеждаше като подскок нагоре.
  double _centerY(double height) =>
      _padTop + (height - _padTop) / 2 - _lastH * _reflect / 2;

  /// Докарва корица в средата. Ползва се и отвън (напр. от долния панел).
  void animateTo(int i) {
    if (i < 0 || i >= widget.covers.length) return;
    _pc.animateToPage(i,
        duration: const Duration(milliseconds: 420), curve: Curves.easeOutCubic);
  }

  // ── Геометрията ─────────────────────────────────────────────────────

  /// Кривата на ИЗНАСЯНЕТО настрани (0→0, 1→1, с полегати краища).
  ///
  /// Оттук идва „дефилирането": корицата се измъква от тестето с ускорение,
  /// забавя се, докато застава в средата с лице към човека, и чак после
  /// потегля към другото тесте. С право пропорционален преход тя минава през
  /// центъра, без да се задържи в него, и движението прилича на плъзгаща се
  /// лента, а не на редуване на лица.
  static double _smooth(double u) => u * u * (3 - 2 * u);

  /// Докъде (в корици разстояние) корицата стига до пълното си странично
  /// положение. По-малко от 1 — извръщането свършва още преди да е стигнала
  /// гнездото си, за да не стоят две почти фронтални корици една до друга,
  /// докато се разминават.
  static const double _turnSpan = 0.8;

  /// Кривата на ОТВРЪЩАНЕТО от човека — ъгъл, ръст, дълбочина, тъмнина.
  ///
  /// ⚠ Тя ЗАДЪЛЖИТЕЛНО трябва да е полегата при нулата. Всички тези величини
  /// зависят от |d|, тъй че всяка крива с ненулев наклон в нулата прави
  /// ЧУПКА там: корицата се приближава и в същия миг тръгва назад със същата
  /// скорост, но с обратен знак. В природата предмет не сменя посоката си
  /// така — окото го чете като дръпване, и то толкова по-силно, колкото
  /// по-бързо се прелиства.
  ///
  /// Затова кривата е полегата в двата края (`_smooth`), но е СВИТА в
  /// [_turnSpan]: така отвръщането пак започва рано и корицата се отдръпва
  /// навреме от разминаването, без чупка в средата.
  static double _ease(double u) => _smooth((u / _turnSpan).clamp(0.0, 1.0));

  /// Отместване на корица спрямо центъра, в ширини на корица.
  ///
  /// Кубична крива с ЧЕТИРИ условия: минава през средата с [_centerSpeed],
  /// пристига в първото странично гнездо на [_firstGap] и точно със
  /// скоростта, с която тестето продължава нататък ([_sideGap] на корица).
  ///
  /// ⚠ Скоростта в средата НЕ е нула — и това е същината на движението.
  ///
  /// Пътят на корицата е крива в равнината „настрани / към зрителя". Ако и
  /// двете съставки замрат в средата, кривата има ВРЪХ — корицата идва
  /// напред и се връща по същия път, а окото вижда остър ъгъл. За парабола
  /// е нужно едното да има плавен връх (приближаването — виж `_ease`), а
  /// другото да минава през средата равномерно. Затова тук се пази ход, и
  /// то по-голям, отколкото в тестето: в близкия план корицата изминава
  /// повече път настрани, точно както при оригинала.
  double _offsetFor(double d) {
    final a = d.abs();
    if (a <= 1) {
      // x(u) = k₃u³ + k₂u² + k₁u
      // x(0)=0 · x'(0)=_centerSpeed · x(1)=_firstGap · x'(1)=_sideGap
      const k1 = _centerSpeed;
      const k3 = _sideGap + _centerSpeed - 2 * _firstGap;
      const k2 = 3 * _firstGap - 2 * _centerSpeed - _sideGap;
      return d.sign * (k3 * a * a * a + k2 * a * a + k1 * a);
    }
    return d.sign * (_firstGap + (a - 1) * _sideGap);
  }

  /// Редът на рисуване: най-далечните най-отдолу, централната — най-отгоре.
  List<int> _paintOrder(double page) {
    final visible = <int>[];
    for (int i = 0; i < widget.covers.length; i++) {
      if ((i - page).abs() <= _span + 0.5) visible.add(i);
    }
    visible.sort((a, b) => (b - page).abs().compareTo((a - page).abs()));
    return visible;
  }

  // ── Рисуването ──────────────────────────────────────────────────────

  Widget _cover(int i, double d, double w, double h) {
    // Ъгълът расте само в първата корица разстояние; след това стои.
    //
    // ⚠ Знакът е противоположен на очакваното от сметката с `rotateY`.
    // Меродавен е екранът: с обратния знак ВЪНШНИЯТ ръб на страничната
    // корица излиза по-близо до зрителя и тестето се скосява навътре —
    // огледално на оригинала. Тук вътрешният ръб е близкият, а корицата се
    // отдалечава навън, както е при Cover Flow.
    final t = d.clamp(-1.0, 1.0);
    // Завъртането, смаляването и потъмняването вървят ЗАЕДНО по бързата
    // крива — те са едно и също нещо: корицата се отвръща от човека.
    // Изнасянето настрани е по другата, полегатата (виж _offsetFor).
    final e = _ease(t.abs());
    final angle = t.sign * _sideAngle * e;
    final a = d.abs().clamp(0.0, _span);
    // Ръстът пада на две стъпки: осезаемо до първото странично гнездо, после
    // съвсем полека с всяка следваща корица навътре.
    final scale = (1 - (1 - _sideScale) * e) *
        math.pow(_depthShrink, math.max(a - 1, 0.0));
    final x = _offsetFor(d.clamp(-_span, _span)) * w;
    // Страничните ОТСТЪПВАТ навътре в дълбочина — иначе застъпването им
    // изглежда като изрязване с ножица, а не като тесте.
    //
    // ⚠ Знакът тук е обърнат спрямо очакваното. При перспективата на Flutter
    // (`setEntry(3, 2, +k)`) делителят е `1 + k·z`, тъй че ПОЛОЖИТЕЛНОТО z
    // отдалечава. С минус страничните корици изскачаха НАПРЕД пред
    // централната и цялото тесте изглеждаше обърнато наопаки.
    final z = e * w * 0.30;

    // Колкото по-навътре в тестето, толкова по-малко светлина стига дотам.
    // Мери се по ДЯЛА от пътя до последната видима корица, за да стигне
    // тъмнината точно до края и при плитко, и при дълбоко тесте.
    final deep = _span > 1
        ? (math.max(a - 1, 0.0) / (_span - 1)).clamp(0.0, 1.0).toDouble()
        : 0.0;
    final dim = (_dimFirst * e +
            (_dimMax - _dimFirst) * math.pow(deep, _dimCurve))
        .clamp(0.0, _dimMax)
        .toDouble();

    final m = Matrix4.identity()
      ..setEntry(3, 2, _perspective)
      ..translate(x, 0.0, z)
      ..rotateY(angle)
      ..scale(scale);

    return Transform(
      alignment: Alignment.center,
      transform: m,
      child: SizedBox(
        width: w,
        height: h * (1 + _reflect),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            _face(i, d, w, h, dim),
            _reflection(i, w, h, dim),
          ],
        ),
      ),
    );
  }

  /// Самата корица.
  ///
  /// Върху изображението ляга САМО сянката на дълбочината — равномерно
  /// потъмняване, без блясък, без градиенти и без каквото и да е рисуване по
  /// самата корица. Тя си остава такава, каквато е направена.
  Widget _face(int i, double d, double w, double h, double dim) {
    final away = d.abs().clamp(0.0, 1.0);
    return Container(
      width: w,
      height: h,
      decoration: BoxDecoration(
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.55 - 0.25 * away),
            blurRadius: 24 - 10 * away,
            spreadRadius: 1,
            offset: Offset(0, 10 - 4 * away),
          ),
        ],
      ),
      child: Stack(
        fit: StackFit.expand,
        children: [
          Image(image: widget.covers[i], fit: BoxFit.fill),
          if (dim > 0.001)
            ColoredBox(color: Colors.black.withValues(alpha: dim)),
        ],
      ),
    );
  }

  /// Отражението: долната част на корицата, обърната надолу и избледняваща.
  ///
  /// ⚠ Обръщането става ВЪТРЕ в собствената си кутия (`Transform.scale` с
  /// отрицателно Y върху дете с точната височина), а НЕ с опора `topCenter`
  /// върху целия образ. При втория начин обърнатото копие се изкачва НАД
  /// опората и ляга върху самата корица — отдолу празно, а върху корицата
  /// стои обърнат наопаки текст.
  Widget _reflection(int i, double w, double h, double dim) {
    final visible = h * _reflect;
    // Маската слиза ПОД изрязването с няколко пиксела — виж защо по-долу.
    const bleed = 3.0;
    final masked = visible + bleed;

    return ClipRect(
      clipBehavior: Clip.antiAlias,
      child: SizedBox(
        width: w,
        height: visible,
        // ⚠ ТУК Е ЦЕЛИЯТ ФОКУС С ЖЪЛТИТЕ ТОЧКИ ПО ДОЛНИЯ РЪБ.
        //
        // `ShaderMask` маскира САМО правоъгълника със своя собствен размер.
        // Детето вътре е `OverflowBox`, който рисува целия образ — над два
        // пъти по-висок от отражението. Всичко под ръба на маската остава
        // НЕМАСКИРАНО, тоест напълно непрозрачно, и единственото, което го
        // спира, е `ClipRect`. Стоят ли двата ръба на едно и също място,
        // последният ред пиксели хваща половин покритие от непрозрачното
        // злато отдолу и се вижда като накъсана чертичка.
        //
        // Затова маската се прави по-висока от изрязването: ръбът на
        // изрязването пада вътре в напълно прозрачната ѝ част и няма какво
        // да покаже.
        child: OverflowBox(
          alignment: Alignment.topCenter,
          minHeight: masked,
          maxHeight: masked,
          child: SizedBox(
            width: w,
            height: masked,
            child: ShaderMask(
              blendMode: BlendMode.dstIn,
              shaderCallback: (rect) => LinearGradient(
                begin: Alignment.topCenter,
                end: Alignment.bottomCenter,
                colors: [
                  Colors.white.withValues(alpha: _reflectAlpha),
                  Colors.transparent,
                  Colors.transparent,
                ],
                // Прозрачността се стига още преди видимия ръб; остатъкът до
                // дъното на маската е чиста прозрачност.
                stops: [0.0, visible * 0.9 / masked, 1.0],
              ).createShader(rect),
              // Целият образ, обърнат, подравнен с ГОРНИЯ ръб: така до
              // корицата застава нейният долен край, а надолу се показва все
              // по-горното — точно както в огледало.
              child: OverflowBox(
                alignment: Alignment.topCenter,
                minHeight: h,
                maxHeight: h,
                child: Transform.scale(
                  scaleY: -1,
                  child: SizedBox(
                    width: w,
                    height: h,
                    // Потъмняването е ВЪТРЕ в маската — така то избледнява
                    // заедно с отражението, вместо да го зачерни изведнъж.
                    child: Stack(
                      fit: StackFit.expand,
                      children: [
                        Image(image: widget.covers[i], fit: BoxFit.fill),
                        if (dim > 0.001)
                          ColoredBox(color: Colors.black.withValues(alpha: dim)),
                      ],
                    ),
                  ),
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }

  /// Коя корица е под пръста. Обхожда се отгоре надолу по реда на
  /// рисуване — иначе тапът върху видимата ивица на съседна корица би
  /// попаднал в тази под нея.
  int? _hitTest(Offset local, Size size, double w, double h) {
    // По РИСУВАНОТО положение — пръстът улучва това, което вижда.
    final page = _shown.value;
    final cx = size.width / 2;
    // Със същата сметка, с която се и рисува — включително полето отгоре.
    final cy = _padTop + (size.height - _padTop) / 2;
    final order = _paintOrder(page).reversed; // отгоре надолу
    for (final i in order) {
      final d = i - page;
      final t = d.clamp(-1.0, 1.0);
      // Същата крива, с която се и рисува — иначе пръстът улучва едно, а на
      // екрана стои друго.
      final e = _ease(t.abs());
      final scale = 1 - (1 - _sideScale) * e;
      // Завъртяната корица заема по-тясна ивица: cos(ъгъла).
      final vw = w * scale * math.cos(e * _sideAngle).abs();
      final vh = h * scale;
      final x = cx + _offsetFor(d.clamp(-_span, _span)) * w;
      final rect = Rect.fromCenter(
        center: Offset(x, cy - h * _reflect / 2),
        width: math.max(vw, 12),
        height: vh,
      );
      if (rect.contains(local)) return i;
    }
    return null;
  }

  @override
  Widget build(BuildContext context) {
    return LayoutBuilder(
      builder: (context, c) {
        // Изборът на трите „ориентационни" стойности става ТУК, при
        // разполагането, защото зависи от действителните размери, а не от
        // ориентацията на устройството: контролът може да заема половин
        // екран изправено и цял екран легнало.
        final wide = c.maxWidth > c.maxHeight;
        _span = wide ? _spanWide : _spanTall;
        _reflect = wide ? _reflectWide : _reflectTall;

        _padTop = c.maxHeight * (wide ? _topAirWide : _topAirTall);

        // Останалата височина се дели между корицата и отражението ѝ.
        final deck = c.maxHeight - _padTop;
        final h = deck / (1 + _reflect) * (wide ? _fillWide : _fillTall);
        final w = h * kCoverAspect;
        final size = Size(c.maxWidth, c.maxHeight);
        _lastW = w;
        _lastH = h;

        return Stack(
          children: [
            // Долният слой е физиката: невидим PageView, който поема
            // плъзгането и дава инерцията и залепването.
            PageView.builder(
              controller: _pc,
              itemCount: widget.covers.length,
              itemBuilder: (_, __) => const SizedBox.expand(),
            ),
            // Върху него — самото тесте, което не пипа събития.
            //
            // ⚠ Positioned.fill е задължително. Без него вътрешният Stack
            // получава свободни ограничения, свива се до най-голямото си дете
            // и застава в ГОРНИЯ ЛЯВ ъгъл — централната корица се озовава
            // залепена вляво, а тестето изглежда разсипано.
            Positioned.fill(
              child: IgnorePointer(
                child: Padding(
                  // Полето отгоре. Тестето се центрира в ОСТАНАЛОТО, тъй че
                  // въздухът застава изцяло горе, а не се дели с долния ръб.
                  padding: EdgeInsets.only(top: _padTop),
                  child: ValueListenableBuilder<double>(
                    valueListenable: _shown,
                    builder: (context, page, _) => Stack(
                      alignment: Alignment.center,
                      children: [
                        for (final i in _paintOrder(page))
                          _cover(i, i - page, w, h),
                      ],
                    ),
                  ),
                ),
              ),
            ),
            // Тапът: страничната корица се докарва в средата, централната
            // се отваря. Слоят е прозрачен за влачене — то отива при
            // PageView-а отдолу.
            Positioned.fill(
              child: GestureDetector(
                behavior: HitTestBehavior.translucent,
                onTapUp: (e) {
                  final hit = _hitTest(e.localPosition, size, w, h);
                  if (hit == null) return;
                  if (hit == _index) {
                    widget.onOpen?.call(hit);
                  } else {
                    animateTo(hit);
                  }
                },
              ),
            ),
          ],
        );
      },
    );
  }
}

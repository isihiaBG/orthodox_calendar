// Разликата между юлианския и григорианския календар за дадена година.
//
// ⚠ ДНЕС Е 13 ДНИ, НО НЕ ЗАВИНАГИ. От 1 март 2100 г. става 14. Досега тя
// стоеше като закована „13" на шест места в кода; генераторът обаче отдавна
// я смята правилно (`paschalion.julian_gregorian_offset` в
// tools/calendar_gen/). Оставено както беше, приложението и базата щяха да се
// разминат тихо — базата с 14, надписът с 13.
int julianOffset(int year) {
  // Броят пропуснати високосни години в григорианския календар спрямо
  // юлианския: вековете, които не се делят на 400.
  final c = year ~/ 100;
  return c - c ~/ 4 - 2;
}

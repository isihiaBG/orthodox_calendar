// style_dates.dart
//
// Превръщането между ГРАЖДАНСКА и ЦЪРКОВНА дата — на едно място.
//
// ⚠⚠ КАЛЕНДАРНО ИЗВАЖДАНЕ, НЕ `Duration`. Това е цялата причина този файл да
// съществува.
//
// `date.subtract(const Duration(days: 13))` работи с АБСОЛЮТНО време. Щом
// прозорецът от 13 дни съдържа смяната на лятното часово време (в България —
// последната неделя на март), резултатът излиза с един час по-къс и пада в
// 23:00 на ПРЕДИШНИЯ ден. Оттам църковната дата се разминава с единица.
//
// Мерено за 2026 (лятното време почва на 29 март):
//
//     граждански   с Duration        по календар
//     29.03        16.03 00:00       16.03   ✅
//     30.03        16.03 23:00  ⚠    17.03
//     31.03        17.03 23:00  ⚠    18.03
//     11.04        28.03 23:00  ⚠    29.03
//     12.04        30.03 00:00       30.03   ✅
//
// ⚠ Затова грешката трае ТОЧНО 13 дни — толкова, колкото отместването
// прескача смяната. После се оправя сама и изглежда като случайност.
// (Забелязана от потребителя, 17.09.2026: „грешка с единица от 31 март до
// 11 април, и само в дневния изглед".)
//
// ⚠ Месечният изглед не страдаше, защото пресъздаваше датата през
// `DateTime.utc(...)` преди изваждането — UTC няма лятно време. Това е
// работело по случайност, не по замисъл, и затова вече минава оттук.
//
// ⚠⚠ СЪЩОТО СЕМЕЙСТВО ГРЕШКА Е ПЛАТЕНО ВЕЧЕ ВЕДНЪЖ: `difference().inDays`
// между МЕСТНИ дати през смяната даваше 42 вместо 43 и целият Триод излизаше
// седмица напред (виж CLAUDE.md). Тогава е поправено само на онова място.

import 'paschalion_offset.dart';

/// Църковната (юлианска) дата на гражданския ден.
///
/// ⚠ `DateTime(y, m, d - 13)` е безопасно: Dart нормализира отрицателния ден
/// сам („1 април − 13" → 19 март), а конструирането не минава през
/// часова аритметика.
DateTime toChurchDate(DateTime civil) =>
    DateTime(civil.year, civil.month, civil.day - julianOffset(civil.year));

/// Обратното — гражданската дата на църковния ден.
DateTime toCivilDate(DateTime church) =>
    DateTime(church.year, church.month, church.day + julianOffset(church.year));

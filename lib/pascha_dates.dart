// pascha_dates.dart
//
// Живите дати в четивата — „⟦пасха+7⟧" се превръща в истинската дата.
//
// ⚠⚠ ЗАЩО ИЗОБЩО. Сказанието за Великден носи таблица с неделите след
// Пасха, а страницата, от която е преведено, е писана за ЕДНА година: там
// пише „Антипасха – 9 май". Закована, тази таблица лъже всяка следваща
// година. Затова в текста стои отместване спрямо Пасха, а датата се смята
// ПРИ ВСЯКО ОТВАРЯНЕ.
//
// ⚠ Същият похват вече се ползва в справочника (`⟦пост⟧` в
// reference_text.dart) — там също текстът зависи от деня, в който се чете.
//
// ⚠ Връзките са по същия начин относителни: „day://+7" се разгъва тук, за
// да не може надписът и адресът да се разминат.
library;

import 'church_dates.dart';
import 'readings_lookup.dart';

// ⚠ Имената на месеците живеят в church_dates.dart — там се решава КАК се
// изписва дата. Тук се решава само КОЯ е датата.
final RegExp _placeholder = RegExp(r'⟦пасха([+-]\d+)⟧');
final RegExp _relLink = RegExp(r'day://([+-]\d+)');

/// Годината, спрямо чиято Пасха се смятат отместванията — ТЕКУЩАТА.
///
/// ⚠⚠ ДВА ОТХВЪРЛЕНИ ВАРИАНТА, и двата по-лоши:
///
/// 1. `AppSettings.flashDate` — първото, което пробвах, и е ПРОСТО ГРЕШНО:
///    то е СИГНАЛ за мигане на ред, не „отвореният ден". Празно е през
///    повечето време и понякога носи стара стойност, тъй че датите щяха да
///    са непредвидими.
/// 2. Годината, разглеждана в „Празници" — изглежда по-умно, но сказанието
///    се отваря от пет различни места и само едно от тях има такава
///    година. Човек, въвел 2045 в празниците, после отваря същото четиво
///    от календара и вижда други числа — едно и също четиво с две лица.
///
/// Текущата година е ЕДНА за всички пътища и е това, което човек очаква да
/// види по подразбиране. (Решено с потребителя, 19.09.2026.)
int _year() => DateTime.now().year;

DateTime dateForOffset(int days, [int? year]) =>
    paschaOf(year ?? _year()).add(Duration(days: days));

/// Заменя запушалките и относителните адреси в готовото HTML.
String expandPaschaDates(String html,
    {int? year, bool? oldStyle, bool? oldFirst}) {
  final y = year ?? _year();
  // ⚠⚠ ИЗПИСВАТ СЕ ПО ОБЩИЯ СТАНДАРТ (church_dates.dart), а не като гола
  // гражданска дата. Дотук сказанието казваше „19 април", а календарът на
  // човека, ако е по стар стил, показваше онзи ден като 6 април — тоест
  // четивото сочеше ден, който в неговия календар изглежда друг.
  // (Докладвано от потребителя, 20.09.2026.)
  var s = html.replaceAllMapped(
      _placeholder,
      (m) => civilDateHtml(dateForOffset(int.parse(m.group(1)!), y),
          oldStyle: oldStyle, oldFirst: oldFirst));
  s = s.replaceAllMapped(_relLink, (m) {
    final d = dateForOffset(int.parse(m.group(1)!), y);
    final mm = d.month.toString().padLeft(2, '0');
    final dd = d.day.toString().padLeft(2, '0');
    return 'day://${d.year}-$mm-$dd';
  });
  return s;
}

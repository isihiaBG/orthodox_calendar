  final String author;
  final String about; // едно-две изречения

  /// Кратко име — над групата в списъка с отметки (bookmarks_all.dart).
  /// Дотук там стоеше името на ФАЙЛА — „razgovori" (бележка на потребителя,
  /// 08.10.2026).
